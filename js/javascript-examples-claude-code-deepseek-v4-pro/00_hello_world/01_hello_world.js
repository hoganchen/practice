/**
 * ============================================================================
 * 知识点：Hello World —— 最小的可运行 JavaScript 程序
 * ============================================================================
 *
 * 【所属分类】00_hello_world —— 起步
 * 【难度等级】入门
 * 【前置知识】无，这是第一个示例
 *
 * 【知识点说明】
 *
 * 1. JavaScript 是什么
 *    JavaScript（简称 JS）是一门动态类型、解释执行（现代引擎会 JIT 编译）、
 *    支持函数式与面向对象两种范式的编程语言。它最初只运行在浏览器里，
 *    后来有了 Node.js，JS 也能脱离浏览器运行在服务端、命令行、桌面端和嵌入式设备上。
 *
 * 2. 本仓库的运行环境
 *    本仓库绝大多数示例使用 Node.js 运行。Node.js 是把 V8 引擎（Chrome 的 JS 引擎）
 *    剥离出来、再加上文件系统/网络等能力后形成的运行时。
 *    因此：JS 是语言，Node.js 是让这门语言能在浏览器之外跑起来的运行环境。
 *
 * 3. console.log —— 最简单的输出方式
 *    console.log() 是内置的调试输出函数。它接收任意个参数，用空格拼接后
 *    打印到标准输出（stdout），并自动换行。
 *    注意它并不是语言的一部分，而是宿主环境（Node.js / 浏览器）提供的全局 API。
 *
 * 4. 分号
 *    JS 有自动分号插入（ASI）机制，多数情况下不写分号也能正常工作。
 *    但 ASI 的规则有反直觉的边界情况，本仓库统一显式书写分号，这也是主流代码风格。
 *
 * 5. 大小写敏感
 *    JS 严格区分大小写：console 与 Console 是两个完全不同的标识符。
 *
 * 【运行方法】
 *
 *   前置：安装 Node.js 18 或更高版本（本仓库用 Node 24 验证）。
 *         在仓库根目录执行 npm install 安装依赖。
 *
 *   方式一（推荐）：在仓库根目录执行
 *     node 00_hello_world/01_hello_world.js
 *
 *   方式二：也可以直接双击运行，或用编辑器（如 VS Code）的"运行"按钮。
 *
 * 【预期输出】
 *   依次打印 5 行文本，展示 console.log 的基础用法。
 * ============================================================================
 */

// ---------------------------------------------------------------------------
// 1. 最经典的一行
// ---------------------------------------------------------------------------

// console 是宿主环境注入的全局对象，log 是它上面的一个方法。
// 字符串可以用单引号、双引号或反引号包裹，三者在这里等价。
console.log('Hello, World!');

// ---------------------------------------------------------------------------
// 2. 一次打印多个值
// ---------------------------------------------------------------------------

// console.log 可以接收任意多个参数，打印时用空格分隔。
// 数字、布尔值、字符串可以混在一起输出，console 会自动做字符串转换。
console.log('数字：', 42, '布尔值：', true);

// ---------------------------------------------------------------------------
// 3. 输出算式的结果
// ---------------------------------------------------------------------------

// 参数会先被求值，再打印求值结果。
// 注意 1 + 2 没有引号，所以是算术运算，结果是 3，而不是字符串 "1 + 2"。
console.log('1 + 2 =', 1 + 2);

// 加了引号就变成字符串拼接，"1" 与 "2" 相接得到 "12"。
// 这个"加号既能做加法又能拼字符串"的特性，是初学者最常踩的坑之一。
console.log('"1" + "2" =', '1' + '2');

// ---------------------------------------------------------------------------
// 4. 程序是自上而下执行的
// ---------------------------------------------------------------------------

// JS 是命令式语言，语句按书写顺序从上到下依次执行。
// 所以下面这行一定在最后打印。
console.log('程序结束，共执行完毕。');
