/**
 * ============================================================================
 * 知识点：微任务与宏任务的优先级 —— queueMicrotask 与执行顺序的真相
 * ============================================================================
 *
 * 【所属分类】18_async —— 异步编程
 * 【难度等级】高级
 * 【前置知识】18_async/02_event_loop_basics.js、18_async/07_async_await_basics.js
 *
 * 【知识点说明】
 *
 * 1. 是什么
 *    - 宏任务（macrotask）：setTimeout、setInterval、setImmediate、I/O 回调。
 *      事件循环每轮只从队列里取**一个**执行。
 *    - 微任务（microtask）：Promise 的 then/catch/finally 回调、
 *      queueMicrotask、await 后面的代码、MutationObserver。
 *      每执行完一个宏任务（以及每段同步代码），就把微任务队列**彻底清空**。
 *    所以"微任务永远比下一个宏任务先执行"。
 *
 * 2. 为什么需要
 *    微任务是"本轮任务的收尾工作"。把 Promise 回调放进微任务队列，
 *    是为了保证"状态变更后马上执行回调"，而不必等到下一个定时器轮次。
 *    理解这个优先级，才能解释：为什么 await 之后的代码比 setTimeout(0) 快；
 *    为什么连续多个 Promise 回调会一口气跑完。
 *    在浏览器里，微任务还会在渲染前清空——这正是"改完数据立刻读布局"
 *    能拿到新值的原因。
 *
 * 3. 核心语法要点
 *    - queueMicrotask(fn) 是唯一"显式"往微任务队列塞函数的 API。
 *    - Promise.then 的回调本质上就是这个 API 的语法糖。
 *    - async 函数里 await 之后的代码，等价于"挂在 then 回调里的代码"，
 *      所以同样属于微任务。
 *    - 微任务可以产生新的微任务，它们会在本轮全部执行完（有饥饿风险）。
 *
 * 4. 常见陷阱
 *    - 以为 setTimeout(0) 和 Promise.then 差不多快：实际差一整个轮次。
 *    - 在微任务里建定时器，然后又依赖"定时器比微任务快"。
 *    - 微任务里无限递归：宏任务永远得不到执行机会。
 *
 * 【运行方法】
 *   在仓库根目录执行：node 18_async/12_microtask_vs_macrotask.js
 *
 * 【预期输出】
 *   带编号的日志，逐步展示"微任务整队清空 → 才轮到下一个宏任务"的规律。
 * ============================================================================
 */

// ---------------------------------------------------------------------------
// 1. 最直观的一次对比
// ---------------------------------------------------------------------------

console.log('--- 1. 微任务 vs 宏任务：谁先执行 ---');

console.log('1 [同步] 脚本开始');

setTimeout(() => {
  console.log('5 [宏任务] setTimeout(0)');
}, 0);

Promise.resolve().then(() => {
  console.log('3 [微任务] Promise.then');
});

queueMicrotask(() => {
  console.log('4 [微任务] queueMicrotask（与 Promise 同一个队列）');
});

console.log('2 [同步] 脚本结束');
// 顺序：1、2（同步）→ 3、4（微任务，一轮清空）→ 5（宏任务）

// ---------------------------------------------------------------------------
// 2. 两个宏任务之间，微任务会整队插进来
// ---------------------------------------------------------------------------
//
// 下面几节统一放进一个 async 流程里依次 await，这样各节的输出不会互相穿插
// （这本身就是 async/await 相比散落的定时器更好用的证据）。

const delay = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

async function runSections() {
  // -------------------------------------------------------------------------
  // 2. 两个宏任务之间，微任务会整队插进来
  // -------------------------------------------------------------------------

  console.log('\n--- 2. 宏任务之间插进来的微任务 ---');

  setTimeout(() => {
    console.log('  宏任务 A 开始');
    queueMicrotask(() => console.log('    微任务：A 里注册的'));
    Promise.resolve().then(() => console.log('    微任务：A 里的 Promise.then'));
    console.log('  宏任务 A 结束');
  }, 0);

  setTimeout(() => {
    console.log('  宏任务 B 开始（A 的微任务都已清空，才轮到我）');
    console.log('  宏任务 B 结束');
  }, 0);

  console.log('  两个宏任务已注册（A、B 谁先打印由注册顺序决定）');
  await delay(30); // 等它们跑完，再进入下一节

  // -------------------------------------------------------------------------
  // 3. await 之后的代码就是微任务
  // -------------------------------------------------------------------------

  console.log('\n--- 3. await 后面的代码属于微任务 ---');

  async function demo() {
    console.log('  A [同步] async 函数体开始');
    await null; // await 任何值都会让出一次执行权
    // 下面这行就相当于写在了 then 回调里，属于微任务
    console.log('  C [微任务] await 之后的代码');
  }

  demo();
  console.log('  B [同步] demo() 调用之后');

  // 再插一个"和微任务抢先后"的宏任务
  setTimeout(() => console.log('  D [宏任务] setTimeout(0)（永远排在 C 之后）'), 0);
  // 顺序：A → B → C（微任务）→ D（宏任务）
  await delay(30);

  // -------------------------------------------------------------------------
  // 4. 一批微任务的顺序：按注册顺序，新产生的排到队尾
  // -------------------------------------------------------------------------

  console.log('\n--- 4. 同一轮里微任务的顺序 ---');

  Promise.resolve().then(() => {
    console.log('  微任务 1');
    // 在微任务内部再注册微任务：它排在本轮队尾，但仍然属于本轮
    Promise.resolve().then(() => console.log('  微任务 1 产生的新微任务（1.1）'));
  });
  Promise.resolve().then(() => console.log('  微任务 2'));
  Promise.resolve().then(() => console.log('  微任务 3'));

  setTimeout(() => console.log('  宏任务：要等所有微任务（含 1.1）都跑完'), 0);
  // 顺序：1、2、3、1.1 → 宏任务
  // 注意 1.1 排在 3 之后，因为它是"插到队尾"的。
  await delay(30);

  // -------------------------------------------------------------------------
  // 5. queueMicrotask 的实用场景
  // -------------------------------------------------------------------------

  console.log('\n--- 5. queueMicrotask 的实用场景 ---');

  // 场景：状态已经改了，但希望"通知观察者"这件事发生在当前同步代码之后、
  // 下一个宏任务之前。这正是微任务最合适的时机。
  const state = { value: 0, listeners: [] };

  function setValue(v) {
    state.value = v;
    // 用微任务代替"同步立刻通知"，避免在调用方的同步流程里插入副作用
    queueMicrotask(() => {
      console.log(`  [通知] 值已变为 ${state.value}，通知 ${state.listeners.length} 个监听器`);
      for (const fn of state.listeners) fn(state.value);
    });
  }

  state.listeners.push((v) => console.log('  [监听器 1] 收到：', v));
  state.listeners.push((v) => console.log('  [监听器 2] 收到：', v));

  setValue(1);
  setValue(2); // 同步调用两次，两次通知都会排进微任务队列
  console.log('  同步代码：setValue 已调用两次（但通知还没发生）');
  // 注意输出里两次通知读到的都是 2——因为通知回调执行时，
  // state.value 已经变成了最后写入的 2（这是"读取最新值"的典型行为，
  // 想要快照就得在注册微任务时把 v 捕获下来）。
  await delay(30);

  // -------------------------------------------------------------------------
  // 6. 饥饿风险：微任务无限产生会拖住宏任务
  // -------------------------------------------------------------------------

  console.log('\n--- 6. 微任务饥饿 ---');

  let n = 0;
  function loop() {
    n++;
    if (n <= 3) {
      queueMicrotask(loop); // 每次都在队尾再排一个
      console.log(`  微任务链第 ${n} 层`);
    }
  }
  loop();

  await new Promise((resolve) => {
    setTimeout(() => {
      console.log('  宏任务终于执行了（如果上面不设上限，它永远等不到）');
      resolve();
    }, 0);
  });
}

await runSections();

console.log('\n示例结束。');
