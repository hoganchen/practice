/**
 * ============================================================================
 * 知识点：事件循环 —— 调用栈、宏任务队列与微任务队列
 * ============================================================================
 *
 * 【所属分类】18_async —— 异步编程
 * 【难度等级】进阶
 * 【前置知识】18_async/01_synchronous_vs_asynchronous.js
 *
 * 【知识点说明】
 *
 * 1. 是什么
 *    事件循环（event loop）是 JS 运行时调度异步任务的机制。三个关键角色：
 *      - 调用栈（call stack）：当前正在执行的同步代码，清空之前别的都不跑。
 *      - 宏任务队列（macrotask queue）：setTimeout、setInterval、
 *        setImmediate、I/O 回调等；事件循环每轮只取出**一个**执行。
 *      - 微任务队列（microtask queue）：Promise.then/catch/finally、
 *        queueMicrotask、MutationObserver；每轮宏任务结束后**全部清空**。
 *    Node.js 另有 process.nextTick 队列，它在"同步代码跑完后"最先处理。
 *
 * 2. 为什么需要
 *    单线程要同时处理"定时器到期""网络数据回来了""用户点了按钮"这些事，
 *    就必须有一套明确的排队规则。理解这套规则，才能解释"为什么这行打印得
 *    比那行晚"，也才能避免回调顺序错误和界面卡顿。
 *
 * 3. 核心语法要点（执行顺序口诀）
 *    ① 同步代码（调用栈清空）
 *    ② process.nextTick 队列（Node 特有）
 *    ③ 微任务队列（全部清空，新产生的微任务也在本轮清完）
 *    ④ 取一个宏任务执行 → 回到 ②，如此循环
 *    微任务优先于宏任务，是这套规则里最重要的一条。
 *
 * 4. 常见陷阱
 *    - 认为 setTimeout(fn, 0) 比 Promise.then 早：恰好相反，微任务优先。
 *    - 在微任务里不断产生新微任务，会"饿死"宏任务队列（见第 6 节）。
 *    - 在 ESM 顶层（本仓库就是 ESM）观察 nextTick 与 Promise 的先后，
 *      会得到与 CommonJS 相反的结论——因为 ESM 的模块体本身是在一个
 *      Promise 任务里被求值的。本篇第 3 节专门演示并解释了这一点。
 *
 * 【运行方法】
 *   在仓库根目录执行：node 18_async/02_event_loop_basics.js
 *
 * 【预期输出】
 *   用带编号的日志逐条展示同步代码、nextTick、微任务、宏任务的执行顺序，
 *   全过程约 90ms。
 * ============================================================================
 */

// ---------------------------------------------------------------------------
// 1. 先说清楚三个队列
// ---------------------------------------------------------------------------

console.log('--- 1. 三个队列的角色 ---');
console.log('同步代码（调用栈）         ：现在就在跑，优先级最高');
console.log('process.nextTick 队列      ：Node 特有，调用栈一空就处理');
console.log('微任务队列（Promise.then） ：每轮宏任务结束后全部清空');
console.log('宏任务队列（setTimeout 等） ：每轮只取一个，最慢');
console.log('下面用真实的定时器把顺序跑一遍，请对照输出阅读。');

// ---------------------------------------------------------------------------
// 2. 在宏任务内部观察教科书顺序
// ---------------------------------------------------------------------------

// 为什么要把演示放进一个 setTimeout 回调里？
// 因为在"宏任务内部"观察时，执行顺序是最标准、最稳定的：
//   同步 → nextTick → 微任务 → 下一个宏任务
setTimeout(() => {
  console.log('\n--- 2. 宏任务内部的完整顺序 ---');

  console.log('1 [同步] 回调开始');

  // 队列类回调先注册。注意：先注册不代表先执行，
  // 执行顺序由"队列优先级"决定，而不是注册顺序。
  process.nextTick(() => {
    console.log('3 [nextTick] 比微任务还优先');
  });

  Promise.resolve().then(() => {
    console.log('4 [微任务] Promise.then');
  });

  queueMicrotask(() => {
    console.log('5 [微任务] queueMicrotask（与 Promise 同一个队列，按注册顺序）');
  });

  setTimeout(() => {
    console.log('6 [宏任务] 下一个宏任务，只能等这一轮彻底清空');
  }, 0);

  console.log('2 [同步] 回调结束');

  // 输出顺序：1 → 2（同步）→ 3（nextTick）→ 4 → 5（微任务）→ 6（下一个宏任务）。
  // 关键理解：6 虽然在同步代码里就注册好了（延迟还是 0），
  // 但它必须排在微任务后面，因为微任务队列要先清空。
}, 5);

// ---------------------------------------------------------------------------
// 3. ESM 顶层的差异：nextTick 反而在 Promise 之后
// ---------------------------------------------------------------------------

// 本仓库的 package.json 设置了 "type": "module"，所有文件都是 ESM。
// 在 ESM 里，模块体本身是在一个 Promise 任务（模块作业）中被求值的，
// 因此"同步代码结束"这个时间点落在 Promise 微任务的上下文里：
// 先注册的 Promise 回调会先执行，nextTick 反而排到后面。
// （如果你把同样的代码放进 .cjs 文件，顺序会反过来。）
setTimeout(() => {
  console.log('\n--- 3. ESM 顶层：Promise 先于 nextTick ---');

  process.nextTick(() => {
    console.log('B [nextTick] 在 ESM 顶层里排在后面');
  });

  Promise.resolve().then(() => {
    console.log('A [微任务] 在 ESM 顶层里反而排在前面');
  });

  console.log('同步代码：先注册 nextTick，再注册 Promise.then');
  console.log('（真正的输出顺序在上面两行之后，请观察 A 与 B 谁先）');
}, 20);

// ---------------------------------------------------------------------------
// 4. 每执行完一个宏任务，微任务队列就被清空
// ---------------------------------------------------------------------------

setTimeout(() => {
  console.log('\n--- 4. 宏任务结束后立即清空微任务 ---');

  setTimeout(() => {
    console.log('宏任务 A：开始');
    Promise.resolve().then(() => {
      console.log('  微任务：A 里注册的（A 一结束就执行，不会等到 B）');
    });
    console.log('宏任务 A：结束');
  }, 0);

  setTimeout(() => {
    console.log('宏任务 B：开始（与 A 同为 0ms，但在 A 之后注册）');
  }, 0);

  console.log('两个 0ms 宏任务已注册，它们要等当前这个宏任务结束才轮得到');
}, 40);

// ---------------------------------------------------------------------------
// 5. 定时器之间的顺序：先比到期时间，再比注册顺序
// ---------------------------------------------------------------------------

setTimeout(() => {
  console.log('\n--- 5. 定时器之间的顺序 ---');

  setTimeout(() => console.log('  定时器：延迟 10ms（后注册，但延迟小）'), 10);
  setTimeout(() => console.log('  定时器：延迟 20ms（先注册，但延迟大）'), 20);
  setTimeout(() => console.log('  定时器：延迟 20ms（与上一个同延迟，按注册顺序排后）'), 20);
  console.log('  三个定时器已注册：10ms、20ms、20ms');
}, 60);

// ---------------------------------------------------------------------------
// 6. 微任务可以插队，但会饿死宏任务
// ---------------------------------------------------------------------------

setTimeout(() => {
  console.log('\n--- 6. 微任务不断插队会饿死宏任务 ---');

  setTimeout(() => {
    console.log('  宏任务 C：终于轮到我了');
  }, 0);

  let depth = 0;
  function scheduleMicrotask() {
    if (depth >= 4) return; // 必须设上限，否则宏任务 C 永远跑不到
    depth++;
    queueMicrotask(() => {
      console.log(`  微任务链：第 ${depth} 层`);
      scheduleMicrotask(); // 在微任务里再产生新的微任务
    });
  }
  scheduleMicrotask();
  console.log('  已注册 5 层微任务链和 1 个宏任务 C');
  // 观察：4 层微任务全部打印完，宏任务 C 才执行。
  // 因为微任务队列会被"彻底清空"——新产生的微任务排在本轮末尾，
  // 但仍然属于本轮。若不设上限，C 将永远得不到执行机会。
}, 75);

// ---------------------------------------------------------------------------
// 7. setImmediate 属于另一个阶段
// ---------------------------------------------------------------------------

setTimeout(() => {
  console.log('\n--- 7. setImmediate 与 check 阶段 ---');

  // setImmediate 的回调排在事件循环的 check 阶段，setTimeout 排在 timers 阶段。
  // 在"主模块里"比较两者顺序是不可靠的（Node 官方明确说不保证），
  // 但在"定时器回调内部"注册时顺序是确定的：本轮先跑完 timers，
  // 紧接着到 check 阶段执行 setImmediate；而新注册的 setTimeout(0)
  // 必须等下一轮的 timers 阶段。所以 setImmediate 一定先打印。
  setTimeout(() => {
    console.log('  内层 setTimeout(0)：要等下一轮的 timers 阶段');
    console.log('\n示例结束。');
  }, 0);

  setImmediate(() => {
    console.log('  内层 setImmediate：同一轮的 check 阶段，先执行');
  });

  console.log('  两个内层回调都已注册（它们都还没执行）');
}, 90);
