/**
 * ============================================================================
 * 知识点：三元运算符 ?: 与逗号运算符 ,
 * ============================================================================
 *
 * 【所属分类】04_operators —— 运算符与表达式
 * 【难度等级】入门
 * 【前置知识】04_operators/03_comparison.js
 *
 * 【知识点说明】
 *
 * 1. 是什么
 *    【三元运算符（条件运算符）】
 *      `条件 ? 值A : 值B` 是 JS 里唯一需要三个操作数的运算符：
 *      条件为真值取"值A"，否则取"值B"。它是**表达式**，不是语句，
 *      所以能直接写进赋值、函数实参、模板字符串里。
 *    【逗号运算符】
 *      `a, b` 会依次对 a 和 b 求值，但整个表达式的值是**最后一个**的值。
 *      它优先级最低（低于赋值），所以常被用作"一个位置塞多条语句"的工具。
 *
 * 2. 为什么需要
 *    - 三元运算符让"二选一"的赋值不必展开成 if/else，代码更紧凑；
 *      在 JSX / 模板字符串 / 数组字面量这些只能放表达式的地方，它是唯一选择。
 *    - 逗号运算符主要用于：for 循环的初始化段与更新段写多条语句、
 *      以及需要"求值但丢弃结果"的紧凑写法。
 *
 * 3. 核心语法要点
 *    - 三元是右结合的：a ? b : c ? d : e 解析成 a ? b : (c ? d : e)。
 *      这个特性让"链式三元"能代替一串 else if。
 *    - 三元只求值被选中的那个分支，另一个分支完全不会执行（短路）。
 *    - 三元与 ?? 的优先级：?? 高于 ?:，所以 a ?? b ? c : d 是 (a ?? b) ? c : d。
 *    - 逗号运算符在函数调用/数组字面量里 **不是** 逗号运算符：
 *      f(a, b) 里的逗号是"参数分隔符"，[a, b] 里是"元素分隔符"，它们不产生"取最后一个值"的效果。
 *      只有出现在需要"单个表达式"的位置（如赋值右侧、括号内）时逗号才是运算符。
 *    - 用括号包裹的逗号是一个表达式：(1, 2, 3) 的值是 3。
 *
 * 4. 常见陷阱
 *    - 嵌套三元超过两层可读性急剧下降，超过两层应改用 if/else 或查表；
 *      更不要用三元去执行带副作用的操作（`x > 0 ? doA() : doB()` 是好写法，
 *      但 `x > 0 ? (a=1, b=2) : c` 就属于滥用）。
 *    - 三元的两个分支应返回**同类型**的值，否则容易埋下类型不一致的隐患
 *      （例如一边返回数字一边返回字符串）。
 *    - 逗号运算符极易与分隔符混淆，是 ESLint 中 no-sequences 规则要禁止的对象，
 *      生产代码几乎不该出现它。
 *    - 三元运算符优先级高于逗号：a ? b : c, d 等价于 (a ? b : c), d。
 *
 * 【运行方法】
 *   在仓库根目录执行：node 04_operators/08_ternary_and_comma.js
 *
 * 【预期输出】
 *   依次打印三元的基础用法、作为表达式的灵活性、嵌套三元的链式写法、
 *   短路与副作用验证，以及逗号运算符的求值顺序演示。
 * ============================================================================
 */

// ---------------------------------------------------------------------------
// 1. 三元运算符的基础用法
// ---------------------------------------------------------------------------

console.log('--- 1. 三元基础 ---');

const age = 20;
// 读作：age 大于等于 18 吗？是就取 '成年'，否则取 '未成年'
const ageLabel = age >= 18 ? '成年' : '未成年';
console.log(`age = ${age} => ${ageLabel}`);

// 与 if/else 的对比：三元是"表达式"，可以直接放在赋值右侧
let access;
if (age >= 18) {
  access = '允许访问';
} else {
  access = '禁止访问';
}
// 上面 5 行等价于下面这 1 行
const accessByTernary = age >= 18 ? '允许访问' : '禁止访问';
console.log('if/else 的结果 =', access, '，三元的结果 =', accessByTernary);

// 三元的结果可以再参与运算
const price = 100;
const finalPrice = price > 50 ? price * 0.9 : price;
console.log(`price = ${price}，大于 50 打九折 => ${finalPrice}`);

// ---------------------------------------------------------------------------
// 2. 三元是表达式：能出现在 if/else 做不到的地方
// ---------------------------------------------------------------------------

console.log('\n--- 2. 三元是表达式 ---');

const score = 88;

// (1) 直接作为函数实参
function describe(kind) {
  return `等级：${kind}`;
}
console.log(describe(score >= 90 ? '优秀' : score >= 60 ? '及格' : '不及格'));

// (2) 直接嵌入模板字符串
console.log(`本次考试${score >= 60 ? '通过' : '未通过'}，得分 ${score}`);

// (3) 直接写在数组 / 对象字面量里
const report = {
  name: '张三',
  score,
  status: score >= 60 ? 'pass' : 'fail',
  level: score >= 90 ? 'A' : score >= 80 ? 'B' : 'C',
};
console.log('生成的报告对象：', report);

// (4) 用在 JSX 风格的条件渲染里（这里是字符串模拟，思想一致）
function renderBadge(isNew) {
  return `<span class="badge">${isNew ? '新品' : '常规'}</span>`;
}
console.log(renderBadge(true)); // 新品
console.log(renderBadge(false)); // 常规

// ---------------------------------------------------------------------------
// 3. 嵌套三元：右结合带来的链式写法
// ---------------------------------------------------------------------------

console.log('\n--- 3. 嵌套三元（右结合） ---');

// 三元是右结合的：a ? b : c ? d : e 会被解析成 a ? b : (c ? d : e)
// 正是这个特性让"链式判断"成立，效果类似 else if
function gradeOf(s) {
  return s >= 90 ? 'A' : s >= 80 ? 'B' : s >= 70 ? 'C' : s >= 60 ? 'D' : 'F';
}
for (const s of [95, 85, 75, 65, 30]) {
  console.log(`  分数 ${s} => 等级 ${gradeOf(s)}`);
}

// 用括号显式写出结合方式，验证上面的解析结果
console.log('  加括号验证：85 =>', 85 >= 90 ? 'A' : 85 >= 80 ? 'B' : 'C'); // 'B'

// 但嵌套超过两层就很难读了。同样的逻辑用查表法更清晰：
const GRADE_TABLE = [
  { min: 90, grade: 'A' },
  { min: 80, grade: 'B' },
  { min: 70, grade: 'C' },
  { min: 60, grade: 'D' },
];
function gradeByTable(s) {
  const hit = GRADE_TABLE.find((row) => s >= row.min);
  return hit ? hit.grade : 'F';
}
console.log('  查表法结果一致：95 =>', gradeByTable(95), '，30 =>', gradeByTable(30));

// ---------------------------------------------------------------------------
// 4. 三元只求值一个分支（短路）
// ---------------------------------------------------------------------------

console.log('\n--- 4. 三元的分支短路 ---');

function branch(name, value) {
  console.log(`    >>> 分支 "${name}" 被求值`);
  return value;
}

console.log('条件为真时：');
const r1 = true ? branch('真分支', 'A') : branch('假分支', 'B');
console.log('  结果 =', r1, '（假分支没有被求值）');

console.log('条件为假时：');
const r2 = false ? branch('真分支', 'A') : branch('假分支', 'B');
console.log('  结果 =', r2, '（真分支没有被求值）');

// 实用价值：用三元避免不必要的计算（或避免访问可能出错的数据）
const data = { list: [] };
const first = data.list.length > 0 ? data.list[0] : null;
console.log('  空数组时安全取值 =', first); // null

// ---------------------------------------------------------------------------
// 5. 逗号运算符
// ---------------------------------------------------------------------------

console.log('\n--- 5. 逗号运算符 ---');

// 在"需要单个表达式"的位置，逗号依次求值并返回最后一个值
const commaValue = (1, 2, 3);
console.log('(1, 2, 3) 的值 =', commaValue); // 3

// 逗号运算符优先级最低（比赋值 = 还低），所以下面这句
// 是"先算 a = (1, 2)，再把结果赋给 x"
let a;
const x = (a = 1, a + 1);
console.log('x = (a = 1, a + 1) => x =', x, '，a =', a); // 2, 1

// 注意区分：函数调用与数组字面量里的逗号是"分隔符"，不是逗号运算符
function sum3(p, q, r) {
  return p + q + r;
}
console.log('sum3(1, 2, 3) =', sum3(1, 2, 3)); // 6（这里是参数分隔符）
console.log('[1, 2, 3].length =', [1, 2, 3].length); // 3（这里是元素分隔符）
console.log('sum3((1, 1), (2, 2), (3, 3)) =', sum3((1, 1), (2, 2), (3, 3))); // 6（括号内才是逗号运算符，都取最后一个）

// 最常见也最正当的用法：for 循环的初始化段 / 更新段写多条语句
console.log('  用逗号在 for 里同时维护两个变量：');
for (let i = 0, j = 10; i < j; i++, j--) {
  console.log(`    i = ${i}, j = ${j}`);
}
// 上面 i++ 和 j-- 之间的逗号就是逗号运算符，让一个更新段能写多条语句

// 求值顺序演示：从左到右依次求值
console.log('  逗号表达式的求值顺序：');
const order = (console.log('    第 1 步'), console.log('    第 2 步'), console.log('    第 3 步'), '最后的值');
console.log('  整个表达式的值 =', order); // '最后的值'

// 与"赋值链"结合：把多个变量在一行里初始化
let m;
let n;
const combo = ((m = 1), (n = 2), m + n);
console.log('  combo = ((m = 1), (n = 2), m + n) =>', combo, '，m =', m, '，n =', n); // 3, 1, 2

// 为什么生产代码要避免逗号运算符：极易与分隔符混淆，可读性差
// 下面这段"能用但不推荐"的代码，等价于三行独立赋值
let u;
let v;
((u = 'a'), (v = 'b'), undefined);
console.log('  不推荐的紧凑写法结果：u =', u, '，v =', v);
// 清晰写法：
u = 'a';
v = 'b';
console.log('  推荐写法结果：u =', u, '，v =', v);

// ---------------------------------------------------------------------------
// 6. 优先级：?? 与 ?: 的组合
// ---------------------------------------------------------------------------

console.log('\n--- 6. 优先级：?? 与 ?: ---');

// ?? 的优先级高于 ?:，所以下面这句是 (null ?? 'B') ? ... : ...
const maybeName = null;
const label = maybeName ?? '默认名' ? '有名字' : '没名字';
console.log('  maybeName ?? "默认名" ? "有名字" : "没名字" =>', label);
// 实际语义：先算出 '默认名'（真值），所以走"有名字"
console.log('  加括号更清晰：((maybeName ?? "默认名") ? "有名字" : "没名字") =>', (maybeName ?? '默认名') ? '有名字' : '没名字');

// 逗号优先级最低，所以 a ? b : c, d 是 (a ? b : c), d
const commaAfterTernary = (true ? 'X' : 'Y', 'Z');
console.log('  (true ? "X" : "Y", "Z") 的值 =', commaAfterTernary); // 'Z'

console.log('\n全部演示结束。');
