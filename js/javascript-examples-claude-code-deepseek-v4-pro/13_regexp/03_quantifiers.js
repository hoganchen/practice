/**
 * ============================================================================
 * 知识点：量词 —— * + ? {n} {n,} {n,m} 以及贪婪与惰性（加 ?）
 * ============================================================================
 *
 * 【所属分类】13_regexp —— 正则表达式
 * 【难度等级】入门
 * 【前置知识】13_regexp/01_basics_and_literals.js、13_regexp/02_character_classes.js
 *
 * 【知识点说明】
 *
 * 1. 是什么
 *    量词（quantifier）写在"一个原子"（一个字符、一个字符类或一个分组）的后面，
 *    用来规定这个原子"重复多少次"。正则的匹配能力有一大半来自量词：
 *    没有量词，你只能匹配固定长度的文本；有了量词，才能表达"若干个数字"。
 *
 * 2. 为什么需要
 *    "手机号是 11 位数字"、"用户名 3 到 16 个字符"、"可能带 http:// 也可能不带"——
 *    现实中的匹配需求几乎都带"次数"概念，量词就是把这些需求直接翻译成正则。
 *
 * 3. 核心语法要点
 *    *        零次或多次（等价 {0,}）
 *    +        一次或多次（等价 {1,}）
 *    ?        零次或一次（等价 {0,1}），即"可选"
 *    {n}      恰好 n 次
 *    {n,}     至少 n 次
 *    {n,m}    至少 n 次、至多 m 次（n 和 m 都是闭区间端点的整数）
 *    ---- 惰性（lazy / 非贪婪）写法：在量词后面加一个 ? ----
 *    *?  +?  ??  {n,m}?   表示"在能匹配成功的前提下，尽量少重复"
 *    ---- 默认情况 ----
 *    不加 ? 时量词是"贪婪"（greedy）的：在能匹配成功的前提下，尽量多重复。
 *    贪婪不是"贪到底就失败"——正则会"回溯"，吐回一些字符来让整体匹配成功。
 *
 * 4. 常见陷阱
 *    (1) 贪婪量词 + 后面还有一个同类字符时，结果常比你预期"更长"：
 *        /<.+>/ 匹配 "<a><b>" 会一口气吃掉整个串，而不是只匹配第一个标签。
 *    (2) 惰性不是"最短"，而是"从左到右第一个能整体匹配成功的最短解"，
 *        它的效果依赖右边的模式，不要以为加了 ? 就万能。
 *    (3) {n,m} 中间不能有空格：/a{1, 3}/ 是语法错误（要在 try/catch 里演示）。
 *    (4) 单独写 { 在非量词语境下可能是字面量，写死要匹配花括号时要转义 \{ \}。
 *    (5) 量词只能作用于"紧挨着它的前一个原子"：/ab+/ 是"一个 a 后面跟多个 b"，
 *        不是"ab 重复多次"；想让 ab 整组重复，要写 /(?:ab)+/。
 *    (6) 量词作用于"能匹配空串的原子"（如把 a* 再套一层量词）会造成大量空匹配
 *        与性能问题，13 号文件会专门讲这个（灾难性回溯）。
 *
 * 【运行方法】
 *   在仓库根目录执行：node 13_regexp/03_quantifiers.js
 *
 * 【预期输出】
 *   逐个小节打印每种量词的匹配结果与位置；重点对比贪婪与惰性在同一段文本上
 *   得到的"匹配长度"差异，并用表格化输出直观展示回溯的效果。
 * ============================================================================
 */

/** 打印 str 中所有匹配：文本、起始位置、长度 */
function show(label, re, str) {
  const flags = re.flags.includes('g') ? re.flags : re.flags + 'g';
  const g = new RegExp(re.source, flags);
  const out = [];
  let m;
  while ((m = g.exec(str)) !== null) {
    out.push(`"${m[0]}"(位置${m.index}, 长度${m[0].length})`);
    if (m[0] === '') g.lastIndex++;
  }
  console.log(`  ${label} → ${out.length} 处：${out.join('  ') || '（无）'}`);
}

console.log('--- 1. 星号 * ：零次或多次 ---');

// a* 表示"字符 a 出现 0 次、1 次或更多次"。
// 注意"零次"是合法的，所以 a* 可以匹配到空串 —— 这在很多场景下是意外之源。
show('a* 于 "aaa"', /a*/, 'aaa');
show('a* 于 "bbb"', /a*/, 'bbb'); // 匹配到空串（位置 0），因为"零个 a"也算匹配
show('ab* 于 "abbb"', /ab*/, 'abbb'); // b* 吃掉了三个 b
show('ab* 于 "a"', /ab*/, 'a'); // b 出现 0 次，所以只匹配 "a"

console.log('--- 2. 加号 + ：一次或多次 ---');

// + 要求至少出现一次，所以它比 * 更适合"确实要有内容"的场景。
show('a+ 于 "aaa"', /a+/, 'aaa');
show('a+ 于 "bbb"', /a+/, 'bbb'); // 零次不行，所以无匹配
show('\\d+ 于 "abc123def45"', /\d+/, 'abc123def45');
show('[\\w.-]+@[\\w.-]+ 于邮箱串', /[\w.-]+@[\w.-]+/, '联系我：zhang.san@example.com 谢谢');
// 上面这条邮箱用的正则里，[\\w.-] 的解释：
//   \\w  单词字符（字母、数字、下划线）
//   .    在字符类里就是字面的点号
//   -    放在末尾，表示字面的连字符
//   +    整个字符类出现一次或多次
// 这只是教学用的简化写法，真正的邮箱校验在 12 号文件里。

console.log('--- 3. 问号 ? ：零次或一次（可选） ---');

// ? 让前一个原子"可有可无"，是处理可选前缀/后缀的利器。
show('https? 于两种协议', /https?/, 'http://a.com 和 https://b.com');
show('colou?r 于两种拼写', /colou?r/, 'color 与 colour 都对');
show('\\d{4}-\\d{2}-\\d{2} 中的可选时区', /\d{4}-\d{2}-\d{2}(Z)?/, '2024-05-01Z 与 2024-05-01');

console.log('--- 4. 花括号 {n} / {n,} / {n,m} ---');

show('a{3} 恰好 3 个', /a{3}/, 'aa aaa aaaa');
show('a{2,} 至少 2 个', /a{2,}/, 'aa aaa aaaa');
show('a{2,3} 2 到 3 个', /a{2,3}/, 'aa aaa aaaa');
show('\\d{11} 恰好 11 位数字（手机号长度）', /\d{11}/, '号码 13800138000 与 123');

console.log('  说明：/a{2,3}/ 面对 "aaaa" 时先贪心吃掉 3 个，得到 "aaa"；');
console.log('        剩下的那个 "a" 不够 2 个，凑不成匹配，所以这一串只贡献一处匹配。');

console.log('--- 5. 量词的作用范围：只作用于紧邻的前一个原子 ---');

const s1 = 'ababab';
show('ab+ 于 "ababab"', /ab+/, s1);
console.log('  解释：这里 b+ 只重复 b，所以匹配是 "ab"（b 只出现一次）。');
show('(ab)+ 于 "ababab"', /(ab)+/, s1);
console.log('  解释：用括号把 ab 变成一个整体原子，+ 才能作用于整组。');
show('(?:ab)+ 于 "ababab"', /(?:ab)+/, s1);
console.log('  解释：(?:...) 是非捕获组，效果一样但不单独保存这一组，见 05 号文件。');

console.log('--- 6. 贪婪：默认情况下"能多则多" ---');

const html = '<b>粗体</b> 和 <i>斜体</i>';

// 逐符号解释 /<.+>/：
//   <    字面量左尖括号
//   .    任意一个字符（默认不含换行）
//   +    前面的 . 出现一次或多次 —— 贪婪，尽量多吃
//   >    字面量右尖括号
show('/<.+>/ 贪婪', /<.+>/, html);
// 结果会从第一个 '<' 一直吃到最后一个 '>'，把两个标签全吞了。

// 逐符号解释 /<[^>]+>/：
//   [^>] 表示"不是 '>' 的任意字符"，这样就不可能提前跨过标签的右边界
//   +    出现一次或多次
show('/<[^>]+>/ 用否定字符类限定边界', /<[^>]+>/, html);

console.log('--- 7. 惰性：在量词后面加 ? ---');

// 逐符号解释 /<.+?>/：
//   <     字面量左尖括号
//   .     任意字符
//   +?    "一次或多次，但尽量少" —— 惰性量词
//   >     字面量右尖括号
// 匹配过程：先只吃 1 个字符试 '>'，不行就再吃 1 个……直到碰上第一个 '>'。
show('/<.+?>/ 惰性', /<.+?>/, html);

// 惰性也可以与花括号组合。
show('".{2,5}?" 惰性范围', /".{2,5}?"/, '"ab" "abcdef" "abc"');

console.log('--- 8. 贪婪 vs 惰性：同一条正则逐行对照 ---');

const demo = '"one" and "two" and "three"';
console.log('  文本 =', demo);
show('".*"  贪婪', /".*"/, demo);
show('".*?" 惰性', /".*?"/, demo);
console.log('  结论：贪婪一次吞掉最长的、"最外层"的那对引号；惰性每次只吃最近的一对。');

const nums = '1234567890';
console.log('  文本 =', nums);
show('\\d+      贪婪', /\d+/, nums);
show('\\d+?     惰性（最少 1 个）', /\d+?/, nums);
show('\\d{2,4}  贪婪', /\d{2,4}/, nums);
show('\\d{2,4}? 惰性', /\d{2,4}?/, nums);

console.log('--- 9. 贪婪并不等于"一定匹配更长"：回溯的作用 ---');

// 这个例子最能说明"贪婪 + 回溯"：模式要求以数字结尾，贪婪的 \d+ 先吃掉全部数字，
// 发现后面还有 (?!\d) 的约束不满足，就吐回一个字符再试，直到成功。
const tail = 'abc12345';
console.log('  文本 =', tail);
show('\\d+\\d 于末尾（贪婪回溯）', /\d+\d/, tail);

// 用一组"必须少于 N 个字符"的约束做对比：贪婪会回溯以满足整体匹配。
show('[a-z]+\\d 贪婪', /[a-z]+\d/, 'abcd7ef9');
console.log('  解释：[a-z]+ 先吃到 "abcd"，接着 \\d 匹配 7 成功；');
console.log('        下一轮从 e 开始，[a-z]+ 吃到 "ef"，\\d 匹配 9 成功。');

console.log('--- 10. 陷阱：{n,m} 中间不能有空格 ---');

// 关键事实：量词里不允许空格。但 JS 有个"宽容规则"（规范附录 B 的兼容行为）：
// 当 { 后面不是合法的量词时，它会被当成一个"字面的花括号字符"，而不是报错。
// 所以在非 u 模式下 /a{1, 3}/ 不报错，而是被当成了字面文本 "a{1, 3}"。
console.log('  非 u 模式下 /a{1, 3}/ 的 source =', JSON.stringify(/a{1, 3}/.source));
console.log('  它其实在匹配字面量 "a{1, 3}" =>', /a{1, 3}/.test('a{1, 3}'));
console.log('  ↑ 这类"悄悄变成字面量"的行为非常危险：你以为写错了会报错，实际是静默失效。');

// 加上 u 标志后，正则按严格模式解析，同样的写法立刻变成语法错误。
try {
  const bad = new RegExp('a{1, 3}', 'u');
  console.log('  不会执行到这里：', bad);
} catch (err) {
  console.log('  new RegExp("a{1, 3}", "u") 的后果 =>', err.constructor.name + ': ' + err.message);
}

console.log('--- 11. 陷阱：量词前面必须真的有东西可重复 ---');

// {2} 这种量词前面没有原子，属于"没有东西可以重复"，任何模式下都直接报错。
try {
  const orphan = new RegExp('{2}');
  console.log('  不会执行到这里：', orphan);
} catch (err) {
  console.log('  new RegExp("{2}") 的后果 =>', err.constructor.name + ': ' + err.message);
}

// 想匹配文本里真实的花括号，必须转义 \{ 与 \}。
show('\\{\\d+\\} 匹配 {123}', /\{\d+\}/, '占位符 {123} 与 {abc}');
// 反过来看：/\d{2}/ 想要的是"两个连续数字"，文本里只有孤零零的一个 "2"，
// 所以匹配不到。想匹配 "{2}" 这三个字符，就必须写成 /\{\d\}/。
show('\\d{2} 在只有单个数字的文本里', /\d{2}/, '数字 {2} 出现在文本里');
show('\\{\\d\\} 才是匹配 {2} 的正确写法', /\{\d\}/, '数字 {2} 出现在文本里');

console.log('--- 12. 小结 ---');
console.log('· * = 0 或多次，+ = 1 或多次，? = 0 或 1 次，{n,m} = 区间次数。');
console.log('· 默认贪婪：尽量多，但会为了整体匹配成功而回溯。');
console.log('· 加 ? 变惰性：尽量少，通常用于"成对符号"之间取最短。');
console.log('· 量词只作用于紧邻的一个原子，想让一串字符整体重复必须用括号分组。');
console.log('· 能用 [^x]+ 描述边界时，就别用 .+ 加惰性，前者更快也更准确。');
