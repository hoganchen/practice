/**
 * ============================================================================
 * 知识点：实战校验 —— 邮箱、手机号、URL、身份证、密码强度、日期格式
 * ============================================================================
 *
 * 【所属分类】13_regexp —— 正则表达式
 * 【难度等级】高级
 * 【前置知识】13_regexp/04_anchors_and_boundaries.js、13_regexp/08_lookahead_lookbehind.js
 *
 * 【知识点说明】
 *
 * 1. 是什么
 *    本文件把前面所有零件组装成"能直接抄走用"的校验函数，覆盖六个常见字段：
 *    邮箱、中国大陆手机号、http(s) URL、18 位身份证号、密码强度、日期格式。
 *    每个正则都在注释里逐符号拆解，并把"能过 / 不能过"的例子跑出来。
 *
 * 2. 为什么需要
 *    表单校验是最常见的正则应用场景，但它也是"翻车最多"的场景：
 *    网上流传的邮箱正则动辄几百字符，既不准确又难以维护；
 *    而很多人用一条正则去承担它做不到的事（比如校验日期是否真实存在）。
 *    所以关键不是背正则，而是知道"哪一层该用正则，哪一层必须用代码"。
 *
 * 3. 核心语法要点
 *    (1) 校验类正则必须用 ^...$ 包住整串，否则会退化成"包含判断"。
 *    (2) 带 u 标志能让 \p{...}、\u{...} 生效，也更容易在写错时立刻报错。
 *    (3) 多个前瞻 (?=...) 串联，可以表达"多个条件同时成立"。
 *    (4) 结构校验（格式对不对）用正则；值校验（日期合不合法、校验位对不对）
 *        用代码。正则不适合做算术。
 *
 * 4. 常见陷阱
 *    (1) 邮箱正则写得越"全"越难维护，现实中推荐"宽松结构 + 后续验证"。
 *    (2) 中国大陆手机号段会变，硬编码全部号段的正则很快就会过时。
 *    (3) URL 校验不要自己手写完整的 RFC 3986，用 new URL() 更可靠；
 *        正则只做"粗筛"。
 *    (4) 日期正则只能校验"形状"（比如月份是不是 00~19），
 *        但管不了"2 月 30 日"，必须再查一次真实日期。
 *    (5) 身份证的"最后一位校验码"是加权求和取模算出来的，正则永远算不了。
 *    (6) 不写 ^ $ 是校验类正则里最致命的错误，一定要在测试里放一个
 *        "合法内容 + 一堆垃圾"的样例来验证。
 *
 * 【运行方法】
 *   在仓库根目录执行：node 13_regexp/12_validation_patterns.js
 *
 * 【预期输出】
 *   对每个字段打印一批典型样例的校验结果（通过 / 拒绝），
 *   并额外打印"只做结构校验 vs 再做值校验"的差异对比。
 * ============================================================================
 */

/** 统一的样例打印器：把 case 列表跑一遍并输出结果 */
function runCases(title, re, cases) {
  console.log(`  ${title}`);
  console.log(`    正则 = ${re}`);
  for (const c of cases) {
    const pass = re.test(c);
    console.log(`      ${pass ? '✓ 通过' : '✗ 拒绝'}  ${JSON.stringify(c)}`);
  }
}

console.log('--- 1. 邮箱校验 ---');

// 逐符号解释 /^[\w.!#$%&'*+/=?^`{|}~-]+@[A-Za-z0-9](?:[A-Za-z0-9-]{0,61}[A-Za-z0-9])?(?:\.[A-Za-z0-9](?:[A-Za-z0-9-]{0,61}[A-Za-z0-9])?)+$/：
//   ^                                          整串开始
//   [\w.!#$%&'*+/=?^`{|}~-]+                   本地部分：单词字符或若干常见符号，一个或多个
//   @                                          字面 @
//    [A-Za-z0-9]                              域名首字符必须是字母或数字（不能是连字符）
//    (?:[A-Za-z0-9-]{0,61}[A-Za-z0-9])?        可选：中间 0~61 个字符，且必须以字母数字结尾
//                                              —— 这一段保证"连字符不能出现在域名开头或结尾"
//    (?:\.[A-Za-z0-9](?:[A-Za-z0-9-]{0,61}[A-Za-z0-9])?)+
//                                              至少一个"点 + 域名段"，保证必须有 TLD
//   $                                          整串结束
const emailRe = /^[\w.!#$%&'*+/=?^`{|}~-]+@[A-Za-z0-9](?:[A-Za-z0-9-]{0,61}[A-Za-z0-9])?(?:\.[A-Za-z0-9](?:[A-Za-z0-9-]{0,61}[A-Za-z0-9])?)+$/;

runCases('邮箱校验（含域名连字符规则）', emailRe, [
  'user@example.com',
  'first.last+tag@sub.example.co',
  'a@b.co',
  'user@-bad.com',        // 域名以连字符开头
  'user@bad-.com',        // 域名以连字符结尾
  'user@example',         // 没有顶级域
  'user@@example.com',    // 两个 @
  'user @example.com',    // 中间有空格
  'user@example.com extra', // 后面拖了垃圾（验证 ^ $ 的作用）
]);

// 宽松结构 + 用代码做进一步判断，工程上往往更好维护。
const looseEmail = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
runCases('宽松版邮箱正则（推荐在真实项目里先用它粗筛）', looseEmail, [
  'user@example.com',
  'user@example',      // 需要至少一个点
  'user@@example.com',
  'user name@example.com',
]);

console.log('--- 2. 中国大陆手机号 ---');

// 逐符号解释 /^1[3-9]\d{9}$/：
//   ^        整串开始
//   1        号段必须以 1 开头
//   [3-9]    第二位是 3~9（覆盖 13x~19x 的常见号段）
//   \d{9}    后面恰好 9 位数字（合计 11 位）
//   $        整串结束
const mobileRe = /^1[3-9]\d{9}$/;

runCases('手机号（简单版）', mobileRe, [
  '13800138000',
  '19912345678',
  '12800138000',   // 第二位是 2，不存在这个号段
  '1380013800',    // 只有 10 位
  '138001380000',  // 12 位
  '138 0013 8000', // 含空格
  'tel13800138000',// 前面有垃圾
]);

// 更精确的号段写法（注意：号段会随政策调整，硬编码需要定期维护）。
// 逐符号解释 /^1(?:3\d|4[5-9]|5[0-35-9]|6[2567]|7[0-8]|8\d|9\d)\d{8}$/：
//   1                                  以 1 开头
//   (?:3\d|4[5-9]|5[0-35-9]|...)       第二位与第三位组成的号段分支：
//       3\d      130~139
//       4[5-9]   145~149
//       5[0-35-9] 150~153、155~159（排除 154）
//       6[2567]  162、165、166、167
//       7[0-8]   170~178
//       8\d      180~189
//       9\d      190~199
//   \d{8}                              后面 8 位数字
const mobileStrict = /^1(?:3\d|4[5-9]|5[0-35-9]|6[2567]|7[0-8]|8\d|9\d)\d{8}$/;
runCases('手机号（精确号段版）', mobileStrict, [
  '13800138000',
  '15412345678',   // 154 不是有效号段
  '16512345678',
  '19912345678',
]);

console.log('--- 3. URL 校验：正则粗筛 + new URL 精校 ---');

// 逐符号解释 /^https?:\/\/[^\s/$.?#].[^\s]*$/i：
//   ^              整串开始
//   https?         字面 http 或 https（s 出现 0 或 1 次）
//   :\/\/          字面 "://"（斜杠都要转义）
//   [^\s/$.?#]     主机名首字符：不能是空白、斜杠、点、$、?、#
//   .              再跟任意一个字符（保证主机名至少两位）
//   [^\s]*         后面跟任意多个非空白字符（路径、查询串等等）
//   $              整串结束
//   i              忽略大小写，让 HTTP:// 也能通过
const urlRe = /^https?:\/\/[^\s/$.?#].[^\s]*$/i;

runCases('URL 粗筛', urlRe, [
  'https://example.com',
  'http://example.com/path/to?q=1#top',
  'https://sub.domain.co:8080/a',
  'ftp://example.com',     // 协议不对
  'https://example',       // 主机名只有一段？这条其实会通过，见下方说明
  'not a url',
  'https://exa mple.com',  // 主机名里有空格
]);

// 用内置的 URL 解析器做真正的校验：它能处理端口范围、非法字符等正则管不了的事。
function isValidUrl(str) {
  if (!urlRe.test(str)) return { ok: false, why: '粗筛未通过' };
  try {
    const u = new URL(str);
    return { ok: true, why: `协议=${u.protocol} 主机=${u.hostname} 端口=${u.port || '(默认)'}` };
  } catch (err) {
    return { ok: false, why: 'new URL 解析失败：' + err.message };
  }
}

console.log('  用 new URL() 做精校：');
for (const u of ['https://example.com', 'https://exa mple.com', 'https://example.com:99999/x']) {
  const r = isValidUrl(u);
  console.log(`    ${(r.ok ? '✓ 通过' : '✗ 拒绝').padEnd(7)} ${JSON.stringify(u).padEnd(34)} ${r.why}`);
}
console.log('  结论：正则负责"看起来像不像"，URL 类负责"到底解不解析得出来"。');

console.log('--- 4. 中国大陆 18 位身份证号 ---');

// 逐符号解释 /^[1-9]\d{5}(?:19|20)\d{2}(?:0[1-9]|1[0-2])(?:0[1-9]|[12]\d|3[01])\d{3}[\dXx]$/：
//   ^                    整串开始
//   [1-9]\d{5}           前 6 位地址码：首位不能是 0，随后 5 位数字
//   (?:19|20)\d{2}       年份：19xx 或 20xx
//   (?:0[1-9]|1[0-2])    月份：01~09 或 10~12
//   (?:0[1-9]|[12]\d|3[01])  日期：01~09、10~29、30~31
//   \d{3}                顺序码 3 位
//   [\dXx]               校验位：数字或字母 X（大小写都收）
//   $                    整串结束
const idCardRe = /^[1-9]\d{5}(?:19|20)\d{2}(?:0[1-9]|1[0-2])(?:0[1-9]|[12]\d|3[01])\d{3}[\dXx]$/;

runCases('身份证号（结构校验）', idCardRe, [
  '11010119900307123X',
  '110101199003071234',
  '110101199013071234',   // 月份 13 不合法
  '110101199002301234',   // 2 月 30 日 —— 结构上却"合法"，见下方说明
  '010101199003071234',   // 地址码首位是 0
  '11010119900307123',    // 17 位
]);

// 值校验：结构对了不代表日期真实存在。这一步正则无能为力。
function isRealDate(y, m, d) {
  const dt = new Date(y, m - 1, d);
  return dt.getFullYear() === y && dt.getMonth() === m - 1 && dt.getDate() === d;
}
function validateIdCard(id) {
  if (!idCardRe.test(id)) return { ok: false, why: '结构不合法' };
  const y = Number(id.slice(6, 10));
  const m = Number(id.slice(10, 12));
  const d = Number(id.slice(12, 14));
  if (!isRealDate(y, m, d)) return { ok: false, why: `${y}-${m}-${d} 这个日期不存在` };
  return { ok: true, why: `出生日期 ${y}-${m}-${d}` };
}
console.log('  结构校验 + 值校验：');
for (const id of ['11010119900307123X', '110101199002301234', '110101199013071234']) {
  const r = validateIdCard(id);
  console.log(`    ${(r.ok ? '✓ 通过' : '✗ 拒绝').padEnd(7)} ${id}  ${r.why}`);
}
console.log('  ↑ 正则只能校验"形状"，"2 月 30 日"必须交给 Date 判断。');

console.log('--- 5. 密码强度 ---');

// 逐符号解释 /^(?=.*[a-z])(?=.*[A-Z])(?=.*\d)(?=.*[^\w\s])[\S]{8,20}$/：
//   ^                  整串开始
//   (?=.*[a-z])        前瞻：后面某处必须有小写字母
//   (?=.*[A-Z])        前瞻：后面某处必须有大写字母
//   (?=.*\d)           前瞻：后面某处必须有数字
//   (?=.*[^\w\s])      前瞻：后面某处必须有"既不是单词字符也不是空白"的字符（即符号）
//   [\S]{8,20}         真正消费的部分：8~20 个非空白字符
//   $                  整串结束
const strongPwdRe = /^(?=.*[a-z])(?=.*[A-Z])(?=.*\d)(?=.*[^\w\s])[\S]{8,20}$/;

runCases('密码强度（大小写 + 数字 + 符号，8~20 位）', strongPwdRe, [
  'Abc12345!',
  'aB3!aaaa',
  'abcdefgh',      // 缺大写、数字、符号
  'ABCDEFG1!',     // 缺小写
  'Abcdefg!',      // 缺数字
  'Abcdefg1',      // 缺符号
  'Ab1!',          // 太短
  'Abc12345! 更多内容', // 含空格，且超出长度
  'Abc 12345!',    // 含空格
]);

// 分级：把"满足几条"作为强度分数，比"通过/不通过"更好用。
const strengthRules = [
  ['长度 >= 8', /^.{8,}$/],
  ['含小写字母', /[a-z]/],
  ['含大写字母', /[A-Z]/],
  ['含数字', /\d/],
  ['含符号', /[^\w\s]/],
];
function scorePassword(pwd) {
  const hit = strengthRules.filter(([, re]) => re.test(pwd));
  return { score: hit.length, hit: hit.map(([name]) => name) };
}
console.log('  强度分级：');
for (const p of ['abc', 'abcdefgh', 'Abcdefgh', 'Abcdefg1', 'Abc12345!']) {
  const r = scorePassword(p);
  const level = r.score <= 2 ? '弱' : r.score <= 4 ? '中' : '强';
  console.log(`    ${p.padEnd(12)} 得分 ${r.score}/5 → ${level}  （命中：${r.hit.join('、')}）`);
}

console.log('--- 6. 日期格式校验 ---');

// 逐符号解释 /^(?<y>\d{4})-(?<m>0[1-9]|1[0-2])-(?<d>0[1-9]|[12]\d|3[01])$/：
//   ^                     整串开始
//   (?<y>\d{4})           年：4 位数字
//   -                     字面连字符
//   (?<m>0[1-9]|1[0-2])   月：01~09 或 10~12
//   -                     字面连字符
//   (?<d>0[1-9]|[12]\d|3[01])  日：01~09、10~29、30~31
//   $                     整串结束
// 注意这里没有用 i 标志，所以只接受数字格式，不接 "2026/9/16" 这类写法。
const dateRe = /^(?<y>\d{4})-(?<m>0[1-9]|1[0-2])-(?<d>0[1-9]|[12]\d|3[01])$/;

runCases('日期 YYYY-MM-DD（结构）', dateRe, [
  '2026-09-16',
  '2026-02-30',   // 结构合法但日期不存在
  '2026-13-01',   // 月份 13
  '2026-00-10',   // 月份 00
  '2026-1-1',     // 没有补零
  '2026/09/16',   // 分隔符不对
  '16-09-2026',   // 顺序不对
]);

// 结构 + 值双重校验，并把三个字段取出来。
function parseDate(str) {
  const m = dateRe.exec(str);
  if (!m) return { ok: false, why: '格式不匹配' };
  const { y, m: mo, d } = m.groups;
  if (!isRealDate(Number(y), Number(mo), Number(d))) {
    return { ok: false, why: `${y}-${mo}-${d} 不是真实存在的日期` };
  }
  return { ok: true, why: `解析为 ${y} 年 ${Number(mo)} 月 ${Number(d)} 日` };
}
console.log('  结构 + 值双重校验：');
for (const s of ['2026-09-16', '2026-02-30', '2026-02-29', '2024-02-29']) {
  const r = parseDate(s);
  console.log(`    ${(r.ok ? '✓ 通过' : '✗ 拒绝').padEnd(7)} ${s}  ${r.why}`);
}
console.log('  ↑ 2026 不是闰年，2 月 29 日不存在；2024 是闰年，所以通过 —— 这种判断只有代码能做。');

console.log('--- 7. 用一条汇总表看清"该用正则还是该用代码" ---');

const summary = [
  ['邮箱结构', '正则', '只看形状，不验证邮箱是否真的存在'],
  ['域名连字符规则', '正则', '首尾不能是连字符，属于结构约束'],
  ['手机号号段', '正则（需维护）', '号段会变，建议配置化而不是写死'],
  ['URL 是否可解析', '代码（new URL）', '端口范围、非法字符等交给标准库'],
  ['日期是否真实存在', '代码（Date）', '闰年、大小月属于算术问题'],
  ['身份证校验位', '代码（加权取模）', '正则无法做算术'],
  ['密码是否满足多条规则', '正则 + 逐条判断', '逐条判断能告诉用户缺什么'],
];
for (const [item, tool, why] of summary) {
  console.log(`  ${item.padEnd(16)} → ${tool.padEnd(16)} ${why}`);
}

