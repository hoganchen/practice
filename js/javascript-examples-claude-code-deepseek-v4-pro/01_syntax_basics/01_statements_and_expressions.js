/**
 * ============================================================================
 * 知识点：语句与表达式
 * ============================================================================
 *
 * 【所属分类】01_syntax_basics —— 语法基础
 * 【难度等级】入门
 * 【前置知识】00_hello_world/01_hello_world.js
 *
 * 【知识点说明】
 *
 * 1. 是什么
 *    这是 JS 语法的第一组基本概念，也是理解后续一切语法的关键：
 *    - 表达式（Expression）：能"求出一个值"的代码片段。有值，可以作为参数、
 *      可以赋给变量。例如 1 + 2、a > b、foo()、x = 5、条件运算符 a ? b : c。
 *    - 语句（Statement）：执行一个"动作"的完整句子。通常没有值（或值不被使用），
 *      用来控制流程、声明变量、定义函数。例如 if、for、while、return、
 *      var/let/const 声明、function 声明、throw、try、break/continue。
 *    - 表达式语句（Expression Statement）：由一个表达式加上分号构成的最常见语句。
 *      也就是"光算不用"的表达式，如 foo(); 或 a = 1;
 *    一句话记忆：表达式**有值**，语句**做事**。凡是能出现在 `const x = ___` 右边的东西，
 *    都是表达式。
 *
 * 2. 为什么需要 / 解决什么问题
 *    很多初学者写代码时说不清"这里能不能用 if"、"为什么对象字面量语句会报错"，
 *    根源都是没区分这两者。分清之后你会立刻明白：
 *    - 为什么函数参数位置不能写 if 语句，但可以写 a ? b : c（因为要的是值）；
 *    - 为什么 `{ }` 在语句位置是"块语句"而不是空对象；
 *    - 为什么箭头函数的简写体只能写表达式。
 *
 * 3. 核心语法要点
 *    （1）表达式有值，可以直接被消费
 *        const n = 1 + 2;         // 1 + 2 是表达式
 *        console.log(a > b);      // 比较运算也是表达式
 *    （2）赋值本身是表达式 —— 它的值是"被赋的值"
 *        console.log(x = 10);     // 打印 10，同时 x 变成 10
 *        所以可以链式赋值：a = b = c = 0;
 *    （3）语句不能作为值使用
 *        const y = if (true) { 1 } else { 2 };  // 语法错误！if 是语句
 *        要用有值的写法：const y = true ? 1 : 2;  // 条件运算符是表达式
 *    （4）块语句 `{ ... }`
 *        出现在"语句位置"的花括号是块语句，用来把多条语句打包成一个整体
 *        （配合 if / for / 单独使用），它没有值。
 *        所以 `{ a: 1 }` 单独作为一条语句时，`a:` 会被当成标签（label），
 *        而不是对象属性 —— 这是著名的坑。想写对象字面量表达式语句，
 *        必须用括号包起来：({ a: 1 });
 *    （5）函数声明 vs 函数表达式
 *        function f() {}          → 函数声明（语句），会被提升
 *        const f = function () {}; → 函数表达式（右边的部分），不会整体提升
 *    （6）IIFE：把函数表达式立刻调用
 *        (function () { ... })();  // 最外层括号把"声明"强行解释成"表达式"
 *    （7）逗号运算符：依次求值，返回最后一个的值
 *        const r = (1, 2, 3);     // r === 3
 *
 * 4. 常见陷阱与注意事项
 *    - `const y = if (...) {}` 会直接 SyntaxError，别把语句当值用。
 *    - 行首的 `{` 或 `function` 会被解析成语句，导致与上一行"粘连"出诡异错误
 *      （详见 02_asi_and_semicolons.js）。
 *    - 不要滥用赋值表达式做"值"：if (x = 0) 是永假（值是 0，falsy），
 *      正确意图多半是 if (x === 0)。这是历史悠久的典型 bug。
 *    - 逗号运算符与"函数参数里的逗号"、"数组字面量里的逗号"完全不同，
 *      只有出现在表达式位置且被括号括住时才是逗号运算符。
 *    - 对象字面量语句 `{a: 1}` 不报错但也不生效（被当成标签 + 表达式语句），
 *      极易误判为"代码没跑"，实际上它跑了，只是没有副作用。
 *
 * 【运行方法】
 *   在仓库根目录执行：node 01_syntax_basics/01_statements_and_expressions.js
 *
 * 【预期输出】
 *   分节展示：表达式求值、赋值表达式的值、条件运算符替代 if、
 *   块语句与标签的陷阱、函数声明与函数表达式的区别、IIFE、逗号运算符。
 * ============================================================================
 */

// ---------------------------------------------------------------------------
// 1. 表达式：有值，能"被使用"
// ---------------------------------------------------------------------------

console.log('--- 1. 表达式有值 ---');

// 下面等号右边全是表达式。JS 会先求出它们的值，再赋给左边的变量。
const a = 1 + 2; // 算术表达式 → 3
const b = a > 2; // 比较表达式 → true
const c = typeof b; // typeof 也是一元运算符，构成表达式 → 'boolean'
const d = [1, 2, 3].length; // 成员访问 + 调用，同样是表达式 → 3

console.log('1 + 2 =', a);
console.log('a > 2 =', b);
console.log('typeof b =', c);
console.log('[1,2,3].length =', d);

// 因为表达式有值，所以可以直接塞进另一个表达式里（这叫"组合"）。
console.log('表达式可以嵌套：(1 + 2) * (3 + 4) =', (1 + 2) * (3 + 4));

// ---------------------------------------------------------------------------
// 2. 赋值本身也是表达式：它的值就是被赋的值
// ---------------------------------------------------------------------------

console.log('\n--- 2. 赋值是表达式 ---');

let x;
// 如果赋值不是表达式，这里就没法把 (x = 10) 当作参数传给 console.log。
// 实际输出是 10，证明"赋值"这个动作的求值结果就是赋进去的值。
console.log('console.log(x = 10) 的输出：', (x = 10));
console.log('此刻 x 的值：', x);

// 正因为赋值有值，才能链式赋值：从右往左依次赋，最终返回最右边的值。
let p, q, r;
p = q = r = 7;
console.log('链式赋值 p q r：', p, q, r);

// 陷阱示范：把 ==（比较）误写成 =（赋值）。
let flag = 0;
// 下面这个 if 的条件是表达式 (flag = 1)，它的值是 1（真值），所以永远成立，
// 并且副作用是"把 flag 改成了 1"——这通常不是程序员的意图。
if ((flag = 1)) {
  console.log('if ((flag = 1)) 成立，因为赋值表达式的结果 1 是真值，副作用是 flag 变成了', flag);
}
console.log('正确写法应当是比较：if (flag === 1)，用 === 而不是 =');

// ---------------------------------------------------------------------------
// 3. 语句不能作为值 —— 用条件运算符替代 if
// ---------------------------------------------------------------------------

console.log('\n--- 3. 语句不能当值用，表达式可以 ---');

// 如果取消下面这行的注释，会直接抛出 SyntaxError（语法错误，程序根本跑不起来）：
//   const level = if (a > 2) { 'big' } else { 'small' };
// 原因：if 是"语句"，它没有值，不能出现在 `const level = ___` 的右边。

// 想要"有值的选择"，就用条件运算符（三目运算符）——它是表达式。
const level = a > 2 ? 'big' : 'small';
console.log('用条件运算符得到 level =', level);

// 同理，箭头函数的简写体（不带花括号）只能写表达式：
const double = (n) => n * 2;
console.log('箭头函数简写体返回表达式结果：double(21) =', double(21));

// 而带花括号的箭头函数体是"块语句"，必须有显式 return，否则返回 undefined。
const doubleWrong = (n) => {
  n * 2; // 这只是"求了个值然后丢掉"，没有 return
};
const doubleRight = (n) => {
  return n * 2; // 显式 return 才是把值交出去
};
console.log('没有 return 的块体箭头函数返回值：', doubleWrong(21));
console.log('有 return 的块体箭头函数返回值：', doubleRight(21));

// ---------------------------------------------------------------------------
// 4. 块语句与"对象字面量语句"的陷阱
// ---------------------------------------------------------------------------

console.log('\n--- 4. 块语句 vs 对象字面量语句 ---');

// 单独的花括号在"语句位置"就是块语句，它把多条语句打包在一起。
{
  const inside = '我在块里';
  console.log('块语句内部：', inside);
}
// 块语句没有值，也不会在外部留下变量（let/const 是块级作用域，下一章会讲）。
console.log('出了块以后，访问 inside 会抛错 —— 这正说明块语句没有"值"也没有"泄漏"');

// 著名的坑：下面这行看起来像"创建了一个对象"，其实不是。
// 在语句位置，`{` 被解析为块语句，`name:` 被解析为"标签（label）"，
// `'alice'` 是一条毫无副作用的表达式语句。整行完全不会创建任何对象。
{
  name: 'alice';
}
console.log("写成 { name: 'alice'; } 不会创建对象，它被当成了标签 + 表达式语句");

// 想让它成为"对象字面量表达式"，必须用括号把语句位置变成表达式位置：
const objFromLiteral = { name: 'alice' };
console.log('赋值给变量的对象字面量才是对象：', objFromLiteral);

// 或者用一层括号包住，让它变成表达式语句（虽然通常没有意义）：
({ name: 'bob' });
console.log('用括号包住 ({ name: "bob" }) 才是真正的对象字面量表达式语句');

// ---------------------------------------------------------------------------
// 5. 函数声明（语句）与函数表达式
// ---------------------------------------------------------------------------

console.log('\n--- 5. 函数声明 vs 函数表达式 ---');

// 函数声明：整体是一条语句，函数名会在当前作用域中"提升"，且提升后即可调用。
console.log('在声明之前就调用函数声明：', declaredHoisted());
function declaredHoisted() {
  return '函数声明被提升了，先调用也不会报错';
}

// 函数表达式：右边是一个表达式，赋值给变量。变量遵循 let/const 的规则，
// 在声明语句执行之前调用会触发"暂时性死区"错误（见 02_variables/04）。
const expressed = function () {
  return '函数表达式：必须先执行到这一行，之后才能调用';
};
console.log('函数表达式赋值之后调用：', expressed());

// 具名函数表达式：函数自己内部可以通过名字递归，但这个名字不会泄漏到外部作用域。
const factorial = function fact(n) {
  return n <= 1 ? 1 : n * fact(n - 1); // 内部用 fact 递归，安全
};
console.log('具名函数表达式做递归：factorial(5) =', factorial(5));
console.log('函数名 fact 在外部访问不到：typeof fact =', typeof fact);

// ---------------------------------------------------------------------------
// 6. IIFE：把函数表达式立刻调用
// ---------------------------------------------------------------------------

console.log('\n--- 6. IIFE（立即调用函数表达式） ---');

// 关键点：函数关键字出现在"语句位置"会被当成函数声明，而函数声明必须带名字，
// 所以后面的 () 会变成语法错误。外层加一对括号，就把"语句位置"变成了"表达式位置"。
const iifeResult = (function () {
  const secret = '只有内部能看到的私有变量';
  return 'IIFE 的返回值：' + secret;
})();
console.log(iifeResult);

// 用箭头函数写 IIFE 更简洁，因为箭头函数本身就不能作为声明，天然是表达式。
const iifeArrow = (() => {
  return '箭头函数版 IIFE 也能立即执行';
})();
console.log(iifeArrow);

// IIFE 的经典用途：制造私有作用域，避免污染全局（在只有 <script> 的年代尤其重要）。
const counter = (function () {
  let count = 0; // 外部无法直接访问，只能通过返回的函数间接操作
  return {
    increment: () => ++count,
    get: () => count,
  };
})();
counter.increment();
counter.increment();
console.log('IIFE 制造私有状态：count =', counter.get(), '（外部拿不到 count 变量本身）');

// ---------------------------------------------------------------------------
// 7. 逗号运算符：依次求值，返回最后一个
// ---------------------------------------------------------------------------

console.log('\n--- 7. 逗号运算符 ---');

// 逗号运算符会从左到右依次求值每个子表达式，最终返回"最后一个"的值。
const commaResult = (1, 2, 3);
console.log('(1, 2, 3) 的值：', commaResult);

// 前面表达式的副作用依然会发生，只是值被丢弃。
let trace = [];
const commaSideEffect = (trace.push('第一'), trace.push('第二'), '最后的值');
console.log('逗号表达式的返回值：', commaSideEffect);
console.log('前面被丢弃值但保留了副作用的表达式：', trace);

// 重要区分：下面两种"逗号"不是逗号运算符！
console.log('函数参数里的逗号是分隔符，不是运算符：Math.max(1, 5, 3) =', Math.max(1, 5, 3));
console.log('数组字面量里的逗号是分隔符：', [1, 5, 3]);
console.log('只有出现在表达式位置、且两侧都是完整表达式的逗号，才是逗号运算符。');

console.log('\n--- 8. 小结 ---');
console.log('· 表达式有值，能被赋值、当参数、参与运算；语句执行动作，没有可用的值。');
console.log('· 能写在 `const x = ___` 右边的，一定是表达式。');
console.log('· 行首的 { 是块语句不是对象字面量；要写成对象要么赋值、要么加括号。');
console.log('· 函数声明是语句（会提升），函数表达式是值（按变量规则处理）。');
