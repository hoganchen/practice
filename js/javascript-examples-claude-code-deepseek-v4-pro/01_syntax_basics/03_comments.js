/**
 * ============================================================================
 * 知识点：单行注释、多行注释与文档注释（JSDoc）
 * ============================================================================
 *
 * 【所属分类】01_syntax_basics —— 语法基础
 * 【难度等级】入门
 * 【前置知识】01_syntax_basics/01_statements_and_expressions.js
 *
 * 【知识点说明】
 *
 * 1. 是什么
 *    JS 只有两种注释语法：
 *    - 单行注释：`// ...`，从 `//` 起到本行结束（不含换行符）全是注释。
 *    - 块注释（多行注释）：`/* ... *\/`，从 `/*` 到最近的 `*\/` 之间的全部内容
 *      （**包括换行**）都是注释。
 *    在这两种语法之上，社区约定出一种"文档注释"写法：以 `/**` 开头的块注释，
 *    内部用 `@param`、`@returns` 等标签描述函数契约。这套约定叫 JSDoc。
 *    注意：JSDoc 只是**注释**，运行时不产生任何效果，但编辑器（VS Code）
 *    和工具（TypeScript、ESLint、TypeDoc）会读取它，用来做类型提示和生成文档。
 *
 * 2. 为什么需要 / 解决什么问题
 *    注释解释"为什么这样做"，代码解释"做了什么"。没有注释的代码在半年后
 *    对任何人都像新代码。而按 JSDoc 规范写注释还有额外收益：
 *    - VS Code 鼠标悬停在函数上时，会直接显示你的注释和参数说明；
 *    - 传入错误类型时编辑器能给出提示（相当于"不用编译的 TypeScript"）；
 *    - 可以用 TypeDoc 等工具一键生成 API 文档网站。
 *
 * 3. 核心语法要点
 *    （1）`//` 单行注释：最常用，可以写在代码后面（行尾注释）。
 *    （2）`/*` 与 `*\/` 配对的块注释：用于大段说明、临时注释掉一段代码、版权声明。
 *        块注释**不能嵌套**：遇到第一个 `*\/` 就结束了。
 *    （3）文档注释 JSDoc：仍然是用 `/*` 与 `*\/` 包起来的块注释，
 *        但必须以 `/**` 开头（多一个星号），否则工具不识别。
 *    （4）常用 JSDoc 标签：
 *        @param {类型} 参数名 说明   —— 描述参数
 *        @returns {类型} 说明        —— 描述返回值
 *        @throws {类型} 说明         —— 描述可能抛出的异常
 *        @example                    —— 给出用法示例
 *        @deprecated                 —— 标记已废弃（编辑器会划删除线）
 *        @type {类型}                —— 给变量标注类型
 *        @typedef / @property        —— 定义自定义类型（对象结构）
 *        @see / @link                —— 交叉引用
 *    （5）类型可写成联合类型 `{string|number}`、可空 `{?number}`、
 *        数组 `{number[]}`、泛型 `{Promise<string>}`。
 *
 * 4. 常见陷阱与注意事项
 *    - 注释不能嵌套：`/* 外层 /* 内层 *\/ 还是注释 *\/` 会在第一个 `*\/` 处结束，
 *      后面的内容会被当作**代码**执行或直接报错。
 *    - 注释要跨行时不要只写 `//` 堆叠几十行，块注释更合适。
 *    - `//` 出现在字符串或正则里时不是注释：'http://a.com' 里的 // 是字符串内容。
 *      同样，"a /* b" 里的 /* 在字符串中也不是注释开始。
 *    - 不要在注释里写会过期的信息（如"共 3 个参数"），改代码时容易忘改注释。
 *    - 不要把代码注释掉当成版本管理：用 Git。注释掉的大段代码只会腐烂。
 *    - 文件开头的 `#!/usr/bin/env node`（shebang）是特例，它必须以 `#!` 开头，
 *      且只能出现在文件第一行，Node 会把它当注释忽略。
 *    - 在本文件的注释文字里想"提到"块注释的结束记号时，不能直接连着写，
 *      否则当前这个注释会被提前结束。标准做法是写成 `*` + `\` + `/` 这样一个
 *      反斜杠转义形式：它对解析器来说只是三个普通字符，不会构成结束记号。
 *
 * 【运行方法】
 *   在仓库根目录执行：node 01_syntax_basics/03_comments.js
 *
 * 【预期输出】
 *   分节演示：单行注释与行尾注释、块注释、JSDoc 的实际效果（打印函数契约）、
 *   注释不参与执行、块注释不可嵌套的报错演示、字符串里的 // 不是注释。
 * ============================================================================
 */

// ---------------------------------------------------------------------------
// 1. 单行注释
// ---------------------------------------------------------------------------

console.log('--- 1. 单行注释 ---');

// 这一整行都是注释，不会被执行。
// 连续多行用 // 也是可以的，但代码块级别的说明更适合用块注释。
// 注释里可以写任意内容：中文、emoji、符号 ~!@#$%^&*() 都不会影响解析。

const radius = 5; // 行尾注释：写在代码后面，解释这一行的意图
console.log('圆的半径：', radius, '（这一行的行尾注释说明了单位是厘米）');

// 临时禁用某一行代码的常见做法：注释掉它。
// console.log('这行被注释掉了，不会打印');
console.log('上一行虽然写着 console.log，但因为以 // 开头，完全不执行');

// ---------------------------------------------------------------------------
// 2. 块注释
// ---------------------------------------------------------------------------

console.log('\n--- 2. 块注释 ---');

/*
 * 这是一个块注释。
 * 它可以横跨很多行，中间的所有内容（包括换行）都属于注释。
 *
 * 常见用途：
 *   1. 文件开头的版权声明 / 模块说明；
 *   2. 一段复杂算法的推导过程；
 *   3. 临时把一大段代码注释掉（但不推荐长期保留）。
 */

const pai = Math.PI; /* 行内块注释：也可以夹在代码中间使用 */
console.log('圆周率：', pai);

// 块注释的一个重要用途：解释"为什么"而不是"是什么"。
// 下面这行之所以用 Math.hypot 而不是 Math.sqrt(a*a + b*b)，
// 是因为 hypot 能避免中间结果溢出/下溢，数值上更稳健。
const hypot = Math.hypot(3, 4);
console.log('Math.hypot(3, 4) =', hypot, '（用 hypot 而非 sqrt(a²+b²) 的理由见上方注释）');

console.log('\n--- 3. JSDoc 文档注释 ---');

/**
 * 计算圆形的面积。
 *
 * 这是本文件里"真正被工具读取"的文档注释：把鼠标悬停在调用处，
 * VS Code 会弹出这段说明和参数表。
 *
 * @param {number} r 圆的半径，必须是非负数。
 * @param {number} [precision=2] 保留的小数位数，可选，默认 2 位。
 * @returns {number} 圆面积，已按 precision 四舍五入。
 * @throws {RangeError} 当 r 为负数时抛出。
 * @example
 *   circleArea(5);      // 78.54
 *   circleArea(5, 0);   // 79
 */
function circleArea(r, precision = 2) {
  // 用注释说明"为什么"要检查：负半径在几何上没有意义，
  // 与其返回 NaN 让调用方困惑，不如立刻抛错、让问题暴露在源头。
  if (r < 0) {
    throw new RangeError('半径不能为负数，收到：' + r);
  }
  return Number((Math.PI * r * r).toFixed(precision));
}

console.log('circleArea(5) =', circleArea(5));
console.log('circleArea(5, 0) =', circleArea(5, 0));

// JSDoc 里的 @throws 不是装饰：调用方确实需要处理这个异常。
// 这里按"演示报错必须在内部捕获"的约定，用 try/catch 包住。
try {
  circleArea(-1);
} catch (err) {
  console.log('circleArea(-1) 抛出的错误：', err.constructor.name, '—', err.message);
}

/**
 * 用户对象的类型定义。
 * @typedef {Object} User
 * @property {number} id   用户 ID
 * @property {string} name 用户名
 * @property {string[]} [tags] 标签列表，可选
 */

/**
 * 按 id 查找用户（演示 @deprecated 的用法）。
 *
 * @deprecated 请改用 findUserById，本函数只是为了兼容旧代码而保留。
 * @param {User[]} users 用户数组
 * @param {number} id 目标 id
 * @returns {User|undefined} 找到的用户，找不到返回 undefined
 */
function findUser(users, id) {
  return users.find((u) => u.id === id);
}

/** @type {User[]} 用户列表，用 @type 给变量标注类型，编辑器就能给自动补全 */
const users = [
  { id: 1, name: '小明', tags: ['admin'] },
  { id: 2, name: '小红' },
];
console.log('findUser(users, 2) =', findUser(users, 2));

// ---------------------------------------------------------------------------
// 4. 注释不参与执行
// ---------------------------------------------------------------------------

console.log('\n--- 4. 注释在"解析阶段"就被丢弃 ---');

// 注释在词法分析阶段就被完全剔除，不会进入语法树，更不会生成任何字节码。
// 因此注释可以随便写，多写不影响运行速度（只影响文件体积）。
const before = '没有注释的字符串';
/* 这里有
   一大段
   块注释 */
const after = '中间隔着块注释的字符串';
console.log(before, '/', after);

// 用 Function.prototype.toString 看一下：注释在"源码文本"里还在，
// 但那只是因为我们取的是原始文本，执行引擎并不关心它。
function withComments() {
  // 这行注释不会被执行
  /* 这段块注释也不会 */
  return '函数体里的注释不影响返回结果';
}
console.log('调用带注释的函数：', withComments());
console.log('函数源码里依然能看到注释（因为 toString 返回的是原始文本），但执行引擎早已丢弃它们。');

// ---------------------------------------------------------------------------
// 5. 陷阱一：块注释不能嵌套
// ---------------------------------------------------------------------------

console.log('\n--- 5. 陷阱：块注释不能嵌套 ---');

// JS 的块注释在遇到第一个结束记号时就终止，不支持嵌套。
// 因此下面这种写法是**错误**的（这里用 new Function 演示，捕获解析错误）：
try {
  const nested = new Function(`
    /* 外层注释开始
       /* 我以为这里还是注释 */
       这行其实已经不在注释里了
    */
  `);
  nested();
} catch (err) {
  console.log('嵌套块注释导致：', err.constructor.name, '—', err.message);
}
console.log('正确做法：要注释掉"本身含块注释"的代码，改用 // 逐行注释，或直接删掉。');

// 同理，注释里如果出现未配对的结束记号，会把后面的代码提前"解锁"。
console.log('结论：块注释的嵌套是 JS 的语法盲区，写多行注释时务必检查有没有多余的结束记号。');

// ---------------------------------------------------------------------------
// 6. 陷阱二：字符串和正则里的 // 不是注释
// ---------------------------------------------------------------------------

console.log('\n--- 6. 陷阱：字符串里的 // 不是注释 ---');

// 这里的 // 出现在字符串字面量内部，只是两个普通字符。
const url = 'https://example.com/path'; // 真正的注释从这一行的 // 才开始
console.log('URL：', url);
console.log('URL 长度：', url.length, '—— 证明 "https://" 里的 // 被算进字符串了');

// 同理，"/*" 在字符串里也不是注释开始。
const notAComment = '这是一段包含 /* 开头记号的字符串 */ 的文本';
console.log(notAComment);
console.log('解析器依据"当前是否处于字符串/正则/模板中"来决定是否识别注释，绝不会误判。');

// 模板字符串里的 // 同样只是普通字符。
const tpl = `模板字符串里的 // 也不是注释，这行会被完整保留`;
console.log(tpl);

// ---------------------------------------------------------------------------
// 7. 陷阱三：shebang（#!）是特例
// ---------------------------------------------------------------------------

console.log('\n--- 7. 特例：shebang ---');
console.log('如果在文件第一行写 #!/usr/bin/env node，Node 会把它当注释忽略，');
console.log('而 Unix 系统会用它找到执行该文件的解释器，从而支持 ./script.js 直接运行。');
console.log('限制：必须第 1 行第 1 个字符开始，中间不能有空行，且不能用 // 或 /* 代替。');

console.log('\n--- 8. 小结 ---');
console.log('· // 单行，/* */ 块注释（可跨行），/** */ 文档注释（JSDoc）。');
console.log('· 块注释不能嵌套；字符串/正则/模板里的 // 与 /* 只是普通字符。');
console.log('· JSDoc 是注释，但编辑器与工具会读取它做类型提示和文档生成。');
console.log('· 写"为什么"，别写"是什么"；能靠命名说清的，就别写注释。');
