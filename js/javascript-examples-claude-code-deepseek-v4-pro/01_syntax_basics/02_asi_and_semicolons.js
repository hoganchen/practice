/**
 * ============================================================================
 * 知识点：自动分号插入（ASI）规则与陷阱
 * ============================================================================
 *
 * 【所属分类】01_syntax_basics —— 语法基础
 * 【难度等级】进阶
 * 【前置知识】01_syntax_basics/01_statements_and_expressions.js
 *
 * 【知识点说明】
 *
 * 1. 是什么
 *    ASI = Automatic Semicolon Insertion，自动分号插入。
 *    它不是一个"猜你意思"的智能补全器，而是规范里写死的三条**极其严格**的规则：
 *    （规则一）如果某个记号（token）违反语法，且它前面有换行，就插入分号；
 *    （规则二）如果遇到 `}`（块结束）仍然语法不合法，就插入分号；
 *    （规则三）如果到了输入结尾（EOF）仍然语法不合法，就插入分号。
 *    另外还有一组"受限产生式"（Restricted Productions），规定某些关键字后
 *    不能直接换行，否则**强制**插入分号。
 *
 * 2. 为什么需要 / 解决什么问题
 *    ASI 让 JS 可以不写分号也大多能跑（这也是某些代码风格的基础）。
 *    但它的三条规则是"出错才补救"，不是"到换行就加分号"。理解这一点，
 *    就能解释所有"为什么这行会跟下一行粘在一起"的诡异现象。
 *
 * 3. 核心语法要点
 *    （1）什么时候**不会**插入分号
 *        只有"不加分号就语法错误"时才会插入。如果不需要分号也合法，
 *        解析器会毫不犹豫地把下一行接上来 —— 这就是所有坑的根源。
 *    （2）五个危险行首记号：`(`、`[`、`` ` ``、`+`、`-`、`/`
 *        它们都能"继续"上一行的表达式，于是两行被合并成一句：
 *          let total = sum
 *          (1 + 2)            → 被解析成  sum(1 + 2)
 *          let v = arr
 *          [0]                → 被解析成  arr[0]
 *    （3）受限产生式（必须记牢）
 *        - return / throw / break / continue / yield 后面换行 →
 *          立刻插入分号，后面的值变成永远执行不到的孤立表达式。
 *        - 后缀 ++ / -- 前面换行 → 当作"新语句的前缀运算"，两行分开。
 *        - 箭头函数的 `=>` 不能换行到参数前。
 *    （4）规则二、规则三的体现
 *        块结束的 `}` 处、文件末尾，即使不写分号也不会报错。
 *    （5）本仓库的策略
 *        统一显式写分号（主流风格：Airbnb、Standard-with-semicolons 等），
 *        并把"行首危险记号"的位置用分号隔断，从根上绕开 ASI 的坑。
 *
 * 4. 常见陷阱与注意事项
 *    - ASI 只在"语法错误"时才补，它**不会**读懂你的意图。
 *    - 换行不等于语句结束。想让语句结束，最保险的办法就是写分号。
 *    - `return` 后换行是新手最常踩的坑，且不报错、只是静默返回 undefined，
 *      极难排查。
 *    - 有些风格（如 StandardJS）确实不加分号，但它们要求行首是 ( [ ` + - / 时
 *      前面补一个分号。这是"用规则对抗规则"，能跑但可读性差。
 *    - 本文件为了演示，刻意写了几段"不写分号"的代码，并用 try/catch 包住
 *      可能抛错的部分，保证文件本身仍能正常退出。
 *
 * 【运行方法】
 *   在仓库根目录执行：node 01_syntax_basics/02_asi_and_semicolons.js
 *
 * 【预期输出】
 *   分节演示：ASI 正常补分号的场景、五个危险行首记号造成的合并、
 *   return 换行的静默失败、`++` 换行的拆分、以及规避手段。
 * ============================================================================
 */

// ---------------------------------------------------------------------------
// 1. ASI 的"正常工作"：只在语法不合法时才补
// ---------------------------------------------------------------------------

console.log('--- 1. ASI 什么时候真的会补分号 ---');

// 下面这段代码完全不写分号，也能正常运行 —— 因为 `const a = 1 const b = 2`
// 这种写法在语法上不成立，解析器只能在换行处插入分号救场。
// 用 new Function 包裹是为了把演示代码"隔离"起来，避免污染本文件的词法环境。
const demoNormal = new Function(`
  const a = 1
  const b = 2
  const c = a + b
  return '不写分号也能跑：a=' + a + ', b=' + b + ', c=' + c
`);
console.log(demoNormal());

// 用 eval 之外的另一种演示方式：下面这段真实代码同样不写分号，
// 因为换行后遇到的是新语句的开头（标识符 console），不加分号也合法吗？
// 不合法 —— `console.log('x') console.log('y')` 是语法错误，所以 ASI 介入。
console.log('下面两行都不写分号，靠 ASI 分隔：')
console.log('第二行正常执行，说明 ASI 在换行处补上了分号')

// ---------------------------------------------------------------------------
// 2. 危险行首一：`(` —— 上一行被当成了函数调用
// ---------------------------------------------------------------------------

console.log('\n--- 2. 危险行首记号 ( 造成的合并 ---');

// 对比一下：下面这两行是"安全"的写法，分号把语句切断得干干净净。
const sum = function (a, b) {
  return a + b;
};
const totalSafe = sum(1, 2); // 明确传两个参数
console.log('加了分号，结果符合预期：sum(1, 2) =', totalSafe);

// 现在用 new Function 演示"不加分号"的版本，看看解析器到底干了什么。
const demoSneakyParen = new Function(`
  const sum = function (a, b) { return a + b }
  let total = sum
  (1 + 2)
  return total
`);
// 我们的意图是：total 应该等于 sum 这个函数本身。
// 但 (1 + 2) 被解析成了上一行的"函数调用参数"，于是变成 total = sum(3)；
// sum(3) 的第二个参数 b 是 undefined，3 + undefined = NaN，所以 total 是 NaN。
const sneakyParen = demoSneakyParen();
console.log('不加分号时 total 的实际值：', sneakyParen);
console.log('类型：', typeof sneakyParen, '——本该是 function，却因为被当成函数调用而变成了 NaN');
console.log('规避手段：把 (1 + 2) 写成 const x = (1 + 2); 或者两行之间补分号。');

// ---------------------------------------------------------------------------
// 3. 危险行首二：`[` —— 上一行被当成了数组下标访问
// ---------------------------------------------------------------------------

console.log('\n--- 3. 危险行首记号 [ 造成的合并 ---');

const demoBracket = new Function(`
  const arr = [10, 20, 30]
  let v = arr
  [0]
  return v
`);
// `[0]` 被粘到上一行，变成 arr[0]，所以 v = 10，而不是"数组本身"。
console.log('不加分号时 v 的实际值：', demoBracket());
console.log('类型：', typeof demoBracket(), '——本该是数组，却因为下标访问变成了数字');

// 更常见也更危险的变体：交换两个变量时行首写数组解构。
// 这里在函数体开头加上 'use strict'，是为了让"给数字的属性赋值"从静默忽略
// 变成明确报错，把问题暴露出来（严格模式的行为差异见 04_strict_mode.js）。
const demoSwap = new Function(`
  'use strict';
  let a = 1
  let b = 2
  try {
    a = b
    [a, b] = [b, a]
    return '交换成功 a=' + a + ', b=' + b
  } catch (err) {
    return '抛错：' + err.constructor.name + ' — ' + err.message
  }
`);
console.log('交换变量时的经典翻车现场（行首未加分号）：', demoSwap());
console.log('原因：`[a, b] = [b, a]` 被当成 `b[a, b] = [b, a]`，先对数字取下标再赋值 → 报错。');
console.log('规避手段：行首的 [ 前面补一个分号（写作 `;[a, b] = [b, a]`），或上一行末尾写分号。');

// ---------------------------------------------------------------------------
// 4. 危险行首三、四、五：`` ` ``、`+`、`-`、`/`
// ---------------------------------------------------------------------------

console.log('\n--- 4. 其它危险行首记号 ---');

// 行首是反引号：模板字符串会被当成"标签模板"（tagged template），
// 也就是上一行的函数名被当成标签函数来调用。
const demoBacktick = new Function(`
  const tag = function (strings) { return 'tag 函数被调用了，收到 ' + strings.length + ' 段字符串' }
  let r = tag
  \`hello\`
  return r
`);
console.log('行首是反引号时：', demoBacktick());

// 行首是 + 或 -：会被当成"延续上一行的加法/减法"，而不是"新的一元运算"。
const demoPlus = new Function(`
  let x = 5
  let y = 3
  let z = x
  +y
  return z
`);
console.log('行首是 + 时：z =', demoPlus(), '（本该是 z = 5，`+y` 只是一条没有副作用的独立语句）');

// 行首是 /：可能被解析成正则字面量，也可能被解析成除法，歧义极大，务必避免。
console.log('行首是 / 的情况最容易产生"正则 or 除法"歧义，实践中直接避免行首写 /。');
console.log('规避手段统一为：凡是行首出现 ( [ ` + - / ，就在上一行末尾补分号。');

// ---------------------------------------------------------------------------
// 5. 受限产生式之一：return 后换行 —— 静默返回 undefined
// ---------------------------------------------------------------------------

console.log('\n--- 5. return 后换行（最隐蔽的坑） ---');

// 注意：规范规定 return 与它的返回值之间不能有换行符（不能有 LineTerminator）。
// 一旦换行，ASI 会立刻在 return 后面插入分号，函数直接返回 undefined，
// 而下面那个 42 变成了一条永远执行不到的孤立表达式语句。
// 这个过程**不会报任何错**，是排查成本最高的坑之一。
function brokenReturn() {
  return
  42;
}

function correctReturn() {
  return 42;
}

console.log('return 后换行，实际返回值：', brokenReturn());
console.log('写成同一行，实际返回值：', correctReturn());
console.log('注意：brokenReturn 里的 42 依然会被解析，只是永远执行不到（不可达代码）。');

// 换行后跟着一对括号时，返回值干脆变成了"另一个表达式"：
function returnThenParen() {
  return (
    '换行后紧跟左括号时，返回值是括号里的表达式'
  );
}
console.log('return 换行 + ( 开头的表达式：', returnThenParen());

// throw / break / continue / yield 有完全相同的限制，而且 throw 更狠：
// `throw` 后面必须紧跟一个表达式，ASI 在换行处插入的分号会让它变成非法的
// `throw;`，于是**在解析阶段**就抛出 SyntaxError —— 整个脚本根本跑不起来。
// 所以这里必须用 try/catch 包住 new Function 的构造过程，捕获解析期错误。
try {
  const demoThrowNewline = new Function(`
    throw
    new Error('boom')
  `);
  console.log('不该走到这里：', demoThrowNewline);
} catch (err) {
  console.log('构造代码时就报错了，错误类型：', err.constructor.name);
  console.log('错误信息：', err.message);
  console.log('结论：return/throw 后换行属于"解析期"问题，连运行的机会都没有。');
}

// ---------------------------------------------------------------------------
// 6. 受限产生式之二：`++` / `--` 前面的换行
// ---------------------------------------------------------------------------

console.log('\n--- 6. 后缀 ++/-- 前面的换行 ---');

// 规范规定：后缀 ++ 与其操作数之间不能有换行。所以下面这段代码
// （本文件里是真实代码，刻意不写分号）会被解析成两条独立语句：`m;` 和 `++n;`
let m = 1;
let n = 2;
m
++n;
console.log('m 的值：', m, ' n 的值：', n);
console.log('解析结果：`m` 单独成句（值是 1，被丢弃），`++n` 是 n 的前缀自增 → n 变成 3。');
console.log('口诀：++ 和操作数必须贴在一起，中间换行就等于换了一条语句。');

// ---------------------------------------------------------------------------
// 7. ASI 的规则二、规则三：`}` 与文件末尾
// ---------------------------------------------------------------------------

console.log('\n--- 7. } 处与文件末尾一定补分号 ---');

// 在块结束的 `}` 之前，即使不写分号也不会报错（规则二）。
function blockEndDemo() {
  const inner = '块内最后一条语句不写分号也没事'
  return inner
}
console.log(blockEndDemo());

// 文件末尾的最后一条语句不写分号也没事（规则三）。但为了统一风格，
// 本仓库依然要求每条语句都以分号结尾。

console.log('\n--- 8. 小结 ---');
console.log('· ASI 是"出错才补救"，不是"见换行就补"——所以换行绝不等于语句结束。');
console.log('· 危险行首：( [ ` + - /  会在上一行末尾补分号后再写这些记号。');
console.log('· return / throw / break / continue / yield 后面不要换行。');
console.log('· 后缀 ++ / -- 必须与操作数贴在一起。');
console.log('· 最省心的策略：老老实实写分号，从根上消灭这一整类 bug。');
