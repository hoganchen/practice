/**
 * ============================================================================
 * 辅助模块：_cycle-hoist-a.js —— 函数声明提升造成的"循环依赖假象" A 侧
 * ============================================================================
 *
 * 【所属分类】19_modules —— ES Module（ESM）模块化
 * 【说明】
 *   本文件以 _ 开头，是辅助模块，批量校验脚本会跳过它。
 *
 *   它演示一个非常迷惑人的现象：
 *     函数声明（function foo() {}）在模块里是**提升**的，所以循环依赖中
 *     "对方在顶层调用我的函数"这件事**不会**报"未定义"；
 *     但如果那个函数体内部再读我这里的 const，就依然会撞上 TDZ。
 *   也就是说：同一个函数，在循环中被调用了两次 ——
 *     第一次（B 初始化阶段）抛 ReferenceError，
 *     第二次（A 初始化阶段）正常返回。
 *   两次调用发生在**同一份模块图、同一次进程启动**里，这个对比非常直观。
 * ============================================================================
 */

import { callAFn, PROBE } from './_cycle-hoist-b.js';

export const A_CONST = 'a-const';

/**
 * 一个普通的函数声明。它是提升的，所以在 A 的模块体执行之前就能被调用。
 * 但函数体里的 A_CONST 只有在 A 的模块体执行到对应那一行之后才有值。
 * @returns {string} 描述文本
 */
export function aFn() {
  return `aFn 读到 A_CONST = ${A_CONST}`;
}

// ✅ 第二次调用：此刻 A 的模块体正在执行，A_CONST 已经初始化 -> 成功。
//    （B 的模块体先于 A 执行，见 _cycle-hoist-b.js 里的说明。）
export const A_RESULT = callAFn();

// 把 B 在它初始化阶段探测到的结果原样带出来给调用方看。
export const B_PROBE = PROBE;
