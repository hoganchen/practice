/**
 * ============================================================================
 * 知识点：具名导出与具名导入（export const / import { a, b } / 重命名 as）
 * ============================================================================
 *
 * 【所属分类】19_modules —— ES Module（ESM）模块化
 * 【难度等级】入门
 * 【前置知识】06_functions/01_function_basics.js、09_objects/01_object_basics.js
 *
 * 【知识点说明】
 *
 * 1. 是什么
 *    具名导出（named export）是指模块把内部的一个个"名字"对外暴露出去，
 *    导入方必须用**相同的名字**（或显式改名的 as) 把它们取进来。
 *    语法上就是在声明前面加 export 关键字：
 *      export const PI = 3.14;
 *      export function add(a, b) { ... }
 *      export class Vector2 { ... }
 *    导入方写：
 *      import { PI, add, Vector2 } from './_math-utils.js';
 *
 * 2. 为什么需要
 *    在 ESM 出现之前，浏览器端只能靠 <script> 全局变量或 AMD/CMD，
 *    Node 端只有 CommonJS。它们共同的毛病是"依赖关系是运行时才确定的"，
 *    打包工具难以做静态分析，也无法做 tree-shaking（摇树优化，剔除未使用代码）。
 *    具名导出的名字在语法层面就是静态可分析的，因此：
 *      - 打包器能精确知道"你只用了 add"，把没用到的 subtract 删掉；
 *      - 引擎/工具能在运行前就报出"你导入了一个不存在的名字"；
 *      - 循环依赖时行为比 CommonJS 更可预测。
 *
 * 3. 核心语法要点
 *    (1) export 直接修饰声明：export const / export let / export function /
 *        export class。注意 export let x = 1; 导出的是"实时绑定"，见 07。
 *    (2) 导入必须用花括号 { }，里面的名字要与导出方一致（或写 原名 as 新名）。
 *    (3) import 语句会被提升到模块顶部，写在文件哪个位置都一样（见下方 3.）。
 *    (4) 一个模块可以有任意多个具名导出，没有数量限制。
 *    (5) 导入进来的绑定是**只读**的，不能重新赋值。
 *
 * 4. 常见陷阱
 *    (1) 花括号不是"解构赋值"！import { a } from '...' 里的 a 必须与导出名完全一致，
 *        不能像解构那样随意起名（解构是 const { a: x } = obj 这种 as 语义）。
 *    (2) 相对路径必须写全扩展名 './_math-utils.js'；ESM 不像 Node 的 require
 *        那样会自动补 .js 或 /index.js。写成 './_math-utils' 会直接报错。
 *    (3) 导入一个模块里不存在的名字是**语法/链接期错误**，代码根本跑不起来，
 *        try/catch 也接不住（因为它在模块链接阶段就失败了）。
 *    (4) 想导入默认导出却写了花括号（或反过来）是最常见的报错来源，见 02、03。
 *    (5) ESM 的 import 声明只能出现在模块顶层，不能写在 if / 函数体里；
 *        需要条件加载请用动态 import()，见 09。
 *
 * 【运行方法】
 *   在仓库根目录执行：node 19_modules/01_named_exports.js
 *
 * 【预期输出】
 *   依次打印导入进来的常量、函数、类的使用结果，
 *   并演示重命名导入、导入求值提升、只读绑定等特性。
 * ============================================================================
 */

// ---------------------------------------------------------------------------
// 1. 基本语法：具名导入
// ---------------------------------------------------------------------------

// 花括号里列出想要的名字，名字必须和 _math-utils.js 里的 export 名一致。
// 路径必须以 ./ 或 ../ 开头（表示相对当前文件），且必须写扩展名 .js。
// 也可以写 'node:fs' 这样的"裸标识符"，那是内置模块/第三方包。
import { PI, E, MODULE_NAME, add, subtract, multiply, Vector2 } from './_math-utils.js';

console.log('--- 1. 具名导入的基本用法 ---');
console.log('PI =', PI);
console.log('E =', E);
console.log('模块名 =', MODULE_NAME);
console.log('add(1, 2) =', add(1, 2));
console.log('subtract(10, 4) =', subtract(10, 4));
console.log('multiply(1.23456, 2) =', multiply(1.23456, 2));

// 导出的类同样可以直接 new
const v = new Vector2(3, 4);
console.log('new Vector2(3, 4) =', String(v), '，长度 =', v.length());

// ---------------------------------------------------------------------------
// 2. 导入时重命名：as 关键字
// ---------------------------------------------------------------------------

// 语法：import { 原名 as 新名, ... } from '...'
// 使用场景：名字冲突（两个模块都有 add）、名字太啰嗦、想表达业务语义。
// 注意：as 只改本文件里的叫法，不影响模块本身。
import { add as sum, subtract as minus, PI as 圆周率 } from './_math-utils.js';

console.log('\n--- 2. 导入时用 as 重命名 ---');
console.log('sum(100, 23) =', sum(100, 23));
console.log('minus(100, 23) =', minus(100, 23));
// 标识符允许使用中文（Unicode 标识符），但不推荐在真实项目里这么做，这里只是演示
console.log('圆周率(重命名后的 PI) =', 圆周率);

// ---------------------------------------------------------------------------
// 3. import 声明会被"提升"到模块顶部
// ---------------------------------------------------------------------------

// 下面这行代码写在第 1 节的 import 之后，但即使把它写在文件最末尾，
// 效果也一样：ESM 的静态 import 在**编译/链接阶段**就处理完了，
// 整个模块的所有 import 都会先于模块体内的任何语句执行。
// 这与 CommonJS 的 require() 不同——require 是普通函数调用，按书写顺序执行。
console.log('\n--- 3. import 的求值时机 ---');
console.log('模块体代码开始执行时，PI 已经可用：', PI);

// ---------------------------------------------------------------------------
// 4. 具名导出是"部分导入"：不需要的东西可以不引入
// ---------------------------------------------------------------------------

// 上面第 1 节没有导入 LOADED_AT、recordCall 等，它们依然存在于模块中，
// 只是本文件不需要，所以不引入。打包工具的 tree-shaking 就建立在这个基础上：
// 没被任何模块引用的导出，可以在产物里被安全地删掉。
import { recordCall, readInternalScale } from './_math-utils.js';

console.log('\n--- 4. 按需导入模块中的其它导出 ---');
console.log('第一次 recordCall() =', recordCall());
console.log('第二次 recordCall() =', recordCall());
console.log('模块内部私有变量 internalScale 的值 =', readInternalScale());
console.log('（internalScale 没有导出，本文件无法直接访问它）');

// ---------------------------------------------------------------------------
// 5. 常见陷阱：花括号不是解构，名字必须一致
// ---------------------------------------------------------------------------

//   import { mul } from './_math-utils.js'   ← 报错！
//   因为 _math-utils.js 里没有叫 mul 的导出。正确写法是：
//     import { multiply as mul } from './_math-utils.js'
//   这类错误在模块"链接阶段"就会被抛出，属于 SyntaxError，
//   连 try/catch 都拦不住，所以只能靠 import 时仔细核对名字。

// 但如果是**动态** import()，拿到的是命名空间对象，取不存在的属性只会得到 undefined，
// 不会报错（动态 import 见 09_dynamic_import.js）。这里先简单感受一下区别：
const ns = await import('./_math-utils.js');
console.log('\n--- 5. 命名空间对象里取不存在的属性 ---');
console.log('ns.multiply 存在吗？', typeof ns.multiply);
console.log('ns.mul（不存在的名字）的值 =', ns.mul);
console.log('注意：静态 import 写错名字会直接报错，动态 import 取不到只是 undefined');

// ---------------------------------------------------------------------------
// 6. 导入的绑定是只读的
// ---------------------------------------------------------------------------

// 下面这行如果取消注释，会抛出 TypeError: Assignment to constant variable.
//   PI = 3;
// 因为导入进来的名字在导入方是"常量绑定"，只允许读取，不允许写入。
// 想修改模块内部状态，必须由模块自己提供函数（如 recordCall 这种）。
console.log('\n--- 6. 小结 ---');
console.log('具名导出：export 修饰声明 → import { 同名 } from 路径（可 as 改名）');
console.log('一个模块可以有多个具名导出，导入时可以只取其中一部分。');
