/**
 * ============================================================================
 * 辅助模块：_math-utils.js —— 一个只使用"具名导出"的模块
 * ============================================================================
 *
 * 【说明】
 *   本文件以 _ 开头，是辅助模块，批量校验脚本会跳过它（不会单独运行它）。
 *   它被 19_modules 下的 01、03、04、05、06、09 等示例导入。
 *
 *   它故意只使用具名导出（export const / export function），不提供默认导出，
 *   这样在演示"默认导入会失败"时才有意义。
 *
 * 【核心要点】
 *   1. export 关键字可以直接写在声明前面（export const / export function / export class）。
 *   2. 一个模块可以有任意多个具名导出，但默认导出最多只有一个。
 *   3. 不写 export 的东西（如下面的 internalScale）是模块私有的，
 *      外部无论如何都拿不到，这是模块封装性的体现。
 * ============================================================================
 */

// ---------------------------------------------------------------------------
// 1. 具名导出：用 export 修饰变量声明
// ---------------------------------------------------------------------------

// export const 导出一个常量。注意导出的是"实时绑定"（live binding）：
// 外部拿到的是这个名字，它会随着模块内部的变化而变化（详见 07_live_bindings.js）。
export const PI = 3.141592653589793;

// 可以一次导出多个变量
export const E = 2.718281828459045;
export const MODULE_NAME = 'math-utils';

// ---------------------------------------------------------------------------
// 2. 模块私有变量：没有 export，外部访问不到
// ---------------------------------------------------------------------------

// 这个变量没有 export 前缀，因此它是本模块私有的。
// 即使外部写 import { internalScale } from './_math-utils.js' 也会直接报语法错误。
const internalScale = 1000;

// ---------------------------------------------------------------------------
// 3. 具名导出：用 export 修饰函数声明
// ---------------------------------------------------------------------------

/**
 * 两数相加
 * @param {number} a
 * @param {number} b
 * @returns {number}
 */
export function add(a, b) {
  return a + b;
}

/**
 * 两数相减
 * @param {number} a
 * @param {number} b
 * @returns {number}
 */
export function subtract(a, b) {
  return a - b;
}

/**
 * 两数相乘，内部会用到模块私有函数，外部无法直接调用它
 * @param {number} a
 * @param {number} b
 * @returns {number}
 */
export function multiply(a, b) {
  return round(a * b);
}

// ---------------------------------------------------------------------------
// 4. 私有函数：被上面的导出函数使用，但不导出
// ---------------------------------------------------------------------------

function round(n) {
  // 保留 4 位小数，避免浮点误差带来的长尾数字
  return Math.round(n * 10000) / 10000;
}

// ---------------------------------------------------------------------------
// 5. 具名导出：用 export 修饰类声明
// ---------------------------------------------------------------------------

/**
 * 一个极简的二维向量类，用于演示类的具名导出
 */
export class Vector2 {
  constructor(x = 0, y = 0) {
    this.x = x;
    this.y = y;
  }

  /** 向量长度 */
  length() {
    return Math.sqrt(this.x ** 2 + this.y ** 2);
  }

  toString() {
    return `Vector2(${this.x}, ${this.y})`;
  }
}

// ---------------------------------------------------------------------------
// 6. 模块私有状态：外部只能通过导出的函数间接读写
// ---------------------------------------------------------------------------

let callCount = 0;

/**
 * 记录一次调用并返回当前累计次数。
 * 这是"模块级单例状态"的典型用法：状态藏在模块里，外部只能通过函数访问。
 * @returns {number}
 */
export function recordCall() {
  callCount += 1;
  return callCount;
}

/**
 * 读取内部私有变量的值（演示封装）
 * @returns {number}
 */
export function readInternalScale() {
  return internalScale;
}

