/**
 * ============================================================================
 * 辅助模块：_cycle-hoist-b.js —— 函数声明提升造成的"循环依赖假象" B 侧
 * ============================================================================
 *
 * 【所属分类】19_modules —— ES Module（ESM）模块化
 * 【说明】
 *   本文件以 _ 开头，是辅助模块，批量校验脚本会跳过它。
 *
 * 【求值顺序回顾】
 *   main 导入 A -> A 的依赖是 B，先求值 B -> B 的依赖 A 正在求值中，跳过
 *   -> B 的主体执行（就是本文件下面的代码）-> 回到 A，A 的主体才执行。
 *
 *   所以在下面那个 IIFE 里调用 aFn() 时：
 *     · aFn 本身可调用 —— 函数声明提升，绑定早就初始化好了；
 *     · 但 aFn 函数体里的 A_CONST 还没初始化 —— A 的模块体一行都没跑。
 *   于是"能调用、一调用就炸"，这正是循环依赖最难 debug 的形态。
 *
 *   注意这里用 try/catch 把错误接住并记录成字符串，而不是让它冒泡 ——
 *   否则整个模块图求值失败，示例进程就没法以退出码 0 结束了。
 * ============================================================================
 */

import { aFn } from './_cycle-hoist-a.js';

/**
 * 只是把 aFn 包一层。注意函数体在**被调用时**才读 aFn，建立绑定本身不读值。
 * @returns {string} aFn 的返回值
 */
export function callAFn() {
  return aFn();
}

// 探测：B 在自己的初始化阶段就调用一次 callAFn()。
export const PROBE = (() => {
  try {
    return `调用成功 -> ${callAFn()}`;
  } catch (err) {
    // 这里拿到的是 ReferenceError: Cannot access 'A_CONST' before initialization
    return `抛错 -> ${err.constructor.name}: ${err.message}`;
  }
})();
