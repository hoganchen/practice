/**
 * ============================================================================
 * 辅助模块：_config.js —— 一个只使用"默认导出"的模块
 * ============================================================================
 *
 * 【说明】
 *   本文件以 _ 开头，是辅助模块，批量校验脚本会跳过它。
 *   它被 02_default_export.js、05_reexport.js、13_json_import.js 等示例导入。
 *
 * 【核心要点】
 *   1. export default 后面接一个"表达式"，这个表达式的值就是默认导出值。
 *   2. 默认导出本质上是名为 "default" 的具名导出，只是语法上被特殊对待。
 *   3. 导入默认导出时名字由导入方自己决定（任意命名）。
 * ============================================================================
 */

/**
 * 一个配置对象。把它作为默认导出，是因为"一个模块只导出一件事"是最常见的约定。
 */
const config = {
  appName: 'javascript-examples',
  version: '1.0.0',
  debug: true,
  locale: 'zh-CN',
  maxRetries: 3,
};

// ---------------------------------------------------------------------------
// 具名导出：和默认导出共存，这个模块就是"混合导出"模块
// ---------------------------------------------------------------------------

// 真实项目里很常见：主体是一个大对象（默认导出），
// 再额外挂几个独立的常量（具名导出）方便按需引入。
export const CONFIG_VERSION = '1.0.0';
export const DEFAULT_LOCALE = 'zh-CN';

/**
 * 把配置对象转成一行可读字符串，演示"具名导出的函数也能操作默认导出的对象"
 * @returns {string}
 */
export function describeConfig() {
  return `${config.appName}@${config.version} (debug=${config.debug})`;
}

// ---------------------------------------------------------------------------
// 默认导出
// ---------------------------------------------------------------------------

// 这是本模块的默认导出。
// 注意：export default 后面写的是一个"值/表达式"，而不是声明语句，
// 所以这里不能写成 export default const config = {...}（那是语法错误）。
export default config;
