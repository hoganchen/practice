// ============================================================================
// 知识点: 切片传参改写的性能对比 (被测函数)
//
// 说明:
// - 对比改写调用方切片头的两种主流写法的运行时开销:
//   A. 传切片指针 *[]T            B. 返回新切片由调用方接收
// - 两者都不产生堆分配, 差异只来自"切片头怎么传递"
// - 每种写法各留一份禁止内联版本, 用于隔离真实函数调用时的调用约定开销
// - 基准测试代码在 04_bench_slice_pass_test.go, 用法说明见该文件头部
//
// 编译和运行:
//   go test ./29_testing/ -bench=Slice -benchmem
// ============================================================================

package main

// 写法 A: 传切片指针, 通过 *s 改写调用方的切片头
func appendViaPtr(s *[]int, v int) { *s = append(*s, v) }

// 写法 B: 返回新切片, 由调用方赋值接收 (Go 官方风格, 如 append / slices.Delete)
func appendReturn(s []int, v int) []int { return append(s, v) }

// 下面两个 noinline 版本强制走真实函数调用, 用于隔离出"调用约定"本身的开销,
// 与上面允许内联的版本形成对照。
//
// "//go:noinline" 是编译器指令而非注释: 它告诉编译器"这个函数永远不要内联"。
// 上面两个函数只有两行, 默认必然被内联; 一旦内联, 切片头全程待在寄存器里,
// A/B 两种写法编出的代码就没差别了, 那组 benchmark 也就失去意义。
//
// 三条语法规则:
//   - "//" 后面绝对不能有空格。有无空格是"指令"与"普通注释"的分界, 而编译器
//     不报错、指令静默失效 -- 只有 gopls 会提示 extraneous space, go vet 不报。
//     实测带空格的版本照样被判定为 can inline, 指令等于白写
//   - 必须紧挨函数声明之前, 但中间隔空行不影响 (实测跨空行仍生效,
//     解析器会向前扫描到最近的声明)
//   - 只能作用于函数声明, 含方法; 不能作用于函数字面量
//
// 怎么确认生效: 要用 -m -m, 普通 -m 只对"能"内联的函数打 can inline, 被指令
// 挡住的什么都不说, 你分不清是"被禁止"还是"只是超了预算":
//   go build -gcflags='-m -m' ./29_testing/
//   -> cannot inline appendViaPtrNI: marked go:noinline
//
// 别在业务代码里拿它做性能优化: 除了多一次调用, 还会丢掉常量传播、边界检查
// 消除等内联带来的连锁优化, 通常反而更慢。想让它快是让它更容易内联, 不是相反

//go:noinline
func appendViaPtrNI(s *[]int, v int) { *s = append(*s, v) }

//go:noinline
func appendReturnNI(s []int, v int) []int { return append(s, v) }
