// ============================================================
// Rust 知识点：变量绑定 —— let 关键字
// Rust 中变量默认不可变（immutable），这是安全性的核心设计
// 编译：rustc 001_variable_binding.rs && .\001_variable_binding.exe
// ============================================================

fn main() {
    // `let` 声明一个变量绑定
    // 变量默认是「不可变」的
    let x = 5;
    println!("x 的值是：{}", x);
    // x = 6; // 编译错误！不能修改不可变变量

    // `mut` 关键字使变量可变
    let mut y = 10;
    println!("y 初始值：{}", y);
    y = 20; // 可以修改，因为 y 是可变的
    println!("y 修改后：{}", y);

    // 变量必须先绑定后使用
    // let z; // 仅声明但不初始化在后续使用时会报错
    // println!("{}", z); // 编译错误：使用了未初始化的变量

    // 变量可以只声明但暂不赋值（需要显式标注类型）
    let z: i32;
    z = 42; // 在使用前赋值即可
    println!("z 的值：{}", z);

    // 变量命名规范：snake_case（小写蛇形命名）
    let my_variable_name = 100;
    println!("{}", my_variable_name);
}
