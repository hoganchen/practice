// ============================================================
// Rust 知识点：变量遮蔽（Shadowing）
// 允许在同一作用域中复用变量名，遮蔽之前的变量
// 遮蔽不同于 mut，它会创建新的绑定（可改变类型）
// 编译：rustc 002_shadowing.rs && .\002_shadowing.exe
// ============================================================

fn main() {
    // 原始绑定
    let x = 5;
    println!("第一次绑定：{}", x);

    // 遮蔽：用 let 重新声明同名变量
    let x = x + 1;
    println!("第二次绑定（遮蔽后）：{}", x);

    // 遮蔽可以改变类型 —— 这是 mut 做不到的！
    let x = "现在变成了字符串";
    println!("第三次绑定（类型已变）：{}", x);

    // 在内部作用域中遮蔽
    let y = 1;
    {
        let y = 99; // 内部作用域的遮蔽，不影响外部
        println!("内部 y：{}", y); // 99
    }
    println!("外部 y：{}", y); // 1（不受内部影响）

    // 遮蔽 vs mut 的关键区别：
    let mut z = "hello";
    // z = 42;    // 编译错误！mut 不能改变类型
    z = "world"; // 但可以改变值
    println!("可变变量 z：{}", z);
}
