// ============================================================
// Rust 知识点：整数类型 —— 有符号/无符号，固定宽度
// Rust 是静态强类型语言，每个变量都有确定的类型
// 编译：rustc 001_integer_types.rs && .\001_integer_types.exe
// ============================================================

fn main() {
    // ---- 有符号整数（可正可负） ----
    let i: i8 = -128;        // 8 位，范围 [-128, 127]
    let i16_val: i16 = -32768;   // 16 位
    let i32_val: i32 = -2147483648; // 32 位（默认整数类型）
    let i64_val: i64 = -9223372036854775808; // 64 位
    let i128_val: i128 = -170141183460469231731687303715884105728; // 128 位

    // ---- 无符号整数（仅非负） ----
    let u: u8 = 255;          // 8 位，范围 [0, 255]
    let u16_val: u16 = 65535;
    let u32_val: u32 = 4294967295;
    let u64_val: u64 = 18446744073709551615;
    let u128_val: u128 = 340282366920938463463374607431768211455;

    // ---- 平台相关整数 ----
    let isize_val: isize = -100; // 指针大小，32位系统=32bit，64位系统=64bit
    let usize_val: usize = 100;  // 同上，通常用作数组/切片索引

    // ---- 数字字面量语法 ----
    let decimal = 98_222;       // 十进制（下划线分隔，提高可读性）
    let hex = 0xff;             // 十六进制（0x 前缀）
    let octal = 0o77;           // 八进制（0o 前缀）
    let binary = 0b1111_0000;   // 二进制（0b 前缀）
    let byte = b'A';            // 字节字面量（仅 u8）

    // ---- 类型推断 ----
    // 如果不标注类型，默认整数类型为 i32
    let guess = 42; // 类型是 i32

    println!("i8: {}, u8: {}", i, u);
    println!("i16: {}, u16: {}", i16_val, u16_val);
    println!("i32: {}, u32: {}", i32_val, u32_val);
    println!("十六进制 0xff = {}", hex);
    println!("二进制 0b1111_0000 = {}", binary);
    println!("字节 b'A' = {}", byte);
    println!("isize: {}, usize: {}", isize_val, usize_val);
    println!("默认整数类型（i32）：{}", guess);

    // ---- 溢出行为 ----
    // debug 模式下溢出会 panic，release 模式下执行环绕操作
    // 使用 wrapping_* 或 saturating_* 等显式方法处理
    let sum = 200u8.wrapping_add(100); // 环绕加法：300 % 256 = 44
    println!("200 + 100 环绕后 = {}", sum);
}
