// ============================================================
// Rust 知识点：Hello World —— 第一个 Rust 程序
// 每个 Rust 程序从 main 函数开始执行
// 编译：rustc 001_hello_world.rs && .\001_hello_world.exe
// ============================================================

// `fn` 用于声明函数；`main` 是程序的入口点
fn main() {
    // `println!` 是一个宏（macro），用于在控制台输出文本并换行
    // 字符串字面量用双引号 `"..."` 包裹
    println!("Hello, World!");

    // 也可以使用 `print!`（不换行）
    print!("Hello, ");
    print!("Rust!\n"); // \n 是换行转义符
}
