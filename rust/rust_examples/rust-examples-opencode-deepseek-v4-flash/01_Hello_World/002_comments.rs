// ============================================================
// Rust 知识点：注释 —— 代码文档与说明
// Rust 有三种注释形式：行注释、文档注释、模块文档注释
// 编译：rustc 002_comments.rs && .\002_comments.exe
// ============================================================

/// 文档注释（三斜线），用于生成 API 文档
/// 描述函数的功能，支持 Markdown 格式
fn documented_function() {
    println!("这是一个有文档注释的函数");
}

//! 模块级文档注释（//!），通常放在文件开头
//! 用于描述当前文件或模块的用途

fn main() {
    // 行注释：双斜线开头，到行尾结束（最常用）

    /*
     * 块注释：/* ... */ 可跨行
     * 常用于临时屏蔽大段代码
     */

    // 调用文档注释的函数
    documented_function();

    println!("注释本身不会被编译执行");
}
