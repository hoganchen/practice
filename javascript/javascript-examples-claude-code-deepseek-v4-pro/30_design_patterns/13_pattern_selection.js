// ❌ 过度设计版：策略表 + 上下文 + 工厂 + 注册表，一共 4 个概念
const GreetingStrategies = new Map([
  ['admin', { greet: (name) => `管理员 ${name}，您好` }],
  ['user', { greet: (name) => `用户 ${name}，您好` }],
]);
class GreetingStrategyFactory {
  static create(role) {
    const s = GreetingStrategies.get(role);
    if (!s) throw new RangeError(`未知角色 ${role}`);
    return s;
  }
}
class GreetingContext {
  constructor(role) {
    this.strategy = GreetingStrategyFactory.create(role);
  }
  greet(name) {
    return this.strategy.greet(name);
  }
}
const overEngineered = new GreetingContext('admin').greet('张三');

// ✅ 刚好够用版：一个函数 + 一个默认值
function greet(role, name) {
  // 分支少、且不会频繁变化时，直接判断最清楚
  return `${role === 'admin' ? '管理员' : '用户'} ${name}，您好`;
}
const justRight = greet('admin', '张三');

console.log('  过度设计版结果：', overEngineered, `（用了 ${'GreetingStrategies + Factory + Context'} 共 3 个概念、约 15 行）`);
