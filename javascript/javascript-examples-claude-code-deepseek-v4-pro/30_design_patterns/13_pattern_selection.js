/**
 * ============================================================================
 * 知识点：模式选择指南 —— 12 个模式的适用场景对照与"不要过度设计"
 * ============================================================================
 *
 * 【所属分类】30_design_patterns —— 设计模式
 * 【难度等级】入门
 * 【前置知识】30_design_patterns/01_module_pattern.js ~ 12_chain_of_responsibility.js
 *
 * 【知识点说明】
 *
 * 1. 是什么
 *    本文件是整个 30_design_patterns 目录的"索引与收口"：
 *      (a) 用对齐表格给出 12 个模式各自的"解决什么问题 / 适用 / 不适用 / 替代方案"；
 *      (b) 用一棵"决策树"回答"我该用哪个"；
 *      (c) 重点讲**不要过度设计**：YAGNI、模式是沟通词汇而非目标、
 *          先写能跑的代码再重构、间接层的成本、什么时候简单函数就够了；
 *      (d) 介绍"反模式"（Anti-Pattern）的概念与几个常见反模式。
 *
 * 2. 为什么需要
 *    学完 12 个模式之后，最常见的失败不是"不会用"，而是"到处用"：
 *      - 看到两个 if 就想抽策略；
 *      - 看到一层包装就想叫装饰器；
 *      - 给只有 3 个接口的服务写了一整套中间件框架 + DI 容器 + 事件总线。
 *    这份指南的全部目的，就是给你一套"**什么时候不用**"的判断标准。
 *    设计模式的价值是**沟通词汇**与**经验沉淀**，不是目标本身。
 *
 * 3. 核心语法要点（本文件不讲代码语法，这里的"语法"是**判断规则**）
 *    本文件是收口与索引，没有新的 JS 语法要点。取而代之，下面这六条
 *    是选择模式时真正要遵守的"语法"——违反了它们，模式就会变成负债：
 *    - 模式是对"反复出现的结构"的命名。命名让沟通变快，但不改变代码的复杂度 ——
 *      它只是把复杂度**转移**到了更合适的地方。
 *    - 每一个模式都引入至少一层间接（函数、对象、接口）。
 *      间接层的收益是"可替换/可扩展"，成本是"更难读、更难调、更多文件"。
 *      收益 > 成本才用。
 *    - YAGNI（You Aren't Gonna Need It）：不要为"将来可能需要"而设计。
 *      那个将来有 80% 的概率不会来，而成本是 100% 立刻支付。
 *    - 三行相似代码 > 一个过早的抽象。抽象的代价是耦合，
 *      而重复的代价只是多打几个字（Sandi Metz 的"重复比错误的抽象便宜"）。
 *    - 重构的时机是"痛点出现第二次"（Rule of Three：第三次重复时再抽象）。
 *    - 模式应该**在重构中被发现**，而不是在写第一版时被设计进去。
 *
 * 4. 常见陷阱（过度设计的具体表现）
 *    - 为 3 个接口引入中间件框架、DI 容器、事件总线 —— 架构宇航员。
 *    - 只有一个实现却写成"接口 + 实现"两套（Java 后遗症）。
 *    - 把所有 if 都改成策略表，代码反而更长。
 *    - 用设计模式互相套娃（工厂造建造者造策略），没人能读懂调用链。
 *    - 在脚手架/模板里预置一堆"以后会用到"的抽象层。
 *    - 把"用了多少模式"当成代码质量的指标。
 *
 * 【运行方法】
 *   在仓库根目录执行：node 30_design_patterns/13_pattern_selection.js
 *
 * 【预期输出】
 *   打印若干张对齐表格：12 个模式速查表、决策树、成本收益对照、常见反模式清单，
 *   并用可运行的小例子对比"过度设计"与"刚好够用"两种写法。
 * ============================================================================
 */

