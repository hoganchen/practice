// 5. 过度设计的成本：一个可量化的例子
// ===========================================================================

console.log('\n--- 5. 间接层的成本（可量化的部分） ---');

/** 直接调用：一层函数 */
function directParse(text) {
  return Number.parseInt(text, 10);
}

/** 过度包装：工厂 + 策略 + 装饰器三层（仅为演示成本） */
const parseStrategies = { int: (t) => Number.parseInt(t, 10) };
function withParseLogging(fn) {
  return (...args) => fn(...args); // 只为了演示多一层调用
}
function createParser(kind) {
  const base = parseStrategies[kind];
  if (!base) throw new RangeError(`未知解析器 ${kind}`);
  return withParseLogging(base);
}
const wrappedParse = createParser('int');

const N = 300_000;
const input = '12345';

let t0 = performance.now();
for (let i = 0; i < N; i += 1) directParse(input);
let t1 = performance.now();
for (let i = 0; i < N; i += 1) wrappedParse(input);
let t2 = performance.now();

console.log(`  ${N} 次调用：直接版 ${(t1 - t0).toFixed(2)}ms，三层包装版 ${(t2 - t1).toFixed(2)}ms`);
console.log(`  慢约 ${((t2 - t1) / Math.max(t1 - t0, 0.001)).toFixed(2)} 倍。`);
console.log(`  结论：单次调用只差几纳秒，绝大多数场景可以忽略 ——
  **但这里要说的是另一件事**：性能不是主要成本，"理解成本"才是。
  读 wrappedParse 的人要多跳 3 个地方，才能确认"它其实就是 parseInt"。
  如果这段代码有 200 处调用，那么每一次阅读都要付出这个成本。
  这就是"间接层税"：你为可扩展性付费，代价是所有人的阅读时间。`);

