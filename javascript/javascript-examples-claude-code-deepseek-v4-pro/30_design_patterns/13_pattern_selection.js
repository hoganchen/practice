console.log('\n--- 6. 不要过度设计：五条忠告 ---');

console.log(`
  【忠告 1】YAGNI —— You Aren't Gonna Need It
    不要为"将来可能需要"而写代码。将来那个需求有 80% 概率不会来，
    而设计成本是 100% 现在就要付。等它真的来了再改，通常只要半小时。

  【忠告 2】模式是"沟通词汇"，不是"目标"
    "这里我们用策略模式"这句话的价值在于**让同事 3 秒内理解结构**，
    而不是"我们用了模式所以代码更高级"。
    如果一句话能说清楚，就不需要用模式来表达。

  【忠告 3】先写能跑的代码，再重构出模式
    第一版就设计模式，通常是"猜错了方向"的模式 ——
    因为你还不了解真正的变化点在哪。
    正确的顺序：写朴素版 → 痛点出现（改第 3 次）→ 重构出模式。
    这就是"Rule of Three"：第三次重复时才是抽象的时机。

  【忠告 4】数一数间接层的数量
    每次想要加一层（函数包装、接口、抽象类），先问：
      "这一层删掉，代码会坏吗？"
    如果答案是"不会，只是没那么优雅"，那就删掉它。
    可读性 > 优雅。

  【忠告 5】简单函数就够了的时候
    以下情况，一个函数（或一个纯函数 + 一个默认值）永远是最优解：
      - 逻辑只有几行；
      - 只会在一个地方使用；
      - 变化方向不明确；
      - 没有跨模块复用的需求；
      - 团队里其他人不熟悉设计模式（引入模式反而增加沟通成本）。

  一句话总纲：
    **模式的价值 = 它消除了多少痛苦 - 它引入了多少间接。**
    任何一个模式，当它消除的痛苦小于引入的间接时，它就是负资产。`);

