/**
 * ============================================================================
 * 知识点：前瞻 (?=) (?!) 与后顾 (?<=) (?<!) 断言
 * ============================================================================
 *
 * 【所属分类】13_regexp —— 正则表达式
 * 【难度等级】高级
 * 【前置知识】13_regexp/05_groups_and_alternation.js、13_regexp/07_named_groups.js
 *
 * 【知识点说明】
 *
 * 1. 是什么
 *    环视（lookaround，也叫"零宽断言"）让我们"看一眼旁边有没有某种模式"，
 *    但这个"看一眼"不消耗字符，最终匹配结果里不含它匹配的内容。
 *    四种形态：
 *      (?=...)    正向前瞻（lookahead）：右边必须能匹配 ...
 *      (?!...)    负向前瞻：右边不能匹配 ...
 *      (?<=...)   正向后顾（lookbehind）：左边必须能匹配 ...
 *      (?<!...)   负向后顾：左边不能匹配 ...
 *    它们和 ^ $ \b 属于同一家族：都只对"位置"提条件，宽度为 0。
 *
 * 2. 为什么需要
 *    很多规则是"条件式"的，用普通模式没法表达：
 *      · 密码必须"同时包含"大写、小写、数字 —— 字符出现顺序不定，普通量词做不到
 *      · 数字加千分位：只在"后面正好还有 3 的倍数个数字"的位置插入逗号
 *      · 取出 "价格是 100 元" 里的 100，但不要 "编号 100"
 *      · 屏蔽日志里的密码：替换 key=xxx 中 = 之后、空格之前的内容
 *    这些"只看不取"的需求，环视是唯一优雅的解法。
 *
 * 3. 核心语法要点
 *    (1) 环视是零宽的：[0] 里看不到断言匹配到的内容，index 也不会因为它而移动。
 *    (2) 断言内部可以有完整的正则（分组、量词、分支、甚至嵌套断言）。
 *    (3) JS（V8）支持"变长后顾"：/(?<=ab+)c/ 是合法的，
 *        这是 JS 相对其他语言的一个优势（其他语言常要求后顾等长）。
 *    (4) 断言里捕获的分组，在 JS 里是能通过 exec 的返回值读到的（虽然平时很少这么用）。
 *    (5) 负向断言与量词一起吃字符时要小心："不吃字符"意味着你可以用 `(?=...)` 在
 *        同一位置反复做判断，而不是"消费"掉文本。
 *
 * 4. 常见陷阱
 *    (1) 把前瞻和后顾写反：`(?=x)` 看的是右边，"前"指的是"匹配位置的前方（右侧）"。
 *    (2) 断言里写量词但忘了它不消耗字符，导致整体匹配长度为 0。
 *    (3) 负向断言用得太多会让可读性急剧下降，且是回溯开销的重灾区。
 *    (4) 后顾里出现 `^` 只在无 m 时表示串首；有 m 时表示行首，容易与预期不符。
 *    (5) 分不清 [^"]* 与 (?!") 的适用场景：前者描述"字符本身"，后者描述"位置"。
 *
 * 【运行方法】
 *   在仓库根目录执行：node 13_regexp/08_lookahead_lookbehind.js
 *
 * 【预期输出】
 *   逐类演示四种断言的匹配位置与结果，并用"密码强度校验""千分位""安全脱敏"
 *   三个实战把断言组合起来使用。
 * ============================================================================
 */

/** 打印所有匹配及其位置 */
function show(label, re, str) {
  const flags = re.flags.includes('g') ? re.flags : re.flags + 'g';
  const g = new RegExp(re.source, flags);
  const out = [];
  let m;
  while ((m = g.exec(str)) !== null) {
    out.push(`"${m[0]}"@${m.index}`);
    if (m[0] === '') g.lastIndex++;
  }
  console.log(`  ${label} → ${out.length} 处：${out.join('  ') || '（无）'}`);
}

console.log('--- 1. 正向前瞻 (?=...)：右边必须是这个 ---');

const prices = '苹果 12 元，香蕉 5 元，进口苹果 30 元';

// 逐符号解释 /苹果(?= )/：
//   苹果     字面文本
//   (?= )    正向前瞻：要求右边紧跟着一个空格，但这个空格不进入匹配结果
show('苹果(?= ) 后跟空格', /苹果(?= )/, prices);
console.log('  注意匹配结果只有 "苹果" 两个字，后面的空格虽然参与了判断，却没有被消耗。');

// 取"价格数字"，但只取"元"前面的那个数字。
// 逐符号解释 /\d+(?=\s*元)/：
//   \d+       一个或多个数字（这部分会被匹配到）
//   (?=\s*元) 正向前瞻：右边允许有若干空白，然后再跟一个"元"字（这部分不进入结果）
show('\\d+(?=\\s*元) 只取元前面的数字', /\d+(?=\s*元)/, prices);

// 对照：不用前瞻就要把"元"也吃进结果，后续还得自己剥掉。
show('\\d+\\s*元（把单位也吃进来了）', /\d+\s*元/, prices);

console.log('--- 2. 负向前瞻 (?!...)：右边不能是这个 ---');

// 最干净的用法：放在锚点后面，做"整串校验"。
// 逐符号解释 /^(?!0)\d+$/：
//   ^          串首
//   (?!0)      负向前瞻：右边不能是字符 0 —— 也就是"不能以 0 开头"
//   \d+        一个或多个数字
//   $          串尾
const noLeadZero = /^(?!0)\d+$/;
for (const v of ['123', '0', '0123', '10']) {
  console.log(`    ${JSON.stringify(v).padEnd(8)} → ${noLeadZero.test(v) ? '通过' : '拒绝'}`);
}
console.log('  断言放在锚点之后、消费字符之前，是最不容易出错的位置。');

// 简单版本：只在"后面不是数字"的位置匹配，等价于"数字串的最后一个字符"。
show('\\d(?!\\d) 只匹配数字串的最后一个数字', /\d(?!\d)/, '123 4567 89');

// 陷阱示范：把负向前瞻和贪婪量词放在一起，会出现"回溯绕过断言"的诡异结果。
const mixed = '编号 100，价格 200 元，重量 300 克';
console.log('  文本 =', mixed);
show('\\d+(?!元) —— 只看紧接着的一个字符', /\d+(?!元)/, mixed);
show('\\d+(?!\\s*元) —— 想排除"带单位的数字"，结果翻车', /\d+(?!\s*元)/, mixed);
console.log('  翻车原因（很重要）：面对 "200 元"，贪婪的 \\d+ 先吃掉 "200"，');
console.log('    此时前瞻发现右边是 " 元"，断言失败；正则于是回溯，把 \\d+ 缩成 "20"，');
console.log('    这时右边剩下 "0 元"，它并不匹配 \\s*元，断言通过了 —— 于是匹配出 "20"。');
console.log('  结论：负向断言 + 可回溯的量词 = 结果取决于回溯路径，必须特别警惕。');
console.log('  修法：给数字加上词边界约束，例如 /\\b\\d+\\b(?!\\s*元)/ 或改用后顾来判断左边。');

console.log('--- 3. 正向后顾 (?<=...)：左边必须是这个 ---');

const currency = '￥1200 和 $800 和 ￥45';

// 逐符号解释 /(?<=￥)\d+/：
//   (?<=￥)  正向后顾：要求左边紧挨着一个"￥"符号（不进入结果）
//   \d+      一个或多个数字（这才是匹配结果）
show('(?<=￥)\\d+ 只取￥后面的数字', /(?<=￥)\d+/, currency);
show('(?<=\\$)\\d+ 只取$后面的数字', /(?<=\$)\d+/, currency);

// 变长后顾：JS 允许后顾里的量词长度不固定。
// 逐符号解释 /(?<=￥\s*)\d+/：左边是"￥"以及可能存在的空格。
show('(?<=￥\\s*)\\d+ 变长后顾', /(?<=￥\s*)\d+/, currency);
console.log('  说明：变长后顾是 JS(V8) 的能力，Python 的 re 在旧版本里会直接报错。');

console.log('--- 4. 负向后顾 (?<!...)：左边不能是这个 ---');

const ids = '$100 和 200 元 和 $300';

// 目标：取出"不是以 $ 开头"的数字。
// 干净的写法是给数字加上词边界，让引擎不能从数字串中间重新起步。
// 逐符号解释 /(?<!\$)\b\d+\b/：
//   (?<!\$)   负向后顾：左边不能是美元符号
//   \b        单词边界
//   \d+       一个或多个数字
//   \b        单词边界
show('(?<!\\$)\\b\\d+\\b 正确写法', /(?<!\$)\b\d+\b/, ids);

// 去掉词边界就会翻车：引擎可以从 "100" 的第二个字符处重新尝试。
// 逐符号解释 /(?<!\$)\d+/：
//   (?<!\$)  负向后顾：左边不能是美元符号
//   \d+      一个或多个数字
show('(?<!\\$)\\d+ 掉了词边界的后果', /(?<!\$)\d+/, ids);
console.log('  翻车原因："$100" 从 $ 后面开始时后顾失败，引擎就往后挪一格，');
console.log('    从 "00" 开始重新匹配 —— 此时左边是 "1" 而不是 "$"，断言通过，于是抠出了 "00"。');
console.log('  这与上一节"负向前瞻被回溯绕过"是同一类问题：断言只管"某个起点"，');
console.log('    而引擎会不断更换起点，所以要用 \\b、^、$ 把起点锁死。');

console.log('--- 5. 环视是零宽的：用 exec 看清 index 与结果 ---');

const s = 'foo123';
const lookaheadM = /foo(?=\d+)/.exec(s);
console.log('  /foo(?=\\d+)/ 对 "foo123" =>',
  JSON.stringify(lookaheadM[0]), '，index =', lookaheadM.index, '，长度 =', lookaheadM[0].length);
console.log('  说明：虽然 (?=\\d+) 检查了 3 个数字，但匹配结果仍只有 "foo"，长度 3。');

const lookbehindM = /(?<=foo)\d+/.exec(s);
console.log('  /(?<=foo)\\d+/ 对 "foo123" =>',
  JSON.stringify(lookbehindM[0]), '，index =', lookbehindM.index, '，长度 =', lookbehindM[0].length);
console.log('  说明：后顾检查了左边的 foo，但匹配从 f 之后的 3 号位置开始，结果只有 "123"。');

console.log('--- 6. 实战一：密码强度校验（多个条件同时满足） ---');

// 用一串"零宽前瞻"逐条提出要求，最后再用 .+ 真正消费掉整串。
// 逐符号解释 /^(?=.*[a-z])(?=.*[A-Z])(?=.*\d)[A-Za-z\d@$!%*?&]{8,}$/：
//   ^                                从头开始
//   (?=.*[a-z])                      前瞻：从当前位置往后某处必须有一个小写字母
//   (?=.*[A-Z])                      前瞻：往后某处必须有一个大写字母
//   (?=.*\d)                         前瞻：往后某处必须有一个数字
//   [A-Za-z\d@$!%*?&]{8,}            真正的"消费"部分：允许的字符，至少 8 个
//   $                                直到结尾
const strongPwd = /^(?=.*[a-z])(?=.*[A-Z])(?=.*\d)[A-Za-z\d@$!%*?&]{8,}$/;

const pwdCases = ['abc12345', 'Abc12345', 'ABCD1234', 'Abcdefgh', 'Ab1', 'Abc12345!', 'Abc 12345'];
console.log('  正则 =', strongPwd);
for (const p of pwdCases) {
  console.log(`    ${JSON.stringify(p).padEnd(14)} → ${strongPwd.test(p) ? '通过' : '拒绝'}`);
}
console.log('  特点：三段前瞻的顺序与字符实际出现的顺序无关，因为它们都从同一个起点向后看。');

// 想更精确地知道"缺哪一条"，就拆成多条小正则分别测试，可读性也更好。
const rules = [
  ['至少一个小写字母', /[a-z]/],
  ['至少一个大写字母', /[A-Z]/],
  ['至少一个数字', /\d/],
  ['长度至少 8 位', /^.{8,}$/],
];
for (const p of ['abc12345', 'Abc12345']) {
  const missed = rules.filter(([, re]) => !re.test(p)).map(([name]) => name);
  console.log(`    ${JSON.stringify(p)} 未满足：${missed.length ? missed.join('、') : '全部满足'}`);
}

console.log('--- 7. 实战二：数字千分位分隔符 ---');

// 逐符号解释 /(?<=\d)(?=(\d{3})+$)/g：
//   (?<=\d)        后顾：左边必须是一个数字（避免在开头插入逗号）
//   (?=(\d{3})+$)  前瞻：从当前位置到结尾，必须正好是 3 的倍数个数字
//                  （这里的 (...) 只是为了分组，方便 + 作用于 \d{3} 整组）
//   g              在所有满足条件的位置插入
const thousands = /(?<=\d)(?=(\d{3})+$)/g;

const numbers = ['1234', '1234567', '123', '1234567890'];
for (const n of numbers) {
  console.log(`    ${n.padEnd(12)} → ${n.replace(thousands, ',')}`);
}
console.log('  原理：正则引擎在每个字符间隙试一次，只有"左边是数字"且"右边恰好剩 3 的倍数个数字"');
console.log('        的位置才会被替换成逗号，而且这些位置本身宽度为 0，不会吃掉任何字符。');

// 支持小数的版本：只处理整数部分。
// 逐符号解释 /(?<=\d)(?=(\d{3})+(\.|$))/g：
//   (?=(\d{3})+(\.|$))  前瞻：右边是 3 的倍数个数字，然后要么遇到小数点，要么到结尾
const thousandsDecimal = /(?<=\d)(?=(\d{3})+(\.|$))/g;
for (const n of ['1234567.891', '9876.5', '100']) {
  console.log(`    ${n.padEnd(14)} → ${n.replace(thousandsDecimal, ',')}`);
}

console.log('--- 8. 实战三：日志脱敏（把敏感值换成星号） ---');

const logText = 'user=alice password=s3cr3t token=abc123 ip=10.0.0.1';

// 逐符号解释 /(?<=password=)\S+/g：
//   (?<=password=)  后顾：左边必须是 "password="
//   \S+             一个或多个非空白字符（也就是密码值本身）
//   g               全部替换
const maskPassword = /(?<=password=)\S+/g;
console.log('  原文   =', logText);
console.log('  脱敏后 =', logText.replace(maskPassword, '******'));

// 更通用：把"key=value"里的 value 全部打码，但保留 key。
// 逐符号解释 /(?<==)[^\s&]+/g：后顾要求左边是等号，然后取一段非空白非 & 的字符。
const maskAllValues = /(?<==)[^\s&]+/g;
console.log('  全部打码 =', logText.replace(maskAllValues, '***'));

console.log('--- 9. 断言里也能做捕获（JS 支持，但少用） ---');

// 在 JS 里，断言内部的分组同样会被记录进结果数组。
const inner = /(?=(\d{3}))\d+/.exec('123456');
console.log('  /(?=(\\d{3}))\\d+/ 对 "123456"：');
console.log('    整体匹配 [0] =', JSON.stringify(inner[0]));
console.log('    前瞻内部捕获 [1] =', JSON.stringify(inner[1]), '（前瞻只"看"了 3 位，没消费）');

console.log('--- 10. 陷阱：断言不消耗字符，可能造成空匹配 ---');

// /(?=\d)/ 只判断"右边是数字"，本身宽度为 0，所以每个数字前都会产生一次空匹配。
const emptyM = [];
const g = /(?=\d)/g;
let mm;
let guard = 0;
while ((mm = g.exec('a1b2')) !== null && guard++ < 10) {
  emptyM.push(`@${mm.index}`);
  g.lastIndex++; // 防止空匹配造成死循环
}
console.log('  /(?=\\d)/g 在 "a1b2" 的匹配位置 =', emptyM.join(' '), '（都是空匹配）');
console.log('  实战中请用 /\\d/ 直接匹配，而不是用前瞻去"看"数字，除非你确实需要位置。');

console.log('--- 11. 小结 ---');
console.log('· (?=) 看右边必须有，(?!) 看右边必须没有。');
console.log('· (?<=) 看左边必须有，(?<!) 看左边必须没有。');
console.log('· 四种断言都是零宽：不消耗字符、不出现在结果里、不改变 index。');
console.log('· 多个前瞻串起来，就能表达"多个条件同时成立"的校验规则。');
console.log('· JS 支持变长后顾，这是它比不少语言更灵活的地方。');
