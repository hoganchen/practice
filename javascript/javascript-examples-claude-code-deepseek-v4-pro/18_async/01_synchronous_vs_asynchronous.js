/**
 * ============================================================================
 * 知识点：同步阻塞 vs 异步非阻塞 —— 用 setTimeout 看清执行顺序
 * ============================================================================
 *
 * 【所属分类】18_async —— 异步编程
 * 【难度等级】入门
 * 【前置知识】06_functions/01_declaration_vs_expression.js
 *
 * 【知识点说明】
 *
 * 1. 是什么
 *    - 同步（synchronous）：一行代码执行完，才轮到下一行。如果某行很慢，
 *      整个程序就"卡"在那里等，这叫阻塞（blocking）。
 *    - 异步（asynchronous）：把耗时操作交出去，注册一个"完成后的回调"，
 *      当前代码不等它，直接继续往下执行；等操作完成后再回来执行回调，
 *      这叫非阻塞（non-blocking）。
 *    在 Node.js 里，setTimeout / 文件读写 / 网络请求都是异步的。
 *
 * 2. 为什么需要
 *    JS 只有一个主线程（单线程）。如果所有操作都同步执行，一次网络请求
 *    就会让整个程序的界面/服务卡死。异步把"等待"这件事从主线程上挪走，
 *    让 CPU 时间内可以处理别的事情。
 *
 * 3. 核心语法要点
 *    - setTimeout(fn, ms) 把 fn 排进"定时器队列"，至少 ms 毫秒后执行；
 *      它不阻塞当前代码，返回值是一个定时器 ID。
 *    - 回调函数不是立即执行的，而是"稍后由事件循环调度执行"。
 *    - 同步代码永远优先于异步回调执行，哪怕延迟写 0。
 *    - 长时间运行的同步循环会拖慢（甚至冻结）整个进程，
 *      也会把定时器的实际触发时间一起往后推。
 *
 * 4. 常见陷阱
 *    - 以为 setTimeout(fn, 0) 会立刻执行：它至少等到本次同步代码全部跑完。
 *    - 以为 ms 是"精确延迟"：它只是"最早可以执行的时刻"，
 *      前面有同步阻塞时会明显延后。
 *    - 在异步回调外面直接用回调内部赋的变量（此时还没执行到）。
 *
 * 【运行方法】
 *   在仓库根目录执行：node 18_async/01_synchronous_vs_asynchronous.js
 *
 * 【预期输出】
 *   带编号的日志，清楚显示"同步先全部执行完，异步回调最后才执行"。
 * ============================================================================
 */

// ---------------------------------------------------------------------------
// 1. 同步：自上而下，一行接一行
// ---------------------------------------------------------------------------

console.log('--- 1. 同步执行：自上而下 ---');

console.log('同步 1：开始');
console.log('同步 2：中间的同步代码');
console.log('同步 3：结束');

// 这三行严格按顺序执行，没有任何悬念。

// ---------------------------------------------------------------------------
// 2. 异步：setTimeout 不阻塞后面的代码
// ---------------------------------------------------------------------------

console.log('\n--- 2. 异步非阻塞：setTimeout 后代码继续跑 ---');

console.log('A 同步：注册定时器之前');

// 关键：这一行只是"登记"了一个 10 毫秒后要执行的回调，然后立刻返回。
// 它不会在这里等 10 毫秒，所以下一行马上就会打印。
setTimeout(() => {
  console.log('E 异步：定时器回调（10ms 后）');
}, 10);

console.log('B 同步：注册定时器之后');
console.log('C 同步：脚本主体结束');

// 输出顺序是 A、B、C、E。
// 为什么 E 最后？因为主线程要先把手上的同步代码全部执行完，
// 事件循环才会回头去看"有没有到期的定时器回调"。

// ---------------------------------------------------------------------------
// 3. 延迟写 0 也一样：同步优先
// ---------------------------------------------------------------------------

console.log('\n--- 3. 延迟为 0 也不等于立刻执行 ---');

console.log('F 同步：注册 0 毫秒定时器之前');

setTimeout(() => {
  console.log('I 异步：0 毫秒定时器回调');
}, 0);

// 微任务（Promise.then）比定时器更早，这里先埋一个伏笔，
// 详细机制见 18_async/02_event_loop_basics.js
Promise.resolve().then(() => {
  console.log('H 微任务：Promise.then 回调');
});

console.log('G 同步：注册 0 毫秒定时器之后');
// 输出顺序是 F、G、H、I：
//   H 是微任务，在本轮同步代码结束后立即执行；
//   I 是宏任务，要等到下一个事件循环轮次。

// ---------------------------------------------------------------------------
// 4. 同步阻塞会拖慢一切
// ---------------------------------------------------------------------------

console.log('\n--- 4. 同步阻塞的代价 ---');

const blockStart = Date.now();

// 注册一个"10 毫秒后"的定时器
setTimeout(() => {
  // 回调真正执行的时刻被前面那段同步阻塞推后了
  console.log(`K 异步：定时器回调实际在 ${Date.now() - blockStart}ms 才执行（注册时只要求 10ms）`);
}, 10);

console.log('J 同步：准备执行一段约 150ms 的阻塞循环');

// 下面这个 while 循环是"忙等待"：它占着 CPU 空转，主线程完全被占住，
// 期间事件循环没法推进，所有定时器/IO 回调都只能排队等着。
const busyUntil = Date.now() + 150;
let iterations = 0;
while (Date.now() < busyUntil) {
  iterations++; // 计数器防止 V8 把空循环优化掉
}

console.log(
  `J 同步：阻塞循环结束，空转了 ${iterations} 次，耗时约 ${Date.now() - blockStart}ms`,
);
// 观察输出：K 的时间戳明显大于 150ms，而不是 10ms。
// 这就是"同步阻塞"带来的后果——单线程被占满，异步回调全部被推迟。

// ---------------------------------------------------------------------------
// 5. 对比：把等待交给定时器就不阻塞
// ---------------------------------------------------------------------------

console.log('\n--- 5. 非阻塞的等待 ---');

function wait(ms) {
  // 返回一个 Promise：调用方可以用 await 或 .then 等它，但主线程不被占住。
  // 真实项目里这种"等待"通常是网络请求、文件读取等 I/O 操作。
  return new Promise((resolve) => {
    setTimeout(() => resolve(`等待了 ${ms}ms`), ms);
  });
}

const t0 = Date.now();

wait(20)
  .then((msg) => {
    console.log('L 异步完成：', msg, `实际耗时 ${Date.now() - t0}ms`);
    return wait(20); // 串行第二个等待
  })
  .then((msg) => {
    console.log('M 异步完成：', msg, `累计耗时 ${Date.now() - t0}ms`);
    console.log('\n示例结束。');
  })
  .catch((err) => {
    // 兜底：本示例不会失败，但写出 catch 是好习惯，
    // 也能避免未处理的 Promise 拒绝让进程非零退出。
    console.error('出现意外错误：', err);
  });

// 注意：最后两行日志由异步回调打印，说明"注册完异步任务后脚本就结束了"，
// 但 Node.js 会等到"没有待处理的任务"才真正退出进程。
