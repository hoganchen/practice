/**
 * ============================================================================
 * 辅助模块：_counter.js —— 演示"实时绑定"（live binding）的计数器模块
 * ============================================================================
 *
 * 【说明】
 *   本文件以 _ 开头，是辅助模块，批量校验脚本会跳过它。
 *   它被 07_live_bindings.js、06_namespace_import.js 导入。
 *
 * 【核心要点】
 *   1. 模块导出的是"绑定"而不是"值的拷贝"。
 *   2. 模块内部修改 count 之后，所有导入方看到的 count 都会同步更新。
 *   3. 导入方不能给导入进来的绑定重新赋值（那会直接报语法错误）。
 *   4. 这解决了 CommonJS 里"解构出来的值不会跟着变"的老问题。
 * ============================================================================
 */

// ---------------------------------------------------------------------------
// 1. 被导出的可变绑定
// ---------------------------------------------------------------------------

// 用 let 声明并且导出。ESM 允许导出可变的绑定，
// 模块外部读到的一定是最新值，而不是导入那一刻的快照。
export let count = 0;

// 另一个可导出的绑定，用来演示"多个导入方看到同一份状态"
export let lastAction = '(尚未有任何操作)';

// ---------------------------------------------------------------------------
// 2. 修改绑定的导出函数
// ---------------------------------------------------------------------------

/**
 * 计数器加一
 * @param {number} step 步长，默认 1
 * @returns {number} 自增后的值
 */
export function increment(step = 1) {
  count += step;
  lastAction = `increment(${step})`;
  return count;
}

/**
 * 计数器减一
 * @param {number} step 步长，默认 1
 * @returns {number} 自减后的值
 */
export function decrement(step = 1) {
  count -= step;
  lastAction = `decrement(${step})`;
  return count;
}

/**
 * 计数器归零
 * @returns {number} 归零后的值
 */
export function reset() {
  count = 0;
  lastAction = 'reset()';
  return count;
}

// ---------------------------------------------------------------------------
// 3. 模块私有状态：没有导出，外部拿不到
// ---------------------------------------------------------------------------

// 统计"总共发生过多少次操作"，注意它是私有的，
// 外部只能通过下面的 getHistorySize() 间接读取。
const history = [];

/**
 * 记录一次历史操作（供内部使用）
 * @param {string} action
 */
export function pushHistory(action) {
  history.push(action);
}

/**
 * 读取历史记录长度的只读快照
 * @returns {number}
 */
export function getHistorySize() {
  return history.length;
}
