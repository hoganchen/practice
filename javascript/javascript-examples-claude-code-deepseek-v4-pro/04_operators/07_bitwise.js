/**
 * ============================================================================
 * 知识点：位运算符 —— & | ^ ~ << >> >>> 与实战用途
 * ============================================================================
 *
 * 【所属分类】04_operators —— 运算符与表达式
 * 【难度等级】进阶
 * 【前置知识】04_operators/01_arithmetic.js
 *
 * 【知识点说明】
 *
 * 1. 是什么
 *    JS 的位运算符直接操作数字的二进制位：
 *      &   按位与（两位都为 1 才得 1）
 *      |   按位或（有一位为 1 就得 1）
 *      ^   按位异或（两位不同得 1，相同得 0）
 *      ~   按位取反（每一位取反，等价于 -x - 1）
 *      <<  左移（低位补 0，相当于乘以 2 的 n 次方）
 *      >>  有符号右移（高位补符号位，相当于除以 2 的 n 次方向下取整）
 *      >>> 无符号右移（高位一律补 0，会把负数变成很大的正数）
 *
 * 2. 为什么需要
 *    虽然业务代码里不常用，但位运算有三个不可替代的场景：
 *      (1) 标志位 / 权限系统：用一个整数同时表示多个"是/否"开关，省内存、易传递；
 *      (2) 取整与乘除 2 的幂：x | 0 截断小数、x << 1 乘 2，在热路径上更快；
 *      (3) 底层协议、哈希、颜色值（0xRRGGBB）、加密算法。
 *
 * 3. 核心语法要点
 *    - 运算前 JS 会把操作数转成 **32 位有符号整数**（ToInt32）：
 *      小数部分被直接丢弃（向零截断），超过 32 位的部分被截掉。
 *      所以 2147483648 | 0 得到 -2147483648，这是必须知道的边界。
 *    - 结果总是 32 位有符号整数（>>> 除外，它产生 32 位无符号整数）。
 *    - ~x 恒等于 -x - 1，所以 ~-1 === 0；常用 ~~x 或 x | 0 来取整。
 *    - >> 保留符号：-8 >> 1 === -4；>>> 不保留符号：-8 >>> 1 === 2147483644。
 *    - 位运算优先级低于比较运算符：a & b === c 会被解析成 a & (b === c)，务必加括号。
 *    - BigInt 也支持位运算，但两边必须都是 BigInt，混用会抛 TypeError。
 *
 * 4. 常见陷阱
 *    - 用位运算做数学运算会丢失精度（先截断为 32 位整数），
 *      金额、时间戳这类超过 32 位或含小数的数据不能用。
 *    - >>> 用于移位没问题，但如果只是想取整，>>> 0 会把负数变成正数：
 *      -1 >>> 0 === 4294967295，这不是你想要的结果。
 *    - 位运算的"取整"是向零截断，-3.9 | 0 得到 -3，而 Math.floor(-3.9) 是 -4。
 *    - 不要为了"性能"滥用位运算，现代引擎对 Math.floor 的优化已经足够好，
 *      可读性通常更重要。
 *
 * 【运行方法】
 *   在仓库根目录执行：node 04_operators/07_bitwise.js
 *
 * 【预期输出】
 *   依次打印真值表、各运算符的计算结果、二进制视角的解析、
 *   权限标志实战、取整技巧与 32 位边界陷阱。
 * ============================================================================
 */

// 小工具：把一个整数格式化成 8 位二进制字符串，方便观察位的变化
function toBinary(n) {
  // (n >>> 0) 把 n 转成 32 位无符号整数，再取低 8 位
  return (n >>> 0).toString(2).padStart(8, '0');
}

// ---------------------------------------------------------------------------
// 1. 真值表：& | ^ ~
// ---------------------------------------------------------------------------

console.log('--- 1. 位运算真值表 ---');

console.log('  位1  位2  |  &  |  |  |  ^');
const pairs = [
  [0, 0],
  [0, 1],
  [1, 0],
  [1, 1],
];
for (const [x, y] of pairs) {
  console.log(`   ${x}    ${y}   |  ${x & y}  |  ${x | y}  |  ${x ^ y}`);
}

// 用具体数字感受一下（5 = 0101，3 = 0011）
const p = 5;
const q = 3;
console.log(`\n  p = ${p} = ${toBinary(p)}`);
console.log(`  q = ${q} = ${toBinary(q)}`);
console.log(`  p & q = ${p & q} = ${toBinary(p & q)}  (0101 & 0011 = 0001 = 1)`);
console.log(`  p | q = ${p | q} = ${toBinary(p | q)}  (0101 | 0011 = 0111 = 7)`);
console.log(`  p ^ q = ${p ^ q} = ${toBinary(p ^ q)}  (0101 ^ 0011 = 0110 = 6)`);

// ~ 按位取反：恒等式 ~x === -x - 1
console.log(`  ~p = ${~p}  (因为 ~5 === -5 - 1 === -6)`);
console.log(`  ~0 = ${~0}，~-1 = ${~-1}（-1 的 32 位全是 1，取反得 0）`);

// 异或的两个有趣性质
console.log(`  p ^ p = ${p ^ p}（自己异或自己是 0，常用于"清零/去重"）`);
console.log(`  p ^ 0 = ${p ^ 0}（异或 0 保持原值）`);

// ---------------------------------------------------------------------------
// 2. 移位运算 << >> >>>
// ---------------------------------------------------------------------------

console.log('\n--- 2. 移位运算 ---');

// << 左移：低位补 0，等价于"乘以 2 的 n 次方"（在 32 位范围内）
console.log('1 << 0 =', 1 << 0); // 1
console.log('1 << 1 =', 1 << 1); // 2
console.log('1 << 4 =', 1 << 4); // 16
console.log('3 << 3 =', 3 << 3); // 24（3 * 8）
console.log('二进制：3 = ' + toBinary(3) + ' -> 3 << 3 = ' + toBinary(3 << 3));

// >> 有符号右移：高位补"符号位"，等价于"除以 2 的 n 次方后向负无穷取整"
console.log('16 >> 2 =', 16 >> 2); // 4
console.log('-16 >> 2 =', -16 >> 2); // -4（符号被保留）
console.log('7 >> 1 =', 7 >> 1); // 3（7 / 2 = 3.5，向下取整）
console.log('-7 >> 1 =', -7 >> 1); // -4（-3.5 向负无穷取整是 -4，不是 -3）

// >>> 无符号右移：高位一律补 0，因此负数会变成巨大的正数
console.log('16 >>> 2 =', 16 >>> 2); // 4（正数时与 >> 相同）
console.log('-16 >>> 2 =', -16 >>> 2); // 1073741820（因为符号位也被当成数值移走了）
console.log('-1 >>> 0 =', -1 >>> 0); // 4294967295（32 位全 1 的无符号解释）

// 移位量会被自动取模 32：移位 33 位等价于移位 1 位
console.log('1 << 33 =', 1 << 33, '（等价于 1 << 1）'); // 2
console.log('1 << 32 =', 1 << 32, '（等价于 1 << 0）'); // 1

// ---------------------------------------------------------------------------
// 3. 实战用途一：权限 / 标志位
// ---------------------------------------------------------------------------

console.log('\n--- 3. 实战：权限标志位 ---');

// 每个权限占用一个二进制位（2 的幂），互相不干扰
const PERM = {
  READ: 1 << 0, // 0b0001 = 1
  WRITE: 1 << 1, // 0b0010 = 2
  DELETE: 1 << 2, // 0b0100 = 4
  ADMIN: 1 << 3, // 0b1000 = 8
};
console.log('权限常量：', PERM);

// 用 | 组合权限：一个数字表示"同时拥有多个权限"
let role = PERM.READ | PERM.WRITE; // 1 | 2 = 3
console.log(`只读+可写的角色值 = ${role}，二进制 = ${toBinary(role)}`);

// 用 & 检查权限：结果非 0 表示"拥有该位"
function hasPermission(userPerm, perm) {
  return (userPerm & perm) === perm; // 用 === perm 而不是 != 0，可支持"复合权限"检查
}
console.log('有 READ 权限吗？', hasPermission(role, PERM.READ)); // true
console.log('有 WRITE 权限吗？', hasPermission(role, PERM.WRITE)); // true
console.log('有 DELETE 权限吗？', hasPermission(role, PERM.DELETE)); // false

// 用 | 追加权限（幂等：重复添加不会出错）
role |= PERM.DELETE;
console.log(`追加 DELETE 后 = ${role}，二进制 = ${toBinary(role)}`);

// 用 & ~ 移除权限（先取反得到除该位外全 1 的掩码，再与）
role &= ~PERM.WRITE;
console.log(`移除 WRITE 后 = ${role}，二进制 = ${toBinary(role)}`);
console.log('移除后还有 WRITE 权限吗？', hasPermission(role, PERM.WRITE)); // false

// 用 ^ 切换权限（有的变没有，没有的变有）
role ^= PERM.ADMIN;
console.log(`切换 ADMIN 后 = ${role}，二进制 = ${toBinary(role)}`);
role ^= PERM.ADMIN;
console.log(`再切换一次 ADMIN 后 = ${role}（回到原状）`);

// 组合权限检查：必须同时具备 READ 和 DELETE
console.log('同时具备 READ|DELETE 吗？', hasPermission(role, PERM.READ | PERM.DELETE)); // true

// 实际应用：把角色值存进数据库的一个整数字段，比存 JSON / 多张关联表都省事
function describePermissions(userPerm) {
  const names = Object.keys(PERM).filter((k) => hasPermission(userPerm, PERM[k]));
  return names.length ? names.join('、') : '无权限';
}
console.log('角色 13 的权限描述：', describePermissions(13)); // READ、DELETE、ADMIN

// ---------------------------------------------------------------------------
// 4. 实战用途二：取整与类型转换技巧
// ---------------------------------------------------------------------------

console.log('\n--- 4. 实战：取整技巧 ---');

const decimals = [3.9, -3.9, 0.5, -0.5, 12.0001];
for (const d of decimals) {
  console.log(
    `  ${d}  =>  d | 0 = ${d | 0}，~~d = ${~~d}，Math.trunc(d) = ${Math.trunc(d)}，Math.floor(d) = ${Math.floor(d)}`,
  );
}
// 结论：| 0 与 ~~ 都是"向零截断"，与 Math.trunc 一致，与 Math.floor 在负数上不同

// 取整后做位运算，顺便解释为什么 32 位之外不可靠
console.log('\n  32 位边界陷阱：');
console.log('    2147483647 | 0 =', 2147483647 | 0, '（32 位有符号最大值，正常）');
console.log('    2147483648 | 0 =', 2147483648 | 0, '（溢出，变成了负数！）');
console.log('    4294967296 | 0 =', 4294967296 | 0, '（溢出后归零）');
console.log('    2147483648 >>> 0 =', 2147483648 >>> 0, '（用 >>> 0 才能得到无符号解释）');
console.log('    Number.MAX_SAFE_INTEGER | 0 =', Number.MAX_SAFE_INTEGER | 0, '（完全丢掉了高位）');

// 用 >>> 0 做"无符号化"：把任意数字的安全解释成 32 位无符号整数
console.log('  -1 >>> 0 =', -1 >>> 0, '（等价于 2^32 - 1）');

// ---------------------------------------------------------------------------
// 5. 实战用途三：颜色值拆解（0xRRGGBB）
// ---------------------------------------------------------------------------

console.log('\n--- 5. 实战：拆分 RGB 颜色 ---');

const color = 0xff8800; // 橙色的 24 位颜色值
// 用 >> 与 & 0xff 把三个字节分别取出来
const red = (color >> 16) & 0xff;
const green = (color >> 8) & 0xff;
const blue = color & 0xff;
console.log(`  颜色 0x${color.toString(16)} => R=${red}, G=${green}, B=${blue}`);

// 反向合成：用 << 与 | 拼回一个整数
const rebuilt = (red << 16) | (green << 8) | blue;
console.log(`  重新合成 = 0x${rebuilt.toString(16)}，与原值相等：${rebuilt === color}`);

// ---------------------------------------------------------------------------
// 6. 陷阱：优先级与 BigInt
// ---------------------------------------------------------------------------

console.log('\n--- 6. 陷阱 ---');

// 陷阱一：位运算优先级低于 ===，不加括号会得到意外结果
const flagA = 1;
const flagB = 0;
console.log('  flagA & flagB === 0 实际是 flagA & (flagB === 0) =', flagA & flagB === 0);
// 上面等价于 1 & (0 === 0) = 1 & true = 1 & 1 = 1，非 0 为真值，不是想要的布尔结果
console.log('  正确的写法 (flagA & flagB) === 0 =', (flagA & flagB) === 0); // true

// 陷阱二：BigInt 与 Number 不能混合做位运算
try {
  console.log(1n & 1);
} catch (err) {
  console.log('  1n & 1 抛出：', err.constructor.name, '-', err.message);
}
// 两边都用 BigInt 才合法
console.log('  两边都是 BigInt：1n & 3n =', 1n & 3n); // 1n

// 陷阱三：位运算会静默丢弃小数与高位，不做任何提示
console.log('  3.99 | 0 =', 3.99 | 0, '（小数被静默丢弃，不会报错）');
// 1e21 远超 32 位，ToInt32 只保留低 32 位，于是得到一个与直觉完全无关的负数
console.log('  1e21 | 0 =', 1e21 | 0, '（高位被丢弃，得到一个毫无意义的负数，极其危险）');
// 对比：同样的数字用 Math.trunc 才是"数学上的取整"
console.log('  Math.trunc(1e21) =', Math.trunc(1e21), '（这才是正确的取整结果）');

console.log('\n全部演示结束。');
