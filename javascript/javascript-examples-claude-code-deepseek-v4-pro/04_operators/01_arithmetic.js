/**
 * ============================================================================
 * 知识点：算术运算符 —— 加减乘除、取余、幂、一元正负号、自增自减
 * ============================================================================
 *
 * 【所属分类】04_operators —— 运算符与表达式
 * 【难度等级】入门
 * 【前置知识】00_hello_world/01_hello_world.js
 *
 * 【知识点说明】
 *
 * 1. 是什么
 *    JavaScript 的算术运算符用于对数值做数学计算，共 8 个：
 *      +  加法（同时也是字符串拼接）
 *      -  减法 / 取负
 *      *  乘法
 *      /  除法
 *      %  取余（求模，结果的符号跟随被除数）
 *      ** 幂运算（ES2016 新增）
 *      ++ 自增（分前置、后置）
 *      -- 自减（分前置、后置）
 *    以及两个一元运算符：+x（转数字）、-x（转数字并取负）。
 *
 * 2. 为什么需要
 *    任何涉及计数、累加、百分比、金额、游戏坐标、分页计算的地方都要用它们。
 *    其中 % 在"判断奇偶""循环取模""哈希分桶"中无处不在，
 *    ++/-- 则是循环计数器最常用的写法。
 *
 * 3. 核心语法要点
 *    - JS 只有一种数字类型 Number（IEEE 754 双精度 64 位浮点数），
 *      没有 int / float 之分，所以 10 / 4 得到 2.5 而不是 2。
 *    - 结果符号：(-7) % 3 === -1，符号跟着"被除数"走，不是数学上的模。
 *    - ** 是右结合的：2 ** 3 ** 2 === 2 ** 9 === 512，且左侧不能直接写一元负号。
 *    - ++x 先自增再返回新值；x++ 先返回旧值再自增。这是最经典的面试题。
 *    - +'42' 得到数字 42，是显式类型转换的常用简写。
 *
 * 4. 常见陷阱
 *    - 浮点精度：0.1 + 0.2 !== 0.3，金融计算要用整数（分）或专门的库。
 *    - 加号的"双重身份"：只要有一个操作数是字符串，+ 就变成拼接而非加法。
 *    - -2 ** 2 是语法错误（SyntaxError），因为一元运算符优先级高于 **，
 *      必须写成 -(2 ** 2) 或 (-2) ** 2。
 *    - 除数为 0 不会抛错，而是得到 Infinity 或 NaN，需要自己判断。
 *
 * 【运行方法】
 *   在仓库根目录执行：node 04_operators/01_arithmetic.js
 *
 * 【预期输出】
 *   依次打印基础运算、取余规则、幂运算、一元运算符、自增自减前后置差异、
 *   以及浮点精度陷阱的演示结果。
 * ============================================================================
 */

// ---------------------------------------------------------------------------
// 1. 五个基础二元算术运算符
// ---------------------------------------------------------------------------

console.log('--- 1. 基础算术运算 ---');

// 加减乘除取余，优先级与数学一致：先 * / %，再 + -
console.log('7 + 3 =', 7 + 3); // 10
console.log('7 - 3 =', 7 - 3); // 4
console.log('7 * 3 =', 7 * 3); // 21
console.log('7 / 3 =', 7 / 3); // 2.3333333333333335（浮点除法，不取整）

// 除数为 0 不报错：正数除以 0 得到 Infinity，0 除以 0 得到 NaN
console.log('7 / 0 =', 7 / 0); // Infinity
console.log('0 / 0 =', 0 / 0); // NaN（Not a Number）
console.log('-7 / 0 =', -7 / 0); // -Infinity

// 取余 %：结果是"余数"，符号永远跟随被除数（左边那个数）
console.log('7 % 3 =', 7 % 3); // 1
console.log('-7 % 3 =', -7 % 3); // -1（不是 2！这是最容易搞错的点）
console.log('7 % -3 =', 7 % -3); // 1

// 取余的经典用途：判断奇偶
console.log('10 % 2 === 0 ? 偶数 : 奇数 =>', 10 % 2 === 0 ? '偶数' : '奇数');

// ---------------------------------------------------------------------------
// 2. 幂运算符 **
// ---------------------------------------------------------------------------

console.log('\n--- 2. 幂运算符 ** ---');

console.log('2 ** 10 =', 2 ** 10); // 1024
console.log('9 ** 0.5 =', 9 ** 0.5); // 3，0.5 次方等价于开平方

// ** 是"右结合"的：从右往左算，2 ** (3 ** 2) 而不是 (2 ** 3) ** 2
console.log('2 ** 3 ** 2 =', 2 ** 3 ** 2); // 512（= 2 ** 9），不是 64

// 陷阱：左侧不能直接跟一元负号，会抛 SyntaxError。
// 因为解析器会把 `-2 ** 2` 理解为 `-(2 ** 2)` 之外的歧义形式而直接拒绝。
// 这里用 new Function 在运行时构造并捕获，避免整个文件语法不通过。
try {
  new Function('return -2 ** 2;');
  console.log('没有报错（不会执行到这里）');
} catch (err) {
  console.log('new Function("return -2 ** 2") 抛出：', err.constructor.name, '-', err.message);
}
// 想要负底数必须加括号
console.log('(-2) ** 2 =', (-2) ** 2); // 4
console.log('-(2 ** 2) =', -(2 ** 2)); // -4

// ---------------------------------------------------------------------------
// 3. 一元运算符 + 和 -
// ---------------------------------------------------------------------------

console.log('\n--- 3. 一元 + / - ---');

// 一元 + 的作用是"转换成数字"，是 Number(...) 的简写形式
console.log("+'42' =", +'42', '类型：', typeof +'42'); // 42 number
console.log("+'3.14' =", +'3.14'); // 3.14
console.log("+'' =", +''); // 0（空字符串转成 0）
console.log("+'abc' =", +'abc'); // NaN（无法解析）
console.log('+true =', +true, '，+false =', +false); // 1 / 0
console.log('+null =', +null); // 0
console.log('+undefined =', +undefined); // NaN

// 一元 - 等价于"先转数字再取负"
console.log("-'5' =", -'5'); // -5
console.log('-(-3) =', -(-3)); // 3

// 实用场景：把用户输入（字符串）安全地转成数字
const input = '128';
const price = +input;
console.log("把 '128' 用一元 + 转成数字后乘以 2：", price * 2); // 256

// ---------------------------------------------------------------------------
// 4. 自增 ++ 与自减 --：前置与后置的区别
// ---------------------------------------------------------------------------

console.log('\n--- 4. 自增自减的前置与后置 ---');

let a = 5;
// 前置 ++a：先把 a 加 1，再把"新值"作为整个表达式的值
const preResult = ++a;
console.log('let a = 5; ++a  => 表达式的值 =', preResult, '，a =', a); // 6, 6

let b = 5;
// 后置 b++：先把"旧值"作为整个表达式的值，再把 b 加 1
const postResult = b++;
console.log('let b = 5; b++  => 表达式的值 =', postResult, '，b =', b); // 5, 6

// 自减同理
let c = 5;
console.log('--c 表达式的值 =', --c, '，c =', c); // 4, 4
let d = 5;
console.log('d-- 表达式的值 =', d--, '，d =', d); // 5, 4

// 经典考题：同一行里既取值又自增
let x = 1;
const tricky = x++ + ++x; // 1（x变成2） + 3（x变成3） = 4
console.log('let x = 1; x++ + ++x =', tricky, '，此时 x =', x); // 4, 3

// 只有单独成句时，前置后置没有区别，此时推荐用前缀形式（社区风格）
let counter = 0;
counter++;
counter++;
++counter;
console.log('counter 累加 3 次后 =', counter); // 3

// ---------------------------------------------------------------------------
// 5. 浮点数精度陷阱
// ---------------------------------------------------------------------------

console.log('\n--- 5. 浮点数精度陷阱 ---');

// 0.1 和 0.2 在二进制浮点里都不能被精确表示，相加会有极小误差
console.log('0.1 + 0.2 =', 0.1 + 0.2); // 0.30000000000000004
console.log('0.1 + 0.2 === 0.3 ?', 0.1 + 0.2 === 0.3); // false！

// 正确做法之一：用极小误差值（epsilon）比较
const EPSILON = Number.EPSILON;
console.log('使用 Number.EPSILON 比较：', Math.abs(0.1 + 0.2 - 0.3) < EPSILON); // true

// 更稳妥的做法：金额一律用"分"这类整数运算，最后再除以 100 展示
const priceInCents = 10 + 20; // 0.1 元 + 0.2 元，用分表示
console.log('用整数分计算：(10 + 20) / 100 =', priceInCents / 100); // 0.3

// 另一个常见陷阱：大整数超过安全范围后失去精度
console.log('Number.MAX_SAFE_INTEGER =', Number.MAX_SAFE_INTEGER); // 9007199254740991
console.log('MAX_SAFE_INTEGER + 1 === MAX_SAFE_INTEGER + 2 ?', Number.MAX_SAFE_INTEGER + 1 === Number.MAX_SAFE_INTEGER + 2); // true，已经不可信

// ---------------------------------------------------------------------------
// 6. 加号的"双重身份"：加法还是拼接？
// ---------------------------------------------------------------------------

console.log('\n--- 6. 加号的双重身份 ---');

// 两个操作数都是数字（或可转数字的原始值）时，+ 做加法
console.log('1 + 2 =', 1 + 2); // 3
// 只要有一个操作数是字符串，+ 就变成字符串拼接（从左到右）
console.log("1 + '2' =", 1 + '2'); // '12'
console.log("'1' + 2 + 3 =", '1' + 2 + 3); // '123'（先拼成 '12'，再拼 '3'）
console.log("1 + 2 + '3' =", 1 + 2 + '3'); // '33'（先算 1+2=3，再拼接）

// 其余算术运算符（- * / %）没有"双重身份"，遇到字符串会强制转成数字
console.log("'6' - '2' =", '6' - '2'); // 4（数字）
console.log("'6' * '2' =", '6' * '2'); // 12（数字）

console.log('\n全部演示结束。');
