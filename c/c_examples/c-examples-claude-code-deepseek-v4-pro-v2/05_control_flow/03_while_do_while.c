/**
 * ============================================================
 * 知识点: while 和 do-while 循环 (While and Do-While Loops)
 * ============================================================
 *
 * 【编译指令】
 *   gcc 03_while_do_while.c -o 03_while_do_while.exe -std=c11 -Wall
 *
 * 【运行指令】
 *   ./03_while_do_while.exe
 *
 * 【知识点概述】
 *   while 和 do-while 是 C 语言中的条件循环结构：
 *     - while (条件) { 循环体 }     ：先判断条件，再执行循环体（可能一次都不执行）
 *     - do { 循环体 } while (条件); ：先执行循环体，再判断条件（至少执行一次）
 *   适用场景：输入验证、计数循环、遍历处理等
 * ============================================================
 */

#include "../common/charset.h"
#include <stdio.h>

/**
 * 主函数
 */
int main(void)
{
    printf("========================================\n");
    printf("  while 和 do-while 循环 示例\n");
    printf("========================================\n\n");

    // ---------------------------------------------------------
    // 示例 1: 基本的 while 循环
    // 从 1 加到 10，计算累加和
    // ---------------------------------------------------------
    printf("【示例 1】基本的 while 循环 —— 计算 1 到 10 的累加和\n");

    int i = 1;      // 循环计数器初始化
    int sum = 0;    // 累加器

    // while 循环执行流程：
    // 1. 判断条件 i <= 10 是否为真
    // 2. 如果为真，执行循环体；如果为假，跳到循环体之后
    // 3. 执行完循环体后，回到步骤 1
    while (i <= 10) {
        sum += i;   // 等价于 sum = sum + i
        i++;        // 计数器自增，防止死循环
    }

    printf("  1 + 2 + ... + 10 = %d\n\n", sum);

    // ---------------------------------------------------------
    // 示例 2: while 循环实现输入验证
    // 持续要求用户输入直到输入合法值
    // ---------------------------------------------------------
    printf("【示例 2】while 循环实现输入验证\n");

    int user_input;

    printf("  请输入一个 1-100 之间的正整数: ");
    scanf("%d", &user_input);

    // 输入验证循环：只要输入无效，就反复提示重新输入
    while (user_input < 1 || user_input > 100) {
        printf("  输入无效！请输入 1-100 之间的数: ");
        scanf("%d", &user_input);
    }

    printf("  输入有效，您输入的是: %d\n\n", user_input);

    // 清除输入缓冲区中的换行符，避免影响后续输入
    while (getchar() != '\n') {
        // 持续读取直到遇到换行符
    }

    // ---------------------------------------------------------
    // 示例 3: do-while 循环 —— 至少执行一次
    // 与 while 的区别：do-while 先执行循环体，再判断条件
    // ---------------------------------------------------------
    printf("【示例 3】do-while 循环 —— 至少执行一次\n");

    int j = 5;

    printf("  使用 do-while，即使条件不满足也至少执行一次:\n");

    do {
        printf("  循环体执行: j = %d\n", j);
        j++;
    } while (j < 3);  // 注意这里条件 j < 3 为假，但循环体已经执行了一次

    printf("  循环结束后的 j = %d\n", j);
    printf("\n");

    // ---------------------------------------------------------
    // 示例 4: do-while 用于菜单选择
    // 经典应用：显示菜单并处理用户选择，直到用户选择退出
    // ---------------------------------------------------------
    printf("【示例 4】do-while 实现菜单选择\n");

    int choice;  // 用户选择

    do {
        // 先显示菜单（至少显示一次）
        printf("\n  ===== 简易计算器菜单 =====\n");
        printf("  1. 加法\n");
        printf("  2. 减法\n");
        printf("  3. 乘法\n");
        printf("  0. 退出\n");
        printf("  请选择 (0-3): ");
        scanf("%d", &choice);

        // 根据选择处理
        switch (choice) {
            case 1:
                printf("  选择了加法运算\n");
                break;
            case 2:
                printf("  选择了减法运算\n");
                break;
            case 3:
                printf("  选择了乘法运算\n");
                break;
            case 0:
                printf("  退出程序。\n");
                break;
            default:
                printf("  无效选择，请重新输入。\n");
                break;
        }
    } while (choice != 0);  // 条件在循环体结束后判断

    // 清除缓冲区
    while (getchar() != '\n') {}

    printf("\n");

    // ---------------------------------------------------------
    // 示例 5: while 循环实现数字反转
    // 展示循环中如何逐位处理数字
    // ---------------------------------------------------------
    printf("【示例 5】while 循环实现数字反转\n");

    int num = 12345;
    int reversed = 0;
    int temp = num;

    printf("  原始数字: %d\n", num);

    while (temp != 0) {
        int digit = temp % 10;          // 取出最后一位数字
        reversed = reversed * 10 + digit;  // 将其加到反转结果中
        temp /= 10;                     // 去掉最后一位
    }

    printf("  反转后的数字: %d\n\n", reversed);

    // ---------------------------------------------------------
    // 示例 6: while 循环计算阶乘
    // ---------------------------------------------------------
    printf("【示例 6】while 循环计算阶乘\n");

    int n = 6;
    int factorial = 1;
    int k = 1;

    while (k <= n) {
        factorial *= k;  // 等价于 factorial = factorial * k
        k++;
    }

    printf("  %d! = %d\n\n", n, factorial);

    // ---------------------------------------------------------
    // 示例 7: 无限循环与 break 配合
    // while (1) 创建无限循环，在循环体内用 break 退出
    // ---------------------------------------------------------
    printf("【示例 7】while (1) 无限循环与 break 配合\n");

    int count = 0;

    while (1) {  // 条件永远为真，无限循环
        count++;
        printf("  第 %d 次循环\n", count);

        if (count >= 3) {
            // 当 count 达到 3 时，用 break 退出循环
            printf("  达到循环次数，break 退出。\n");
            break;
        }
    }
    printf("\n");

    // ---------------------------------------------------------
    // while 与 do-while 的对比总结
    // ---------------------------------------------------------
    printf("========================================\n");
    printf("  while 与 do-while 对比总结:\n");
    printf("\n");
    printf("  while (条件) { 循环体 }\n");
    printf("    先判断 → 再执行，可能一次都不执行\n");
    printf("    适用于：前置条件判断\n\n");
    printf("  do { 循环体 } while (条件);\n");
    printf("    先执行 → 再判断，至少执行一次\n");
    printf("    适用于：输入验证、菜单循环\n");
    printf("    注意：末尾有分号 ;\n");
    printf("========================================\n");

    return 0;
}
