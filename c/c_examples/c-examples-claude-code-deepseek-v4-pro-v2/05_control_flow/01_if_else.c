/**
 * ============================================================
 * 知识点: if-else 条件判断语句 (if-else Conditional Statements)
 * ============================================================
 *
 * 【编译指令】
 *   gcc 01_if_else.c -o 01_if_else.exe -std=c11 -Wall
 *
 * 【运行指令】
 *   ./01_if_else.exe
 *
 * 【知识点概述】
 *   if-else 是 C 语言中最基本的条件分支结构，根据条件的真（非零）或假（零）
 *   来决定程序的执行路径。包括：
 *     - if (条件) { ... }              ：单分支
 *     - if (条件) { ... } else { ... } ：双分支
 *     - if (条件) { ... } else if (条件) { ... } else { ... } ：多分支
 *     - 嵌套 if 语句
 *     - 常见陷阱：赋值 = 与比较 == 的混淆
 * ============================================================
 */

#include "../common/charset.h"
#include <stdio.h>   // 标准输入输出库，提供 printf、scanf 等函数
#include <stdlib.h>  // 标准库，提供 abs 等工具函数

/**
 * 主函数 —— 程序的入口点
 */
int main(void)
{
    printf("========================================\n");
    printf("  if-else 条件判断语句 示例\n");
    printf("========================================\n\n");

    // ---------------------------------------------------------
    // 示例 1: 基本的 if-else 结构
    // 根据成绩判断是否及格
    // ---------------------------------------------------------
    printf("【示例 1】基本的 if-else 结构\n");

    int score = 75;  // 定义成绩变量

    // 注意：条件表达式 score >= 60 的结果为 1（真）或 0（假）
    if (score >= 60) {
        // 条件为真时执行此代码块
        printf("  成绩 %d 分，及格！\n\n", score);
    } else {
        // 条件为假时执行此代码块
        printf("  成绩 %d 分，不及格！\n\n", score);
    }

    // ---------------------------------------------------------
    // 示例 2: if-else if-else 多分支结构
    // 根据分数评定等级
    // ---------------------------------------------------------
    printf("【示例 2】if-else if-else 多分支结构\n");

    score = 85;  // 重新赋值

    // 多分支判断：从上到下依次判断，遇到第一个为真的条件就执行
    if (score >= 90) {
        printf("  等级: A (优秀)\n");
    } else if (score >= 80) {
        printf("  等级: B (良好)\n");  // score=85 时执行这个分支
    } else if (score >= 70) {
        printf("  等级: C (中等)\n");
    } else if (score >= 60) {
        printf("  等级: D (及格)\n");
    } else {
        printf("  等级: F (不及格)\n");
    }
    printf("\n");

    // ---------------------------------------------------------
    // 示例 3: 嵌套 if 语句
    // 先判断是否成年，再判断是否满足其他条件
    // ---------------------------------------------------------
    printf("【示例 3】嵌套 if 语句\n");

    int age = 20;          // 年龄
    int has_license = 1;   // 是否有驾照（1 表示有，0 表示无）

    if (age >= 18) {
        // 外层 if 条件为真，进入内层判断
        printf("  年龄 %d 岁，已成年。\n", age);

        if (has_license) {
            // 内层 if 条件也为真
            printf("  有驾照，可以合法驾驶汽车。\n");
        } else {
            // 内层 if 条件为假
            printf("  没有驾照，不能驾驶汽车。\n");
        }
    } else {
        printf("  年龄 %d 岁，未成年，不能驾驶汽车。\n", age);
    }
    printf("\n");

    // ---------------------------------------------------------
    // 示例 4: 常见陷阱 —— 赋值运算符 = 与比较运算符 ==
    // 这是一个非常经典的 C 语言 bug！
    // ---------------------------------------------------------
    printf("【示例 4】常见陷阱 —— 赋值 = 与比较 == 的混淆\n");

    int x = 5;
    int y = 10;

    // 错误写法（注释掉，仅供演示）：
    // if (x = y) {   // 这是赋值操作！把 y 的值赋给 x，表达式值为 10（非零，恒为真）
    //     printf("  永远会执行到这里！\n");
    // }

    // 正确写法：使用 == 进行比较
    if (x == y) {
        printf("  x 等于 y\n");
    } else {
        printf("  x 不等于 y (x=%d, y=%d)\n", x, y);
    }

    // 防御性编程技巧：将常量放在左边，这样误写 = 会导致编译错误
    // if (10 == x) { ... }    // 正确，且误写为 10 = x 会编译报错
    // if (x = 10) { ... }    // 错误，但编译器可能只给警告，不会报错
    printf("\n");

    // ---------------------------------------------------------
    // 示例 5: 条件表达式的真值理解
    // C 语言中，任何非零值都被视为"真"，零被视为"假"
    // ---------------------------------------------------------
    printf("【示例 5】C 语言中的真值概念\n");

    int value = 3;  // 非零值

    // 直接判断 value，等价于 value != 0
    if (value) {
        printf("  value = %d, 非零即为真 (true)\n", value);
    } else {
        printf("  value = %d, 零即为假 (false)\n", value);
    }

    // 常见用法：判断函数返回值
    // 很多 C 标准库函数返回 0 表示成功，非零表示错误
    // 如：if (!some_function()) { /* 成功 */ }
    printf("\n");

    // ---------------------------------------------------------
    // 示例 6: 三元运算符（条件表达式）
    // 这是 if-else 的简洁形式，适用于简单的二选一赋值
    // ---------------------------------------------------------
    printf("【示例 6】三元运算符 ? :  —— 简洁的条件表达式\n");

    int a = 10;
    int b = 20;

    // 语法：条件 ? 表达式1 : 表达式2
    // 如果条件为真，整个表达式值为表达式1，否则为表达式2
    int max = (a > b) ? a : b;

    printf("  a=%d, b=%d 中的较大值是: %d\n", a, b, max);

    // 三元运算符也可以嵌套，但可读性会下降，不推荐
    int min = (a < b) ? a : b;
    printf("  a=%d, b=%d 中的较小值是: %d\n", a, b, min);
    printf("\n");

    printf("========================================\n");
    printf("  示例结束，程序退出。\n");
    printf("========================================\n");

    return 0;  // 返回 0 表示程序正常结束
}
