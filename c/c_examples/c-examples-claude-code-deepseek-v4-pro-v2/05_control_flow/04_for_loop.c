/**
 * ============================================================
 * 知识点: for 循环 (For Loop)
 * ============================================================
 *
 * 【编译指令】
 *   gcc 04_for_loop.c -o 04_for_loop.exe -std=c11 -Wall
 *
 * 【运行指令】
 *   ./04_for_loop.exe
 *
 * 【知识点概述】
 *   for 循环将初始化、条件判断和循环变量更新集中在一个语句中：
 *     for (初始化; 条件; 更新) { 循环体 }
 *   包括：
 *     - 基本 for 循环结构
 *     - 多循环控制变量
 *     - 死循环 for (;;)
 *     - 嵌套 for 循环（多层循环）
 *     - 循环中的逗号运算符
 * ============================================================
 */

#include "../common/charset.h"
#include <stdio.h>

/**
 * 主函数
 */
int main(void)
{
    printf("========================================\n");
    printf("  for 循环 示例\n");
    printf("========================================\n\n");

    // ---------------------------------------------------------
    // 示例 1: 基本的 for 循环
    // 打印 1 到 5
    // ---------------------------------------------------------
    printf("【示例 1】基本的 for 循环 —— 打印 1 到 5\n");

    // for 循环的三个部分：
    //   - 初始化:   int i = 1     （循环开始前执行一次）
    //   - 条件:     i <= 5       （每次循环前判断，真则继续，假则退出）
    //   - 更新:     i++          （每次循环体执行完后执行）
    for (int i = 1; i <= 5; i++) {
        printf("  i = %d\n", i);
    }
    printf("\n");

    // ---------------------------------------------------------
    // 示例 2: for 循环的多种写法
    // 1) 递减循环
    // ---------------------------------------------------------
    printf("【示例 2a】for 循环 —— 递减循环\n");

    for (int i = 5; i >= 1; i--) {
        printf("  倒数: %d\n", i);
    }
    printf("\n");

    // ---------------------------------------------------------
    // 示例 2b: 步长不为 1 的循环
    // ---------------------------------------------------------
    printf("【示例 2b】for 循环 —— 步长为 2\n");

    for (int i = 0; i <= 10; i += 2) {
        printf("  偶数: %d\n", i);
    }
    printf("\n");

    // ---------------------------------------------------------
    // 示例 3: 多个循环控制变量
    // 使用逗号运算符在初始化部分和更新部分操作多个变量
    // ---------------------------------------------------------
    printf("【示例 3】多个循环控制变量\n");

    // 同时用 i 和 j 两个变量控制循环
    // i 从 0 递增，j 从 10 递减
    for (int i = 0, j = 10; i <= j; i++, j--) {
        printf("  i = %2d, j = %2d, i+j = %2d\n", i, j, i + j);
    }
    printf("\n");

    // ---------------------------------------------------------
    // 示例 4: 死循环 for (;;)
    // 三个部分都可以省略，相当于 while (1)
    // ---------------------------------------------------------
    printf("【示例 4】死循环 for (;;) 与 break 退出\n");

    int count = 0;

    // for (;;) 等价于 while (1)，是典型的死循环写法
    for (;;) {
        count++;
        printf("  第 %d 次循环\n", count);

        if (count >= 3) {
            printf("  退出死循环\n");
            break;  // 必须用 break 或其他方式退出，否则循环永不结束
        }
    }
    printf("\n");

    // ---------------------------------------------------------
    // 示例 5: 嵌套 for 循环 —— 打印乘法口诀表
    // 外层循环控制行，内层循环控制列
    // ---------------------------------------------------------
    printf("【示例 5】嵌套 for 循环 —— 打印乘法口诀表\n\n");

    for (int i = 1; i <= 9; i++) {        // 外层循环：行
        for (int j = 1; j <= i; j++) {    // 内层循环：列（只打印到 i）
            printf("  %dx%d=%2d", j, i, i * j);
        }
        printf("\n");  // 每行结束后换行
    }
    printf("\n");

    // ---------------------------------------------------------
    // 示例 6: 嵌套循环 —— 星号三角形
    // ---------------------------------------------------------
    printf("【示例 6】嵌套 for 循环 —— 打印直角三角形\n\n");

    int rows = 5;

    for (int i = 1; i <= rows; i++) {        // 外层循环：控制行数
        for (int j = 1; j <= i; j++) {      // 内层循环：控制每行的星号数
            printf("* ");
        }
        printf("\n");  // 每行结束后换行
    }
    printf("\n");

    // ---------------------------------------------------------
    // 示例 7: for 循环的省略写法 —— 初始化在外部
    // ---------------------------------------------------------
    printf("【示例 7】for 循环的省略写法\n");

    int i = 0;  // 初始化放在循环外部

    // 省略初始化部分，但分号不能省
    for (; i < 5; i++) {
        printf("  i = %d\n", i);
    }

    // 也可以省略更新部分，在循环体内处理
    int j = 0;
    for (; j < 5; ) {
        printf("  j = %d\n", j);
        j++;  // 更新操作放在循环体内
    }
    printf("\n");

    // ---------------------------------------------------------
    // 示例 8: 使用 break 提前退出嵌套循环
    // break 只会跳出最内层的循环
    // ---------------------------------------------------------
    printf("【示例 8】在嵌套循环中使用 break\n");

    for (int x = 1; x <= 3; x++) {
        for (int y = 1; y <= 3; y++) {
            printf("  (x=%d, y=%d) ", x, y);

            if (x == 2 && y == 2) {
                printf("-> 遇到 break，退出内层循环！");
                break;  // 只退出内层的 for (y) 循环
            }
        }
        printf("\n");
    }
    printf("  注意：break 只退出了内层循环，外层循环继续执行\n");
    printf("\n");

    // ---------------------------------------------------------
    // 示例 9: for 循环中的 continue
    // 跳过本次循环的剩余部分，进入下一次迭代
    // ---------------------------------------------------------
    printf("【示例 9】for 循环中使用 continue\n");

    printf("  1-10 中跳过 5 的打印:\n");
    for (int num = 1; num <= 10; num++) {
        if (num == 5) {
            continue;  // 跳过数字 5，不执行下面的 printf
        }
        printf("  %d ", num);
    }
    printf("\n\n");

    // ---------------------------------------------------------
    // 示例 10: for 循环求范围总和
    // ---------------------------------------------------------
    printf("【示例 10】for 循环计算 1-100 的和\n");

    int total = 0;

    for (int num = 1; num <= 100; num++) {
        total += num;
    }

    printf("  1 + 2 + ... + 100 = %d\n\n", total);

    // ---------------------------------------------------------
    // 总结
    // ---------------------------------------------------------
    printf("========================================\n");
    printf("  for 循环要点总结:\n");
    printf("  1. for (初始化; 条件; 更新) 将循环控制集中在一行\n");
    printf("  2. 用逗号操作符可控制多个变量\n");
    printf("  3. for (;;) 是死循环，需配合 break 退出\n");
    printf("  4. 嵌套循环时，break/continue 只影响最内层\n");
    printf("  5. 适合已知循环次数的情况\n");
    printf("========================================\n");

    return 0;
}
