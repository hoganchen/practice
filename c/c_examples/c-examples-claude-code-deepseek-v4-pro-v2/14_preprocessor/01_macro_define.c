/**
 * ============================================================
 *  知识点: 宏定义 (#define)
 *
 *  编译指令: gcc 01_macro_define.c -o 01_macro_define.exe -std=c11 -Wall
 *  运行指令: ./01_macro_define.exe
 *
 *  本文件演示:
 *    1. 对象宏 (Object-like macros): #define 名称 值
 *    2. 函数宏 (Function-like macros): #define ADD(x,y) ((x)+(y))
 *    3. 常见陷阱 (括号的重要性!)
 *    4. #undef 取消宏定义
 *    5. 多行宏定义 (反斜杠续行)
 * ============================================================
 */

#include "../common/charset.h"
#include <stdio.h>
#include <math.h>

/*------------------------------------------------------------------
 *  1. 对象宏 (Object-like Macros)
 *
 *  语法: #define 宏名 替换文本
 *  预处理器会在编译前将代码中所有的宏名替换为替换文本
 *------------------------------------------------------------------*/

/* 常量宏 */
#define PI           3.1415926535
#define MAX_STUDENTS 50
#define SCHOOL_NAME  "清华大学"

/* 表达式宏 */
#define AREA_CIRCLE(r)  (PI * (r) * (r))

/* 使用已有宏定义新宏 */
#define TWO_PI       (2.0 * PI)

/*------------------------------------------------------------------
 *  2. 函数宏 (Function-like Macros)
 *
 *  特点:
 *    - 没有类型检查, 任何类型都可以"传参"
 *    - 参数在代码中直接展开, 可能有副作用
 *    - 比函数调用快 (没有调用开销), 但会增大代码体积
 *
 *  重要: 参数和整体都需要加括号, 否则有优先级问题!
 *------------------------------------------------------------------*/

/* 正确的宏定义: 每个参数和整个表达式都加括号 */
#define SQUARE(x)       ((x) * (x))
#define MAX(a, b)       ((a) > (b) ? (a) : (b))
#define MIN(a, b)       ((a) < (b) ? (a) : (b))
#define ABS(x)          ((x) < 0 ? -(x) : (x))

/*------------------------------------------------------------------
 *  3. 常见的宏陷阱
 *------------------------------------------------------------------*/

/* 陷阱示例: 没有括号的情况 */
#define SQUARE_BAD(x)   (x * x)       /* 没有给参数加括号 */
#define DOUBLE_BAD(x)   x + x         /* 没有给整个表达式加括号 */

/* 副作用陷阱: 参数被多次求值 */
#define MAX_EVAL(a, b)  ((a) > (b) ? (a) : (b))
/* 如果传入 MAX_EVAL(i++, j++), i 和 j 会被递增两次! */

/*------------------------------------------------------------------
 *  4. 多行宏 (反斜杠续行)
 *
 *  多行宏使用反斜杠 \ 续行, 最后一行不需要反斜杠
 *  do { ... } while(0) 是一种惯用法, 确保宏在使用时表现如一个语句
 *------------------------------------------------------------------*/

/* 多行宏: 打印调试信息 */
#define DEBUG_PRINT(fmt, val)                          \
    do {                                               \
        printf("[DEBUG] %s:%d - ", __FILE__, __LINE__);\
        printf(fmt, val);                              \
        printf("\n");                                  \
    } while (0)

/* 多行宏: 交换两个变量的值 (使用 do-while(0) 技巧) */
#define SWAP(a, b, type)                               \
    do {                                               \
        type temp = (a);                               \
        (a) = (b);                                     \
        (b) = temp;                                    \
    } while (0)

/*------------------------------------------------------------------
 *  5. #undef — 取消宏定义
 *------------------------------------------------------------------*/


/*------------------------------------------------------------------
 *  主函数
 *------------------------------------------------------------------*/
int main(void)
{
    printf("========================================\n");
    printf("  宏定义 (#define)\n");
    printf("========================================\n\n");

    /*--------------------------------------------------------------
     *  1. 对象宏的使用
     *--------------------------------------------------------------*/
    printf("=== 1. 对象宏 (Object-like Macros) ===\n");
    printf("PI            = %.10f\n", PI);
    printf("TWO_PI        = %.10f\n", TWO_PI);
    printf("MAX_STUDENTS  = %d\n", MAX_STUDENTS);
    printf("SCHOOL_NAME   = %s\n", SCHOOL_NAME);
    printf("\n");

    /*--------------------------------------------------------------
     *  2. 函数宏的使用
     *--------------------------------------------------------------*/
    printf("=== 2. 函数宏 (Function-like Macros) ===\n");

    int a = 5, b = 8;
    printf("SQUARE(%d) = %d\n", a, SQUARE(a));
    printf("MAX(%d, %d) = %d\n", a, b, MAX(a, b));
    printf("MIN(%d, %d) = %d\n", a, b, MIN(a, b));
    printf("ABS(%d) = %d\n", -10, ABS(-10));
    printf("AREA_CIRCLE(%d) = %f\n", 5, AREA_CIRCLE(5));
    printf("\n");

    /* 函数宏对不同类型都适用 — 无类型检查 */
    printf("SQUARE(3.5) = %f (浮点数也可以)\n", SQUARE(3.5));
    printf("MAX('A', 'Z') = '%c' (字符也可以)\n", MAX('A', 'Z'));
    printf("\n");

    /*--------------------------------------------------------------
     *  3. 括号陷阱演示
     *--------------------------------------------------------------*/
    printf("=== 3. 缺少括号的陷阱 ===\n");

    int x = 3;

    /* 正确的宏 */
    printf("SQUARE(x + 1)   = %d  (正确: ((3+1)*(3+1)) = 16)\n",
           SQUARE(x + 1));

    /* 错误的宏: 没有加括号 */
    printf("SQUARE_BAD(x+1) = %d  (错误: (3+1*3+1) = 7)\n",
           SQUARE_BAD(x + 1));

    /* 另一个例子: DOUBLE_BAD */
    printf("5 * DOUBLE_BAD(3) = %d   (期望: 30, 实际: 5*3+3 = 18)\n",
           5 * DOUBLE_BAD(3));
    printf("5 * (DOUBLE_BAD(3)) 正确写法应产生: 5 * (3+3) = 30\n");

    printf("\n结论: 宏参数和整个表达式都必须加括号! 这是最重要的规则\n\n");

    /*--------------------------------------------------------------
     *  4. 参数副作用陷阱
     *--------------------------------------------------------------*/
    printf("=== 4. 参数多次求值的副作用 ===\n");

    int i = 5, j = 8;
    printf("i = %d, j = %d\n", i, j);
    int maxVal = MAX_EVAL(i++, j++);
    printf("MAX_EVAL(i++, j++) = %d\n", maxVal);
    printf("i = %d, j = %d (递增了两次! 副作用!)\n", i, j);
    printf("解释: 宏展开为 ((i++) > (j++) ? (i++) : (j++))\n");
    printf("      条件中 i 和 j 各递增一次, 结果表达式中又递增一次!\n");
    printf("      这是函数宏最常见的陷阱之一\n\n");

    /*--------------------------------------------------------------
     *  5. 多行宏的使用
     *--------------------------------------------------------------*/
    printf("=== 5. 多行宏 (反斜杠续行) ===\n");

    DEBUG_PRINT("当前值 a = %d", a);
    DEBUG_PRINT("当前值 b = %d", b);

    /* 使用 SWAP 宏交换 */
    printf("\n交换前: a = %d, b = %d\n", a, b);
    SWAP(a, b, int);
    printf("交换后: a = %d, b = %d\n", a, b);

    /* 也可以交换其他类型 */
    double da = 1.5, db = 9.8;
    printf("\ndouble 交换前: da = %.1f, db = %.1f\n", da, db);
    SWAP(da, db, double);
    printf("double 交换后: da = %.1f, db = %.1f\n", da, db);
    printf("\n");

    /*--------------------------------------------------------------
     *  6. #undef — 取消宏定义
     *--------------------------------------------------------------*/
    printf("=== 6. #undef — 取消宏定义 ===\n");

    printf("MAX_STUDENTS = %d\n", MAX_STUDENTS);

    /* 取消宏定义 */
    #undef MAX_STUDENTS

    /* 如果现在使用 MAX_STUDENTS, 会编译错误 */
    /* printf("MAX_STUDENTS = %d\n", MAX_STUDENTS);  // 取消注释会报错! */

    /* 可以重新定义 */
    #define MAX_STUDENTS 100
    printf("重新定义后 MAX_STUDENTS = %d\n", MAX_STUDENTS);
    printf("\n");

    /*--------------------------------------------------------------
     *  7. 宏与函数的对比
     *--------------------------------------------------------------*/
    printf("=== 7. 宏 vs 函数 ===\n");
    printf(" 宏的优势: 无类型限制, 无调用开销, 可处理参数类型不确定的操作\n");
    printf(" 宏的劣势: 无类型检查, 多次求值副作用, 代码膨胀, 不易调试\n");
    printf(" 建议: 简单操作用宏, 复杂逻辑用函数\n");
    printf("       C99 起 inline 函数可替代大部分函数宏\n");

    return 0;
}
