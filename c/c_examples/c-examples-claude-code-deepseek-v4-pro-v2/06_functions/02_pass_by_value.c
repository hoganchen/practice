/**
 * ============================================================
 * 知识点: 传值调用 (Pass by Value)
 * ============================================================
 *
 * 【编译指令】
 *   gcc 02_pass_by_value.c -o 02_pass_by_value.exe -std=c11 -Wall
 *
 * 【运行指令】
 *   ./02_pass_by_value.exe
 *
 * 【知识点概述】
 *   C 语言中，函数参数总是通过"传值"（pass by value）方式传递。
 *   这意味着函数接收的是实参的副本，而不是实参本身。
 *   因此，函数内部对参数的修改不会影响调用者的原始变量。
 *   如果需要修改调用者的变量，必须使用指针（后续章节会介绍）。
 * ============================================================
 */

#include "../common/charset.h"
#include <stdio.h>

// =============================================================
// 函数声明
// =============================================================

/*
 * 尝试交换两个整数的值
 * 注意：由于 C 是传值调用，这个函数实际上无法交换外部的变量！
 */
void swap_fail(int a, int b);

/*
 * 演示函数参数是实参的副本
 * 函数内部修改参数值，不影响调用者
 */
void try_to_modify(int x);

/*
 * 演示数组参数的特殊性
 * 数组名作为参数时，传递的是数组首元素的地址（模拟传引用）
 */
void modify_array_element(int arr[], int index, int new_value);

/*
 * 演示结构体作为参数时也是传值
 */
struct Point {
    int x;
    int y;
};

void modify_point(struct Point p);

/*
 * 演示传值调用过程中副本与原始变量的关系
 */
void increment_with_copy(int n);

/**
 * 主函数
 */
int main(void)
{
    printf("========================================\n");
    printf("  传值调用 (Pass by Value) 示例\n");
    printf("========================================\n\n");

    // ---------------------------------------------------------
    // 示例 1: 基本类型传值 —— 修改无效
    // ---------------------------------------------------------
    printf("【示例 1】int 传值 —— 函数内修改不影响外部\n");

    int num = 10;
    printf("  调用前: num = %d\n", num);

    try_to_modify(num);  // 传递的是 num 的副本

    printf("  调用后: num = %d\n", num);
    printf("  结论: num 的值没有改变！\n\n");

    // ---------------------------------------------------------
    // 示例 2: 经典的交换失败案例
    // ---------------------------------------------------------
    printf("【示例 2】交换函数 —— 为什么不能成功交换？\n");

    int x = 5;
    int y = 10;

    printf("  调用 swap_fail 前: x = %d, y = %d\n", x, y);

    swap_fail(x, y);  // 传递的是 x 和 y 的副本

    printf("  调用 swap_fail 后: x = %d, y = %d\n", x, y);
    printf("  结论: 交换没有生效！因为函数交换的是副本。\n\n");

    // ---------------------------------------------------------
    // 示例 3: 传值过程的详细图解
    // ---------------------------------------------------------
    printf("【示例 3】传值调用过程详解\n");

    int original = 100;
    printf("  原始变量 original 的地址: %p, 值: %d\n",
           (void*)&original, original);

    printf("  调用函数 increment_with_copy(original)...\n");
    increment_with_copy(original);

    printf("  调用后 original 的值: %d (未改变)\n", original);
    printf("\n");

    // ---------------------------------------------------------
    // 示例 4: 数组参数的特殊性
    // 数组名作为参数时传递的是首元素地址（不是整个数组的副本）
    // ---------------------------------------------------------
    printf("【示例 4】数组作为参数 —— 地址传递\n");

    int my_array[] = {10, 20, 30, 40, 50};
    int array_size = sizeof(my_array) / sizeof(my_array[0]);

    printf("  修改前: ");
    for (int i = 0; i < array_size; i++) {
        printf("%d ", my_array[i]);
    }
    printf("\n");

    // 修改数组的元素
    modify_array_element(my_array, 2, 999);  // 将下标为 2 的元素改为 999

    printf("  修改后: ");
    for (int i = 0; i < array_size; i++) {
        printf("%d ", my_array[i]);
    }
    printf("\n");

    printf("  注意：数组元素被成功修改了！\n");
    printf("  原因：数组作为参数传递的是地址（模拟了传引用）\n\n");

    // ---------------------------------------------------------
    // 示例 5: 结构体传值
    // ---------------------------------------------------------
    printf("【示例 5】结构体作为参数 —— 也是传值\n");

    struct Point p1 = {10, 20};
    printf("  调用 modify_point 前: p1 = (%d, %d)\n", p1.x, p1.y);

    modify_point(p1);  // 结构体整体传值（副本）

    printf("  调用 modify_point 后: p1 = (%d, %d)\n", p1.x, p1.y);
    printf("  结论：结构体也是传值，副本的修改不影响原始变量\n\n");

    // ---------------------------------------------------------
    // 示例 6: 传值调用的优点
    // ---------------------------------------------------------
    printf("【示例 6】传值调用的优点\n");
    printf("  1. 数据安全：函数无法意外修改调用者的数据\n");
    printf("  2. 无副作用：函数行为更可预测，便于调试\n");
    printf("  3. 表达式透明：函数参数可以是任意表达式\n");
    printf("  4. 支持常量实参：如 add(5, 3) 中的 5 和 3\n");
    printf("\n");

    // ---------------------------------------------------------
    // 对比：用指针实现真正的交换（提前预览）
    // ---------------------------------------------------------
    printf("========================================\n");
    printf("  附加: 用指针实现真正的交换（后续知识点预览）\n");
    printf("========================================\n\n");

    printf("  指针可以解决传值调用无法修改外部变量的问题：\n");
    printf("  将在后续章节（指针）中详细介绍。\n\n");

    printf("========================================\n");
    printf("  传值调用要点总结:\n\n");
    printf("  1. C 语言函数参数总是传值\n");
    printf("  2. 函数操作的是实参的副本\n");
    printf("  3. 修改副本不影响原始变量\n");
    printf("  4. 数组名作为参数时传递的是地址\n");
    printf("  5. 结构体也是传值（复制整个结构体）\n");
    printf("  6. 传值保证了数据的安全性和函数的纯度\n");
    printf("========================================\n");

    return 0;
}

// =============================================================
// 函数实现
// =============================================================

/**
 * swap_fail - 尝试交换两个整数（失败版）
 * @a: 第一个整数（副本）
 * @b: 第二个整数（副本）
 *
 * 此函数交换的是 a 和 b 的副本，不影响调用者中的原始变量。
 */
void swap_fail(int a, int b)
{
    printf("  进入 swap_fail 函数:\n");
    printf("    传入的 a = %d, b = %d\n", a, b);

    // 交换 a 和 b（只对副本有效）
    int temp = a;
    a = b;
    b = temp;

    printf("    交换后 a = %d, b = %d\n", a, b);
    printf("  离开 swap_fail 函数（局部变量 a、b 将被销毁）\n");
}

/**
 * try_to_modify - 尝试修改参数的值
 * @x: 整数（副本）
 *
 * 函数内部修改 x，但此修改不会影响调用者中的原始变量。
 * 当函数返回时，参数 x 这个副本被销毁。
 */
void try_to_modify(int x)
{
    printf("  进入 try_to_modify: 参数 x 的初始值 = %d\n", x);
    printf("  参数 x 的地址: %p\n", (void*)&x);

    // 修改 x 的值（只修改了副本）
    x = 999;

    printf("  修改后 x = %d\n", x);
    printf("  离开 try_to_modify。局部变量 x 即将被销毁。\n");
}

/**
 * increment_with_copy - 演示传值过程
 * @n: 整数副本
 */
void increment_with_copy(int n)
{
    printf("  函数 increment_with_copy 收到参数 n:\n");
    printf("    n 的地址: %p（与 original 地址不同！）\n", (void*)&n);
    printf("    n 的值: %d\n", n);

    n++;  // 只修改了副本

    printf("    n++ 后: %d\n", n);
    printf("  函数返回，n 被销毁。\n\n");
}

/**
 * modify_array_element - 修改数组中的元素
 * @arr: 数组名（传递的是首元素地址）
 * @index: 要修改的下标
 * @new_value: 新值
 *
 * 注意：虽然数组名传递的是地址，但在函数内部 arr 仍然是传值！
 * arr 是一个指针变量，它存储了数组第一个元素的地址。
 * 通过 arr[index] 实际上是修改了原始数组的内存。
 */
void modify_array_element(int arr[], int index, int new_value)
{
    // arr 是一个指针变量，它被初始化为 my_array 的首地址
    printf("  函数内 arr 的地址（指针变量本身）: %p\n", (void*)&arr);
    printf("  arr 存储的地址（指向数组首元素）: %p\n", (void*)arr);

    printf("  修改 arr[%d] 从 %d 改为 %d\n",
           index, arr[index], new_value);

    arr[index] = new_value;  // 通过地址修改了原始数组
    printf("  修改成功！\n");
}

/**
 * modify_point - 尝试修改结构体
 * @p: Point 结构体（副本）
 *
 * 结构体作为参数时也是传值，修改不影响原始变量。
 */
void modify_point(struct Point p)
{
    printf("  函数内修改结构体成员...\n");
    p.x = 999;  // 只修改了副本
    p.y = 888;  // 只修改了副本
    printf("  修改后副本的值为: (%d, %d)\n", p.x, p.y);
    printf("  函数返回，结构体副本被销毁。\n");
}
