/**
 * ============================================================
 *  知识点: 结构体基础 (Structure Basics)
 *
 *  编译指令: gcc 01_struct_basics.c -o 01_struct_basics.exe -std=c11 -Wall
 *  运行指令: ./01_struct_basics.exe
 *
 *  本文件演示:
 *    1. struct 定义与 typedef 简化类型名
 *    2. 使用点运算符 (.) 访问成员
 *    3. 结构体的初始化方式（普通初始化、指定初始化器 C99）
 *    4. 结构体的赋值（整体拷贝）
 * ============================================================
 */

#include "../common/charset.h"
#include <stdio.h>
#include <string.h>

/*------------------------------------------------------------------
 *  方式一: 直接定义 struct 类型
 *  关键字 struct 后面跟着标记名 Student, 使用时必须写 struct Student
 *------------------------------------------------------------------*/
struct Student {
    int    id;        /* 学生学号 */
    char   name[50];  /* 学生姓名 */
    float  score;     /* 学生成绩 */
};  /* 注意分号不能省略 */

/*------------------------------------------------------------------
 *  方式二: 使用 typedef 为结构体起别名
 *  这样定义后, 可以直接用 Point 声明变量, 无需写 struct Point
 *------------------------------------------------------------------*/
typedef struct {
    double x;   /* X 坐标 */
    double y;   /* Y 坐标 */
} Point;

/*------------------------------------------------------------------
 *  方式三: 定义结构体时同时使用 typedef
 *  结构体标记名是可选的, 这里保留标记名以便后续自引用
 *------------------------------------------------------------------*/
typedef struct Book {
    char    title[100];   /* 书名 */
    char    author[50];   /* 作者 */
    int     year;         /* 出版年份 */
    double  price;        /* 价格 */
} Book;  /* 现在 Book 等价于 struct Book */

/*------------------------------------------------------------------
 *  主函数
 *------------------------------------------------------------------*/
int main(void)
{
    printf("========================================\n");
    printf("  结构体基础 (Structure Basics)\n");
    printf("========================================\n\n");

    /*--------------------------------------------------------------
     *  1. 结构体变量的声明与初始化
     *
     *  方法 A: 声明后逐个成员赋值
     *--------------------------------------------------------------*/
    struct Student stu1;              /* 声明一个 Student 结构体变量 */
    stu1.id    = 1001;                /* 给 id 成员赋值 */
    strcpy(stu1.name, "张三");        /* 字符串需要使用 strcpy */
    stu1.score = 92.5f;               /* 给 score 成员赋值 */

    printf("--- 逐个成员赋值 ---\n");
    printf("学号: %d\n",   stu1.id);
    printf("姓名: %s\n",   stu1.name);
    printf("成绩: %.1f\n", stu1.score);
    printf("\n");

    /*--------------------------------------------------------------
     *  方法 B: 初始化列表, 按成员声明顺序初始化
     *  注意: 如果提供的值少于成员数, 剩余成员会被零初始化
     *--------------------------------------------------------------*/
    struct Student stu2 = { 1002, "李四", 88.0f };

    printf("--- 初始化列表 ---\n");
    printf("学号: %d\n",   stu2.id);
    printf("姓名: %s\n",   stu2.name);
    printf("成绩: %.1f\n", stu2.score);
    printf("\n");

    /*--------------------------------------------------------------
     *  方法 C: 指定初始化器 (Designated Initializers, C99 起支持)
     *  可以按任意顺序初始化指定的成员
     *  未指定的成员会被零初始化
     *--------------------------------------------------------------*/
    struct Student stu3 = {
        .score = 95.5f,
        .name  = "王五",
        .id    = 1003
    };

    printf("--- 指定初始化器 (Designated Initializers) ---\n");
    printf("学号: %d\n",   stu3.id);
    printf("姓名: %s\n",   stu3.name);
    printf("成绩: %.1f\n", stu3.score);
    printf("\n");

    /*--------------------------------------------------------------
     *  2. 使用 typedef 定义的结构体
     *  无需写 struct 关键字, 更简洁
     *--------------------------------------------------------------*/
    Point p1 = { 3.5, 7.2 };     /* 初始化二维坐标 */
    Point p2;                     /* 声明但不初始化 */

    /* 逐个赋值 */
    p2.x = 10.0;
    p2.y = 20.0;

    printf("--- typedef 结构体 Point ---\n");
    printf("p1: (%.1f, %.1f)\n", p1.x, p1.y);
    printf("p2: (%.1f, %.1f)\n", p2.x, p2.y);
    printf("\n");

    /*--------------------------------------------------------------
     *  3. 结构体的赋值 —— 整体拷贝
     *  结构体变量之间可以直接用 = 赋值, 编译器会逐字节拷贝
     *--------------------------------------------------------------*/
    struct Student stu4;
    stu4 = stu1;  /* 将 stu1 的所有成员逐字节赋值给 stu4 */

    printf("--- 结构体整体赋值 (拷贝) ---\n");
    printf("stu4 (拷贝自 stu1):\n");
    printf("学号: %d\n",   stu4.id);
    printf("姓名: %s\n",   stu4.name);
    printf("成绩: %.1f\n", stu4.score);
    printf("\n");

    /* 修改 stu1 验证是深拷贝还是浅拷贝 */
    stu1.score = 60.0f;
    printf("修改 stu1.score 为 %.1f 后, stu4.score 仍为 %.1f (互不影响)\n",
           stu1.score, stu4.score);
    printf("说明: 结构体赋值是深拷贝, 每个成员独立复制\n");
    printf("\n");

    /*--------------------------------------------------------------
     *  4. Book 结构体 —— 带 typedef 的结构体标记名
     *--------------------------------------------------------------*/
    Book book1 = {
        .title  = "C程序设计语言",
        .author = "Brian W. Kernighan / Dennis M. Ritchie",
        .year   = 1978,
        .price  = 59.00
    };

    printf("--- Book 结构体 ---\n");
    printf("书名:   %s\n",   book1.title);
    printf("作者:   %s\n",   book1.author);
    printf("年份:   %d\n",   book1.year);
    printf("价格:   %.2f 元\n", book1.price);

    return 0;
}
