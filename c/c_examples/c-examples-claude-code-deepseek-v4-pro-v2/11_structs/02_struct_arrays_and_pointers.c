/**
 * ============================================================
 *  知识点: 结构体数组与指针 (Arrays of Structs and Pointers to Structs)
 *
 *  编译指令: gcc 02_struct_arrays_and_pointers.c -o 02_struct_arrays_and_pointers.exe -std=c11 -Wall
 *  运行指令: ./02_struct_arrays_and_pointers.exe
 *
 *  本文件演示:
 *    1. 结构体数组的定义与遍历
 *    2. 指向结构体的指针, 箭头运算符 (->)
 *    3. 结构体作为函数参数 (传值 vs 传指针)
 *    4. 从函数返回结构体
 * ============================================================
 */

#include "../common/charset.h"
#include <stdio.h>
#include <string.h>

/*------------------------------------------------------------------
 *  定义 Student 结构体, 用于演示数组、指针、传参等操作
 *------------------------------------------------------------------*/
typedef struct {
    int    id;              /* 学生学号 */
    char   name[50];        /* 学生姓名 */
    float  score;           /* 学生成绩 */
} Student;

/*------------------------------------------------------------------
 *  函数声明 (具体实现在 main 函数之后)
 *------------------------------------------------------------------*/

/* 传值: 打印一个学生信息 (传入整个结构体副本) */
void printStudentByValue(Student s);

/* 传指针: 打印一个学生信息 (传入结构体指针) */
void printStudentByPtr(const Student *ps);

/* 传指针: 修改学生成绩 (通过指针修改原结构体) */
void updateScore(Student *ps, float newScore);

/* 返回结构体: 创建一个新的 Student 并返回 */
Student createStudent(int id, const char *name, float score);

/* 遍历打印整个学生数组 */
void printAllStudents(const Student arr[], int count);

/*------------------------------------------------------------------
 *  主函数
 *------------------------------------------------------------------*/
int main(void)
{
    printf("========================================\n");
    printf("  结构体数组与指针\n");
    printf("========================================\n\n");

    /*--------------------------------------------------------------
     *  1. 结构体数组 (Array of Structs)
     *--------------------------------------------------------------*/

    /* 声明并初始化一个 Student 数组, 包含 3 名学生 */
    Student class[3] = {
        { 1001, "张三", 92.5f },
        { 1002, "李四", 88.0f },
        { 1003, "王五", 95.5f }
    };

    printf("--- 结构体数组初始化与遍历 ---\n");
    for (int i = 0; i < 3; i++) {
        /* 使用点运算符访问数组成员的字段 */
        printf("class[%d]: 学号=%d, 姓名=%s, 成绩=%.1f\n",
               i, class[i].id, class[i].name, class[i].score);
    }
    printf("\n");

    /*--------------------------------------------------------------
     *  2. 指向结构体的指针 (Pointer to Struct)
     *  使用箭头运算符 (->) 通过指针访问成员
     *--------------------------------------------------------------*/

    /* 声明一个指向 Student 的指针, 指向数组的第一个元素 */
    Student *ptr = &class[0];

    printf("--- 指向结构体的指针与箭头运算符 ---\n");
    /* 通过指针打印第一个学生信息 */
    printf("ptr->id    = %d\n",    ptr->id);
    printf("ptr->name  = %s\n",    ptr->name);
    printf("ptr->score = %.1f\n",  ptr->score);

    /* 指针算术: ptr + 1 会自动跳过一个 Student 的大小 */
    printf("\n使用指针算术遍历数组:\n");
    for (Student *p = class; p < class + 3; p++) {
        printf("学号=%d, 姓名=%s, 成绩=%.1f\n",
               p->id, p->name, p->score);
    }
    printf("\n");

    /*--------------------------------------------------------------
     *  3. 传值 vs 传指针
     *
     *  传值 (pass by value):
     *    - 函数接收的是结构体的"副本"
     *    - 函数内修改不影响原结构体
     *    - 适合小的结构体或只读场景
     *
     *  传指针 (pass by pointer):
     *    - 函数接收的是结构体的"地址"
     *    - 函数内可以通过指针修改原结构体
     *    - 效率更高 (只传递 4/8 字节的地址, 而非整个结构体拷贝)
     *--------------------------------------------------------------*/

    printf("--- 传值调用: printStudentByValue ---\n");
    printStudentByValue(class[0]);   /* 传递整个结构体的副本 */
    printf("(传值: 函数内无法修改原结构体)\n\n");

    printf("--- 传指针调用: printStudentByPtr ---\n");
    printStudentByPtr(&class[0]);    /* 传递结构体的地址 */
    printf("(传指针: 高效, 只传递地址)\n\n");

    printf("--- 传指针修改成绩 ---\n");
    printf("修改前: class[1].score = %.1f\n", class[1].score);
    updateScore(&class[1], 99.0f);   /* 通过指针修改原结构体 */
    printf("修改后: class[1].score = %.1f\n", class[1].score);
    printf("\n");

    /*--------------------------------------------------------------
     *  4. 从函数返回结构体
     *  函数返回结构体是合法的, 返回的是整个结构体的副本
     *--------------------------------------------------------------*/

    printf("--- 返回结构体 ---\n");
    Student newStu = createStudent(2001, "赵六", 87.5f);
    printStudentByValue(newStu);
    printf("\n");

    /*--------------------------------------------------------------
     *  5. 综合示例: 使用函数遍历结构体数组
     *--------------------------------------------------------------*/
    printf("--- 调用函数遍历整个数组 ---\n");
    printAllStudents(class, 3);

    return 0;
}


/* =================================================================
 *  函数实现
 * ================================================================= */

/*------------------------------------------------------------------
 *  printStudentByValue: 传值方式打印结构体
 *  参数 s 是整个结构体的副本, 修改它不会影响原结构体
 *------------------------------------------------------------------*/
void printStudentByValue(Student s)
{
    printf("  [传值] 学号=%d, 姓名=%s, 成绩=%.1f\n",
           s.id, s.name, s.score);

    /* 修改副本不影响原结构体 */
    s.score = 0.0f;   /* 这行不会影响 main 中的原结构体 */
}

/*------------------------------------------------------------------
 *  printStudentByPtr: 传指针方式打印结构体
 *  参数 ps 是指向结构体的指针
 *  使用 const 修饰表示只读, 函数不会修改结构体内容
 *------------------------------------------------------------------*/
void printStudentByPtr(const Student *ps)
{
    /* 使用箭头运算符 (->) 通过指针访问成员 */
    printf("  [传指针] 学号=%d, 姓名=%s, 成绩=%.1f\n",
           ps->id, ps->name, ps->score);
}

/*------------------------------------------------------------------
 *  updateScore: 通过指针修改结构体成员
 *  参数 ps 是指向目标结构体的指针
 *------------------------------------------------------------------*/
void updateScore(Student *ps, float newScore)
{
    ps->score = newScore;  /* 通过指针修改原结构体 */
}

/*------------------------------------------------------------------
 *  createStudent: 创建一个新的 Student 并返回
 *  返回整个结构体, 调用者接收副本
 *------------------------------------------------------------------*/
Student createStudent(int id, const char *name, float score)
{
    Student s;
    s.id = id;
    strncpy(s.name, name, sizeof(s.name) - 1);
    s.name[sizeof(s.name) - 1] = '\0'; /* 确保字符串以 '\0' 结尾 */
    s.score = score;
    return s;  /* 返回结构体的副本 */
}

/*------------------------------------------------------------------
 *  printAllStudents: 遍历打印整个结构体数组
 *  参数 arr 是数组首地址 (传指针), count 是元素个数
 *------------------------------------------------------------------*/
void printAllStudents(const Student arr[], int count)
{
    for (int i = 0; i < count; i++) {
        printf("  [%d] 学号=%d, 姓名=%s, 成绩=%.1f\n",
               i, arr[i].id, arr[i].name, arr[i].score);
    }
}
