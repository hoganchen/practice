/*
 * ============================================================
 *  知识点: 运算符优先级与结合性
 *
 *  本文件覆盖以下核心概念:
 *    1. C语言运算符优先级表（从高到低）
 *    2. 结合性（左结合 vs 右结合）
 *    3. 使用优先级导致的常见误解
 *    4. 使用括号明确表达式的求值顺序
 *
 *  编译指令:
 *    gcc 04_operator_precedence.c -o 04_operator_precedence.exe -std=c11 -Wall
 *
 *  运行指令:
 *    ./04_operator_precedence.exe
 * ============================================================
 */

#include "../common/charset.h"
#include <stdio.h>

int main(void)
{
    printf("========================================\n");
    printf("   运算符优先级与结合性\n");
    printf("========================================\n\n");

    /*
     * ============================================
     *  1. 优先级概览（从高到低）
     * ============================================
     *
     *  优先级  运算符              说明                  结合性
     *  ----------------------------------------------------------
     *   最高   () [] -> .          括号/数组/成员访问    左→右
     *         ! ~ ++ -- + - * &   单目运算符            右→左
     *         (type) sizeof
     *         * / %               乘除取模              左→右
     *         + -                 加减                  左→右
     *         << >>               移位                  左→右
     *         < <= > >=           关系比较              左→右
     *         == !=               相等比较              左→右
     *         &                   按位与                左→右
     *         ^                   按位异或              左→右
     *         |                   按位或                左→右
     *         &&                  逻辑与                左→右
     *         ||                  逻辑或                左→右
     *         ?:                  三元条件              右→左
     *         = += -= *= /= 等    赋值                  右→左
     *   最低   ,                   逗号                  左→右
     *
     *  重要原则: 如果对优先级不确定，使用括号 () 明确意图！
     *  清晰的代码比简洁的代码更重要。
     */
    printf("===== 1. 优先级概览 =====\n");
    printf("（详细表见代码注释）\n\n");
    printf("黄金法则: 不确定时加括号！\n\n");

    /*
     * ============================================
     *  2. 算术运算符优先级
     * ============================================
     *
     *  * / % 优先级高于 + -
     *  与数学中的"先乘除后加减"一致
     */
    printf("===== 2. 算术运算符优先级 =====\n");

    /* 演示: 先乘除后加减 */
    int result1 = 2 + 3 * 4;    /* 3 * 4 先计算，再加 2 */
    printf("2 + 3 * 4 = %d （先算乘法 3*4=12，再加 2）\n", result1);

    /* 使用括号改变优先级 */
    int result2 = (2 + 3) * 4;  /* 先算括号内的加法 */
    printf("(2 + 3) * 4 = %d （先算加法 2+3=5，再乘 4）\n\n", result2);

    /*
     * ============================================
     *  3. 赋值与比较的优先级
     * ============================================
     *
     *  关系运算符（==、!= 等）优先级高于赋值运算符（=）
     *  但低于算术运算符
     */
    printf("===== 3. 赋值与比较的优先级 =====\n");

    int a = 5, b = 10;
    int flag;

    /* 如下的表达式等价于 flag = (a == b) */
    flag = a == b;           /* 先比较 a == b（结果为 0），再赋值 */
    printf("flag = a == b: flag = %d （先比较 a==b 再赋值）\n", flag);

    /* 常见错误: 想在条件中先赋值再比较，但忘了括号 */
    int x = 0;
    /* if (x = 5 != 0) */   /* 这实际上是: x = (5 != 0) => x = 1 */
    if ((x = 5) != 0)       /* 先赋值 x=5，再比较 x!=0 */
    {
        printf("(x = 5) != 0 为真，x = %d\n\n", x);
    }

    /*
     * ============================================
     *  4. 逻辑运算符的优先级
     * ============================================
     *
     *  ! > && > ||
     *  关系运算符（< > == 等）优先级高于 && 和 ||
     */
    printf("===== 4. 逻辑运算符优先级 =====\n");

    int age = 25;
    int has_ticket = 1;     /* 1 表示有票 */
    int is_vip = 0;         /* 0 表示不是 VIP */

    /*
     * 不加括号的版本 —— 依赖默认优先级
     * age >= 18 && has_ticket || is_vip
     * 等价于: (age >= 18 && has_ticket) || is_vip
     * 因为 && 优先级高于 ||
     */
    int can_enter = age >= 18 && has_ticket || is_vip;
    printf("age=%d, ticket=%d, vip=%d\n", age, has_ticket, is_vip);
    printf("can_enter = age>=18 && has_ticket || is_vip\n");
    printf("等价于: (age>=18 && has_ticket) || is_vip\n");
    printf("结果: %d\n\n", can_enter);

    /* 推荐: 使用括号明确表达意图，即使知道优先级 */
    int can_enter_clear = (age >= 18) && (has_ticket || is_vip);
    printf("使用括号明确意图: (age>=18) && (has_ticket || is_vip)\n");
    printf("结果: %d\n\n", can_enter_clear);

    /* ! 优先级高于 && 和 || */
    int valid = 1;
    printf("!valid && has_ticket = %d\n", !valid && has_ticket);
    printf("等价于: (!valid) && has_ticket\n\n");

    /*
     * ============================================
     *  5. 移位与算术的优先级
     * ============================================
     *
     *  算术运算符优先级高于移位运算符
     *  所以 1 << 2 + 3 实际上是 1 << (2+3) = 1 << 5 = 32
     */
    printf("===== 5. 移位与算术优先级 =====\n");

    int shift_val = 1 << 2 + 3;     /* 先算 2+3=5，再左移 5 位 */
    printf("1 << 2 + 3 = %d （先算加法 2+3=5，再左移）\n", shift_val);

    int shift_val2 = (1 << 2) + 3;  /* 先移位再加 */
    printf("(1 << 2) + 3 = %d （括号确保先移位）\n\n", shift_val2);

    /*
     * ============================================
     *  6. 结合性（Associativity）
     * ============================================
     *
     *  结合性决定了当多个运算符具有相同优先级时的求值顺序。
     *
     *  左结合（Left-to-right）: 从左向右求值
     *    例如: a - b - c = (a - b) - c
     *
     *  右结合（Right-to-left）: 从右向左求值
     *    例如: a = b = c   = a = (b = c)
     *         三元运算符: a ? b : c ? d : e = a ? b : (c ? d : e)
     */
    printf("===== 6. 结合性 =====\n");

    /* 左结合示例: 减法 */
    int sub = 100 - 30 - 20;         /* (100 - 30) - 20 = 50 */
    printf("100 - 30 - 20 = %d （左结合: (100-30)-20）\n", sub);

    /* 右结合示例: 赋值 */
    int p, q, r;
    p = q = r = 10;                 /* p = (q = (r = 10)) */
    printf("p = q = r = 10: p=%d, q=%d, r=%d （右结合）\n", p, q, r);

    /* 三元运算符的右结合 */
    int score = 75;
    const char *grade = score >= 90 ? "优秀"
                      : score >= 80 ? "良好"
                      : score >= 70 ? "中等"
                      : score >= 60 ? "及格"
                      : "不及格";
    /*
     * 上面等价于:
     * score >= 90 ? "优秀" : (score >= 80 ? "良好" : (...))
     * 右结合使得链式 ?: 能够正常工作
     */
    printf("score=%d, 等级=%s\n\n", score, grade);

    /*
     * ============================================
     *  7. 逗号运算符
     * ============================================
     *
     *  逗号运算符的优先级最低。
     *  表达式 expr1, expr2 会依次求值 expr1 和 expr2，
     *  整个表达式的值是 expr2 的值。
     */
    printf("===== 7. 逗号运算符 =====\n");

    int comma_result;
    int a1 = 1, a2 = 2, a3 = 3, a4 = 4, a5 = 5;
    comma_result = (a1, a2, a3, a4, a5);     /* 括号中的逗号是逗号运算符 */
    printf("(a1, a2, a3, a4, a5) = %d （逗号表达式取最后一个值）\n", comma_result);

    /* 逗号运算符优先级低于赋值 */
    int comma_val;
    int v1 = 1, v2 = 2, v3 = 3;
    comma_val = (v1, v2, v3);      /* 等价于: comma_val = (v1, v2, v3) => comma_val = 3 */
    printf("comma_val = (v1, v2, v3) 的结果: comma_val = %d (逗号表达式的值是最后一个)\n", comma_val);

    /* 演示逗号运算符的优先级 */
    int w1 = 1, w2 = 2, w3 = 3;
    int comma_low;
    comma_low = w1, w2, w3;       /* 等价于: (comma_low = w1), w2, w3 */
    printf("comma_low = w1, w2, w3 的结果: comma_low = %d (赋值优先级高于逗号，所以先赋值 w1)\n", comma_low);

    /* 正确的用法：在 for 循环中使用逗号表达式 */
    printf("for 循环中的逗号表达式:\n");
    for (int i = 0, j = 10; i < j; i++, j--)
    {
        printf("  i=%d, j=%d\n", i, j);
    }

    printf("\n");

    /*
     * ============================================
     *  8. 综合案例 —— 分析复杂表达式
     * ============================================
     */
    printf("===== 8. 复杂表达式分析 =====\n");

    int i = 1, j = 2, k = 3;
    int tricky;

    /*
     * 分析以下表达式:
     *   tricky = ++i && j++ || ++k
     *
     * 优先级:  && 高于 ||
     * 结合性:  && 和 || 都是左结合
     * 短路求值:  && 和 || 都有短路行为
     *
     * 求值步骤:
     *   1. ++i => i=2 (真)
     *   2. j++ => 先取 j=2 (真)，然后 j=3
     *   3. ++i && j++ => 真 && 真 => 真
     *   4. || 的左侧为真，短路，不执行 ++k
     *   5. k 保持为 3
     */
    tricky = ++i && j++ || ++k;
    printf("表达式: tricky = ++i && j++ || ++k\n");
    printf("结果:   tricky = %d, i=%d, j=%d, k=%d\n", tricky, i, j, k);
    printf("解释: i=2(真), j++ 返回 2(真), && => 真, || 短路 → k 不变\n\n");

    /*
     * 另一个常见陷阱 —— 指针解引用与自增的优先级
     * *p++ 等价于 *(p++) —— 后缀 ++ 优先级高于 *
     */
    int arr[] = {10, 20, 30};
    int *ptr = arr;
    printf("数组: arr = {10, 20, 30}\n");
    printf("*ptr++ = %d （先解引用 *ptr，然后 ptr++）\n", *ptr++);
    printf("此时 ptr 指向: %d\n\n", *ptr);

    /*
     * ============================================
     *  9. 总结
     * ============================================
     */
    printf("===== 9. 总结与建议 =====\n");
    printf("1. 记住基本优先级: ! > 算术 > 关系 > 逻辑 > 赋值\n");
    printf("2. 移位和算术: 移位优先级低于算术\n");
    printf("3. 不确定时加括号 ()，使代码意图清晰\n");
    printf("4. 不要写过于复杂的表达式，一行只做一件事\n");
    printf("5. 在代码评审中，依赖优先级 vs 加括号是一个常见的讨论点\n");
    printf("   大多数团队规范推荐: 用括号明确非显而易见的优先级\n");

    return 0;
}
