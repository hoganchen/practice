/*
 * ============================================================
 *  知识点: 算术运算符与逻辑运算符
 *
 *  本文件覆盖以下核心概念:
 *    1. 算术运算符: +（加）、-（减）、*（乘）、/（除）、%（取模）
 *    2. 逻辑运算符: &&（与）、||（或）、!（非）
 *    3. 短路求值（Short-circuit Evaluation）
 *    4. 整数除法与浮点数除法的区别
 *    5. 自增自减运算符: ++、--
 *
 *  编译指令:
 *    gcc 01_arithmetic_logical_ops.c -o 01_arithmetic_logical_ops.exe -std=c11 -Wall
 *
 *  运行指令:
 *    ./01_arithmetic_logical_ops.exe
 * ============================================================
 */

#include "../common/charset.h"
#include <stdio.h>

int main(void)
{
    printf("========================================\n");
    printf("    算术运算符与逻辑运算符\n");
    printf("========================================\n\n");

    /*
     * ============================================
     *  1. 算术运算符（Arithmetic Operators）
     * ============================================
     *
     *  运算符  名称      示例        说明
     *  +       加法      a + b      两数相加
     *  -       减法      a - b      两数相减
     *  *       乘法      a * b      两数相乘
     *  /       除法      a / b      两数相除（整数/浮点行为不同）
     *  %       取模      a % b      a 除以 b 的余数（仅适用于整数）
     */
    printf("===== 1. 算术运算符 =====\n");

    int a = 17, b = 5;

    printf("a = %d, b = %d\n", a, b);
    printf("a + b = %d (加法)\n", a + b);
    printf("a - b = %d (减法)\n", a - b);
    printf("a * b = %d (乘法)\n", a * b);
    printf("a / b = %d (整数除法，结果截断为整数)\n", a / b);
    printf("a %% b = %d (取模余数)\n\n", a % b);  /* %% 输出一个 % */

    /*
     * ============================================
     *  2. 整数除法 vs 浮点数除法
     * ============================================
     *
     *  两个整数相除，结果仍是整数（小数部分被截断，不是四舍五入）!
     *  只要有一个操作数是浮点数，结果就是浮点数。
     */
    printf("===== 2. 整数除法 vs 浮点数除法 =====\n");

    int x = 10, y = 3;
    printf("%d / %d = %d (整数除法)\n", x, y, x / y);
    printf("%d / %d = %.2f (强制转换为 double)\n\n", x, y, (double)x / y);

    /*
     * 取模运算符 % 的特性:
     *   - 只适用于整数类型（int、short、long 等）
     *   - 不能用于 float 或 double
     *   - 结果的符号与被除数相同
     */
    printf("取模运算的符号:\n");
    printf(" 17 %%  5 = %d\n", 17 % 5);
    printf(" 17 %% -5 = %d (结果符号与被除数相同)\n", 17 % -5);
    printf("-17 %%  5 = %d\n", -17 % 5);
    printf("-17 %% -5 = %d\n\n", -17 % -5);

    /*
     * ============================================
     *  3. 自增与自减运算符（++ / --）
     * ============================================
     *
     *  ++ 使变量加 1，-- 使变量减 1。
     *
     *  前缀形式（++a）: 先加 1，再使用新值
     *  后缀形式（a++）: 先使用旧值，再加 1
     */
    printf("===== 3. 自增与自减运算符 =====\n");

    int count = 10;
    printf("初始值 count = %d\n", count);

    /* 后缀自增 */
    int result1 = count++;
    printf("后缀 count++: 先返回 %d，然后 count 变为 %d\n", result1, count);

    /* 前缀自增 */
    count = 10;     /* 重置 */
    int result2 = ++count;
    printf("前缀 ++count: 先自增为 %d，然后返回 %d\n\n", count, result2);

    /*
     * ============================================
     *  4. 逻辑运算符（Logical Operators）
     * ============================================
     *
     *  运算符  名称    示例         说明
     *  &&      逻辑与  a && b      两者都为真才为真
     *  ||      逻辑或  a || b      至少一个为真即为真
     *  !       逻辑非  !a          取反（真变假，假变真）
     *
     *  在 C 语言中:
     *    0 表示"假"（false）
     *    非 0 值表示"真"（true）
     *    逻辑运算的结果是 int 类型: 1（真）或 0（假）
     */
    printf("===== 4. 逻辑运算符 =====\n");

    int p = 1, q = 0;       /* 1 表示真，0 表示假 */

    printf("p = %d (真), q = %d (假)\n", p, q);
    printf("p && q = %d (逻辑与: 真 && 假 = 假)\n", p && q);
    printf("p || q = %d (逻辑或: 真 || 假 = 真)\n", p || q);
    printf("!p = %d, !q = %d (逻辑非)\n\n", !p, !q);

    /*
     * ============================================
     *  5. 短路求值（Short-circuit Evaluation）
     * ============================================
     *
     *  && 和 || 采用"短路求值"策略:
     *    - a && b: 如果 a 为假，就不再求值 b（因为结果必定为假）
     *    - a || b: 如果 a 为真，就不再求值 b（因为结果必定为真）
     *
     *  短路求值非常重要，可以用来:
     *    - 避免空指针解引用: if (ptr != NULL && *ptr == value)
     *    - 避免除零: if (b != 0 && a / b > 0)
     */
    printf("===== 5. 短路求值 =====\n");

    int divisor = 0;
    int quotient;

    /* 安全除法 —— 利用短路求值避免除零 */
    if (divisor != 0 && (quotient = 10 / divisor) > 0)
    {
        printf("结果是 %d\n", quotient);
    }
    else
    {
        /*
         * 因为 divisor == 0，所以 divisor != 0 为假，
         * && 短路，不执行 10 / divisor，避免了除零错误
         */
        printf("除数不能为 0 （短路求值避免了除零错误）\n");
    }

    /* 短路求值副作用演示 */
    int i = 0, j = 0;

    /* || 的短路: i 为 0（假），所以 j++ 会被执行 */
    int short1 = (i != 0) || (j++);      /* j++ 被执行 */
    (void)short1;
    printf("短路 ||: i = %d, j = %d (j++ 被执行)\n", i, j);

    i = 0; j = 0;
    int short2 = (i == 0) || (j++);      /* i 为 0（真），j++ 被短路！ */
    (void)short2;
    printf("短路 ||: i = %d, j = %d (j++ 被短路)\n\n", i, j);

    /*
     * ============================================
     *  6. 组合示例
     * ============================================
     */
    printf("===== 6. 综合示例 =====\n");

    int year = 2024;

    /* 判断闰年: 能被 4 整除但不能被 100 整除，或者能被 400 整除 */
    int is_leap = (year % 4 == 0 && year % 100 != 0) || (year % 400 == 0);
    printf("%d 年%s闰年\n", year, is_leap ? "是" : "不是");

    /* 判断一个数是否在范围内 */
    int score = 85;
    int pass = (score >= 60) && (score <= 100);
    printf("分数 %d 是否及格且有效: %s\n", score, pass ? "是" : "否");

    /* 使用 ! 简化条件 */
    int found = 0;      /* 0 表示未找到 */
    if (!found)         /* 等价于 found == 0 */
    {
        printf("未找到记录，正在搜索...\n");
    }

    return 0;
}
