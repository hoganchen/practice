/*
 * ============================================================
 *  知识点: 格式说明符（Format Specifiers）
 *
 *  本文件覆盖以下核心概念:
 *    1. 整数格式: %d、%i、%u、%x/%X、%o
 *    2. 浮点格式: %f、%lf、%e/%E、%g/%G
 *    3. 字符与字符串: %c、%s
 *    4. 指针格式: %p
 *    5. 宽度与精度控制: %5d、%5.2f、%-10s
 *
 *  编译指令:
 *    gcc 03_format_specifiers.c -o 03_format_specifiers.exe -std=c11 -Wall
 *
 *  运行指令:
 *    ./03_format_specifiers.exe
 * ============================================================
 */

#include "../common/charset.h"
#include <stdio.h>

int main(void)
{
    int a = 42;
    int b = -255;
    unsigned int u = 3000000000U;   /* 无符号整数，注意 U 后缀 */
    double pi = 3.14159265358979;
    float f = 2.71828f;
    char ch = 'Z';
    const char *str = "Hello, C Language!";

    printf("========================================\n");
    printf("    格式说明符（Format Specifiers）\n");
    printf("========================================\n\n");

    /*
     * ============================================
     *  1. 整数格式说明符
     * ============================================
     *
     *  %d   —— 十进制有符号整数（decimal）
     *  %i   —— 十进制有符号整数（与 %d 相同，但 scanf 中不同）
     *  %u   —— 十进制无符号整数（unsigned）
     *  %x   —— 十六进制小写（hexadecimal, lowercase）
     *  %X   —— 十六进制大写（hexadecimal, UPPERCASE）
     *  %o   —— 八进制（octal）
     *  %hd  —— short int
     *  %ld  —— long int
     *  %lld —— long long int
     */
    printf("===== 1. 整数格式说明符 =====\n");
    printf("a = %d (十进制)\n", a);
    printf("a = %i (%%i，也是十进制)\n", a);
    printf("a = %x (十六进制小写)\n", a);
    printf("a = %X (十六进制大写)\n", a);
    printf("a = %o (八进制)\n", a);
    printf("b = %d (负数十进制)\n", b);
    printf("b = %X (负数十六进制，补码表示)\n", b);
    printf("u = %u (无符号十进制)\n", u);
    printf("u = %#x (带 0x 前缀的十六进制)\n", u);
    printf("u = %#o (带 0 前缀的八进制)\n\n", u);

    /*
     * ============================================
     *  2. 浮点格式说明符
     * ============================================
     *
     *  %f   —— 十进制小数形式（float/double）
     *  %lf  —— 与 %f 相同，printf 中 %f 和 %lf 效果一样
     *  %e   —— 科学计数法小写（exponential, e.g. 3.14e+00）
     *  %E   —— 科学计数法大写（e.g. 3.14E+00）
     *  %g   —— 自动选择 %f 或 %e（取较短者）
     *  %G   —— 自动选择 %f 或 %E
     *  %Lf  —— long double 类型
     */
    printf("===== 2. 浮点格式说明符 =====\n");
    printf("pi = %f (默认 %%f, 6位小数)\n", pi);
    printf("pi = %.10f (%.10f, 10位小数)\n", pi, pi);
    printf("pi = %e (科学计数法小写)\n", pi);
    printf("pi = %E (科学计数法大写)\n", pi);
    printf("pi = %g (自动选择格式)\n", pi);
    printf("f  = %f (float 类型)\n\n", f);

    /*
     * ============================================
     *  3. 字符与字符串格式说明符
     * ============================================
     *
     *  %c   —— 单个字符（character）
     *  %s   —— 字符串（string，以 \0 结尾的字符数组）
     */
    printf("===== 3. 字符与字符串 =====\n");
    printf("ch = %c (字符)\n", ch);
    printf("ch = %d (字符的 ASCII 码)\n", ch);
    printf("ch = 0x%X (字符的 ASCII 码，十六进制)\n", ch);
    printf("str = %s (字符串)\n\n", str);

    /*
     * ============================================
     *  4. 指针格式说明符
     * ============================================
     *
     *  %p   —— 指针地址（pointer），以十六进制显示
     *  输出格式因平台而异，通常为 0xXXXXXXXX
     */
    printf("===== 4. 指针格式 =====\n");
    printf("变量 a 的地址: %p\n", (void*)&a);
    printf("字符串 str 的地址: %p\n", (void*)str);
    printf("main 函数的地址: %p\n\n", (void*)main);

    /*
     * ============================================
     *  5. 宽度（Width）与精度（Precision）
     * ============================================
     *
     *  语法: %[标志][宽度][.精度][长度]格式
     *
     *  宽度: 最小字段宽度
     *    如果实际值比宽度短，默认右对齐并用空格填充
     *    如果实际值比宽度长，则按实际宽度输出
     *
     *  精度:
     *    对于整数: 最小数字位数（不足补零）
     *    对于浮点数: 小数点后的位数
     *    对于字符串: 最大字符数
     *
     *  标志:
     *    -  —— 左对齐（默认右对齐）
     *    +  —— 总是显示正负号
     *    空格 —— 正数前显示空格
     *    0  —— 用零填充（仅数字）
     *    #  —— 显示前缀（0x、0 等）
     */
    printf("===== 5. 宽度与精度控制 =====\n");

    /* 宽度控制 */
    printf("宽度控制:\n");
    printf("|%d|\n", 42);              /* 无宽度 */
    printf("|%5d|\n", 42);             /* 宽度5，右对齐 */
    printf("|%-5d|\n", 42);            /* 宽度5，左对齐 */
    printf("|%05d|\n", 42);            /* 宽度5，左补零 */

    /* 浮点数宽度和精度 */
    printf("\n浮点数宽度和精度:\n");
    printf("|%f|\n", pi);              /* 默认 6 位小数 */
    printf("|%.2f|\n", pi);            /* 保留 2 位小数 */
    printf("|%8.2f|\n", pi);           /* 宽度 8，2 位小数，右对齐 */
    printf("|%-8.2f|\n", pi);          /* 宽度 8，2 位小数，左对齐 */
    printf("|%010.2f|\n", pi);         /* 宽度 10，2 位小数，左补零 */
    printf("|%+8.2f|\n", pi);          /* 显示正负号 */
    printf("|%+8.2f|\n", -pi);         /* 负数显示负号 */

    /* 字符串宽度 */
    printf("\n字符串宽度:\n");
    printf("|%s|\n", str);             /* 原样输出 */
    printf("|%30s|\n", str);           /* 宽度 30，右对齐 */
    printf("|%-30s|\n", str);          /* 宽度 30，左对齐 */
    printf("|%.5s|\n", str);           /* 最多显示 5 个字符 */
    printf("|%20.5s|\n", str);         /* 宽度 20，最多 5 字符 */

    /* 整数宽度和精度 */
    printf("\n整数宽度和精度:\n");
    printf("|%d|\n", 255);
    printf("|%8d|\n", 255);
    printf("|%.8d|\n", 255);           /* 精度 8，至少 8 位数字 */
    printf("|%08d|\n", 255);           /* 等价效果 */

    /*
     * ============================================
     *  6. 特殊格式 —— %% 输出 % 本身
     * ============================================
     */
    printf("\n===== 6. 特殊格式 =====\n");
    printf("百分号: 100%%\n");          /* %% 输出一个百分号 */

    return 0;
}
