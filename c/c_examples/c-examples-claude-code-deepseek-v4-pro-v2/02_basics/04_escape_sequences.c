/**
 * ============================================================
 * 知识点: 转义序列 (Escape Sequences)
 *
 * 转义序列是以反斜杠 \ 开头的字符组合,用于表示无法直接输入
 * 或具有特殊含义的字符。C语言中的转义序列在编译时被替换为
 * 对应的实际字符值。
 *
 * 常用转义序列:
 *   \n  - 换行符 (newline)         - 0x0A
 *   \t  - 水平制表符 (tab)          - 0x09
 *   \r  - 回车符 (carriage return)  - 0x0D
 *   \\  - 反斜杠本身                - 0x5C
 *   \"  - 双引号                    - 0x22
 *   \'  - 单引号                    - 0x27
 *   \0  - 空字符 (null)             - 0x00
 *   \xNN - 十六进制转义              - 0xNN
 *   \NNN - 八进制转义                - 0NNN (最多三位八进制)
 *   \a  - 响铃 (alert/bell)         - 0x07
 *   \b  - 退格 (backspace)          - 0x08
 *   \f  - 换页 (form feed)          - 0x0C
 *   \v  - 垂直制表符 (vertical tab)  - 0x0B
 *
 * 编译指令:
 *   gcc 04_escape_sequences.c -o 04_escape_sequences.exe -std=c11 -Wall
 * 运行:
 *   ./04_escape_sequences.exe
 * ============================================================
 */

#include "../common/charset.h"
#include <stdio.h>
#include <string.h>

int main(void)
{
    printf("========================================\n");
    printf("  C语言转义序列演示 (Escape Sequences)\n");
    printf("========================================\n\n");

    /* ---------- 1. 换行符 \n ---------- */
    printf("【1】换行符 \\n : 将光标移动到下一行开头\n");
    printf("第一行\n第二行\n第三行\n\n");

    /* ---------- 2. 水平制表符 \t ---------- */
    printf("【2】水平制表符 \\t : 跳到下一个制表位(通常每8列一个)\n");
    printf("姓名\t年龄\t城市\n");
    printf("张三\t25\t北京\n");
    printf("李四\t30\t上海\n");
    printf("王五\t28\t广州\n\n");

    /* ---------- 3. 回车符 \r ---------- */
    printf("【3】回车符 \\r : 将光标移动到当前行开头(不换行)\n");
    printf("这行文字会被覆盖\r---前面被覆盖了---\n\n");

    /* ---------- 4. 反斜杠 \\ ---------- */
    printf("【4】反斜杠 \\\\ : 输出反斜杠字符本身\n");
    printf("文件路径: C:\\\\Users\\\\example\\\\file.txt\n");
    printf("反斜杠示例: \\\\n 表示字符 \\ 后跟 n,而不是换行\n\n");

    /* ---------- 5. 双引号 \" ---------- */
    printf("【5】双引号 \\\" : 在字符串中嵌入双引号\n");
    printf("他说: \"你好,世界!\"\n");
    printf("双引号转义: \\\"这个字符串被引号包围\\\"\n\n");

    /* ---------- 6. 单引号 \' ---------- */
    printf("【6】单引号 \\' : 在字符常量中表示单引号\n");
    char quote_char = '\'';
    printf("单引号字符: %c\n", quote_char);
    printf("字符常量示例: char c = '\\'';\n\n");

    /* ---------- 7. 空字符 \0 ---------- */
    printf("【7】空字符 \\0 : 字符串结束标志(ASCII码0)\n");
    char str_with_null[] = "Hello\0World";
    printf("字符串 \"Hello\\0World\" 通过 %%s 输出: \"%s\"\n", str_with_null);
    printf("说明: \\0 之后的字符不会被 %%s 打印,字符串在 \\0 处结束\n");
    /* 验证字符串长度 */
    printf("strlen(str_with_null) = %zu (在 \\0 处停止计数)\n\n", strlen(str_with_null));

    /* ---------- 8. 十六进制转义 \xNN ---------- */
    printf("【8】十六进制转义 \\xNN : 使用十六进制值表示字符\n");
    /* \x41 = 0x41 = 65 = 'A' */
    char hex_a = '\x41';
    /* \x48\x65\x6C\x6C\x6F = "Hello" */
    printf("\\x41 = %c\n", hex_a);
    printf("\\x48\\x65\\x6C\\x6C\\x6F = \"%c%c%c%c%c\"\n\n",
           '\x48', '\x65', '\x6C', '\x6C', '\x6F');

    /* ---------- 9. 八进制转义 \NNN ---------- */
    printf("【9】八进制转义 \\NNN : 使用八进制值表示字符(最多三位)\n");
    /* \101 = 八进制101 = 十进制65 = 'A' */
    char oct_a = '\101';
    /* \112\141\163\157\156 = "Jason" */
    printf("\\101 = %c\n", oct_a);
    printf("\\112\\141\\163\\157\\156 = \"%c%c%c%c%c\"\n\n",
           '\112', '\141', '\163', '\157', '\156');

    /* ---------- 10. 响铃符 \a ---------- */
    printf("【10】响铃符 \\a : 触发系统提示音(终端蜂鸣)\n");
    printf("听到一声提示音了吗? \a\n\n");

    /* ---------- 11. 退格符 \b ---------- */
    printf("【11】退格符 \\b : 光标向左移动一个位置\n");
    printf("12345\b\b\bXY\n");
    printf("解释: 输出12345后,退格3次,再输出XY,结果为12XY5\n\n");

    /* ---------- 12. 综合示例 ---------- */
    printf("========= 综合示例 =========\n");
    /* 使用多种转义序列构建一个格式化的输出 */
    printf("+------------------+------+--------+\n");
    printf("| 商品\\t\\t| 数量 | 价格\\t|\n");
    printf("+------------------+------+--------+\n");
    printf("| 苹果\\t\\t| 10\\t| \\$5.00 |\n");
    printf("| 香蕉\\t\\t| 20\\t| \\$3.50 |\n");
    printf("| 橙子\\t\\t| 15\\t| \\$4.00 |\n");
    printf("+------------------+------+--------+\n");

    /* 演示 \0 在字符数组中的应用 */
    char name[] = {'J', 'a', 's', 'o', 'n', '\0'};
    printf("\n通过字符数组构造的字符串: %s\n", name);

    return 0;
}
