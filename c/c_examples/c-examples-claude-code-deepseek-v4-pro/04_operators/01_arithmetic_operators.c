/*
 * ============================================
 * 知识点：算术运算符
 * 说明：
 *   C语言的基本算术运算符：
 *   +  加法
 *   -  减法
 *   *  乘法
 *   /  除法（注意整型除法的截断行为）
 *   %  取模（求余数，只能用于整型）
 *   ++ 自增（加1）
 *   -- 自减（减1）
 *
 * 编译方法：
 *   gcc 01_arithmetic_operators.c -o 01_arithmetic_operators
 * ============================================
 */

#include <stdio.h>
#include "../utf8fix.h"

int main() {
    int a = 10, b = 3;

    // ========== 基本算术运算 ==========
    printf("===== 基本算术运算 =====\n");
    printf("a = %d, b = %d\n\n", a, b);

    printf("加法: a + b = %d\n", a + b);     // 10 + 3 = 13
    printf("减法: a - b = %d\n", a - b);     // 10 - 3 = 7
    printf("乘法: a * b = %d\n", a * b);     // 10 * 3 = 30

    // 整型除法：结果截断小数部分
    printf("除法: a / b = %d (整型除法截断小数)\n", a / b);  // 3

    // 取模运算：求余数
    printf("取模: a %% b = %d\n", a % b);    // 10 % 3 = 1
    // 注意：在printf中，%% 才能输出单个 %

    // ========== 整型除法 vs 浮点除法 ==========
    printf("\n===== 除法详解 =====\n");

    int   int_div = 10 / 3;            // 整型除法，结果截断
    float float_div = 10.0f / 3.0f;    // 浮点除法
    double mix_div = 10 / 3.0;         // 混合类型：自动转为double

    printf("10 / 3     (整型)     = %d\n", int_div);
    printf("10.0 / 3.0 (浮点)     = %f\n", float_div);
    printf("10 / 3.0   (混合)     = %lf\n", mix_div);

    // 类型转换：将 int 转为 float 再做除法
    printf("(float)10 / 3 = %f\n", (float)10 / 3);

    // ========== 取模的细节 ==========
    printf("\n===== 取模运算细节 =====\n");
    printf("10 %% 3 = %d\n", 10 % 3);
    printf("-10 %% 3 = %d\n", -10 % 3);     // 结果符号与被除数相同
    printf("10 %% -3 = %d\n", 10 % -3);

    // 取模的应用：判断奇偶
    int num = 7;
    if (num % 2 == 0) {
        printf("%d 是偶数\n", num);
    } else {
        printf("%d 是奇数\n", num);
    }

    // ========== 自增自减运算符 ==========
    printf("\n===== 自增与自减 =====\n");
    int x = 5;

    printf("初始: x = %d\n", x);

    // 前置自增：先加1，再使用
    printf("++x 的值: %d (前置自增)\n", ++x);  // x先变为6，再输出
    printf("现在 x = %d\n", x);

    // 后置自增：先使用，再加1
    x = 5;  // 重置
    printf("x++ 的值: %d (后置自增)\n", x++);  // 先输出5，x再变为6
    printf("现在 x = %d\n", x);

    // 自减同理
    printf("\n自减演示:\n");
    int y = 10;
    printf("--y = %d (前置自减)\n", --y);   // 9
    y = 10;
    printf("y-- = %d (后置自减)\n", y--);   // 10，然后y变为9
    printf("现在 y = %d\n", y);

    // ========== 复合赋值运算符 ==========
    printf("\n===== 复合赋值运算符 =====\n");
    int z = 10;

    z += 5;   // 等价于 z = z + 5
    printf("z += 5   => z = %d\n", z);

    z -= 3;   // 等价于 z = z - 3
    printf("z -= 3   => z = %d\n", z);

    z *= 2;   // 等价于 z = z * 2
    printf("z *= 2   => z = %d\n", z);

    z /= 4;   // 等价于 z = z / 4
    printf("z /= 4   => z = %d\n", z);

    z %= 3;   // 等价于 z = z % 3
    printf("z %%= 3   => z = %d\n", z);

    // ========== 运算符优先级 ==========
    printf("\n===== 运算符优先级 =====\n");
    // 乘除 > 加减，括号可以改变优先级
    int result = 3 + 4 * 2;            // 4*2先算 = 8, +3 = 11
    printf("3 + 4 * 2 = %d (乘法优先级更高)\n", result);

    result = (3 + 4) * 2;              // 括号优先
    printf("(3 + 4) * 2 = %d (括号优先)\n", result);

    return 0;
}

/*
 * ============================================
 * 关键点总结：
 *
 * 1. 整型除法截断小数部分
 * 2. 取模 % 只适用于整型
 * 3. ++x 先加后用，x++ 先用后加
 * 4. 复合赋值 x += y 等价于 x = x + y
 * 5. 用括号明确运算优先级
 * ============================================
 */
