/*
 * ============================================
 * 知识点：Hello World — C语言程序入口
 * 说明：
 *   这是C语言中最基础的程序。每个C程序都从
 *   main() 函数开始执行。printf() 用于向控制
 *   台输出文本。
 *
 * 编译方法：
 *   gcc 01_hello_world.c -o 01_hello_world
 * 运行方法：
 *   ./hello_world    (Linux/Mac)
 *   hello_world.exe  (Windows)
 * ============================================
 */

/*
 * #include 是预处理指令，用于引入头文件。
 * stdio.h 是标准输入输出头文件，提供了
 * printf()、scanf() 等函数。
 * 头文件告诉编译器有哪些函数可用。
 */
#include <stdio.h>
#include "../utf8fix.h"

/*
 * main() 是程序的入口函数。
 * 程序总是从 main() 函数的第一行开始执行。
 * int 表示函数返回一个整数值给操作系统。
 * 返回 0 通常表示程序正常结束。
 */
int main() {
    /*
     * printf() 是标准输出函数。
     * 它会将字符串打印到控制台。
     * \n 是转义字符，表示换行（newline）。
     */
    printf("Hello, World!\n");

    /*
     * return 0; 表示程序成功结束。
     * 操作系统会收到这个返回值。
     * 非零返回值通常表示程序异常终止。
     */
    return 0;
}

