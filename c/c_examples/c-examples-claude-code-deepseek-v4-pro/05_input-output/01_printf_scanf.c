/*
 * ============================================
 * 知识点：标准输入输出（printf 和 scanf）
 * 说明：
 *   printf() 用于格式化输出
 *   scanf()  用于格式化输入
 *   它们都使用格式字符串来控制输入输出的格式。
 *
 * 常用格式说明符：
 *   %d   整型        %f   浮点(float)
 *   %lf  双精度浮点   %c   字符
 *   %s   字符串       %p   指针
 *   %x   十六进制     %o   八进制
 *   %zu  size_t
 *
 * 编译方法：
 *   gcc 01_printf_scanf.c -o 01_printf_scanf
 * ============================================
 */

#include <stdio.h>
#include "../utf8fix.h"

int main() {
    // ============================================================
    // 第一部分：printf 格式化输出
    // ============================================================
    printf("========================================\n");
    printf("第一部分：printf 格式化输出\n");
    printf("========================================\n");

    // ---------- 整型输出 ----------
    printf("\n--- 整型输出 ---\n");
    int i = 255;
    printf("十进制: %d\n", i);
    printf("八进制: %o\n", i);
    printf("十六进制(小写): %x\n", i);
    printf("十六进制(大写): %X\n", i);

    // ---------- 浮点输出 ----------
    printf("\n--- 浮点输出 ---\n");
    double pi = 3.1415926535;

    printf("默认: %f\n", pi);
    printf("保留2位小数: %.2f\n", pi);
    printf("保留4位小数: %.4f\n", pi);
    printf("科学计数法: %e\n", pi);
    printf("自动格式: %g\n", 3.14159);  // 自动选择 %f 或 %e

    // 宽度和对齐
    printf("右对齐(宽度10): |%10d|\n", 42);
    printf("左对齐(宽度10): |%-10d|\n", 42);
    printf("补零(宽度8): %08d\n", 123);

    // ---------- 字符和字符串 ----------
    printf("\n--- 字符和字符串 ---\n");
    char ch = 'A';
    char str[] = "Hello, C Language!";

    printf("字符: %c\n", ch);
    printf("ASCII码: %d\n", ch);
    printf("字符串: %s\n", str);
    printf("字符串(前5字符): %.5s\n", str);

    // ---------- 多变量输出 ----------
    printf("\n--- 多变量输出 ---\n");
    char name[] = "张三";
    int age = 25;
    double score = 92.5;

    printf("姓名: %s, 年龄: %d, 成绩: %.1f\n", name, age, score);

    // ============================================================
    // 第二部分：scanf 格式化输入
    // ============================================================
    printf("\n========================================\n");
    printf("第二部分：scanf 格式化输入\n");
    printf("========================================\n");
    printf("(本部分需要交互输入，运行后请输入数据)\n\n");

    // ---------- 输入整数 ----------
    int num;
    printf("请输入一个整数: ");
    // &num 取变量地址，scanf 需要知道存储位置
    int ret = scanf("%d", &num);
    if (ret == 1) {
        // ret = scanf 成功读取的项数
        printf("你输入了: %d\n", num);
    } else {
        printf("输入无效！\n");
        // 清空输入缓冲区
        while (getchar() != '\n');
    }

    // ---------- 输入浮点数 ----------
    double dval;
    printf("请输入一个浮点数: ");
    ret = scanf("%lf", &dval);  // double 用 %lf
    if (ret == 1) {
        printf("你输入了: %.2f\n", dval);
    } else {
        printf("输入无效！\n");
        while (getchar() != '\n');
    }

    // ---------- 输入字符 ----------
    char input_char;
    printf("请输入一个字符: ");
    scanf(" %c", &input_char);  // 注意空格：跳过前导空白字符
    printf("你输入了: '%c' (ASCII: %d)\n", input_char, input_char);

    // ---------- 输入字符串 ----------
    /*
     * 注意：scanf 用 %s 读取字符串时遇到空格会停止。
     * 更安全的读取方式见下方 gets/fgets 替代方案。
     */
    char input_str[50];
    printf("请输入一个字符串（不含空格）: ");
    scanf("%s", input_str);  // 数组名本身就是地址，不需要 &
    printf("你输入了: %s\n", input_str);

    // ---------- 同时输入多个值 ----------
    int a, b;
    printf("请输入两个整数（用空格或回车分隔）: ");
    ret = scanf("%d %d", &a, &b);
    if (ret == 2) {
        printf("a = %d, b = %d, a + b = %d\n", a, b, a + b);
    }

    // ---------- 清空输入缓冲区 ----------
    // 清理 scanf 后留在缓冲区的换行符
    while (getchar() != '\n');

    // ============================================================
    // 第三部分：getchar 和 putchar
    // ============================================================
    printf("\n========================================\n");
    printf("第三部分：getchar 和 putchar\n");
    printf("========================================\n");

    printf("请输入一行文本（按回车结束）:\n");
    char c;
    // getchar() 从 stdin 读取一个字符
    // putchar() 向 stdout 写入一个字符
    while ((c = getchar()) != '\n') {
        // 将小写字母转换为大写
        if (c >= 'a' && c <= 'z') {
            c = c - 32;  // 转大写
        }
        putchar(c);
    }
    putchar('\n');

    printf("\n===== 格式化说明符速查表 =====\n");
    printf("| 说明符 | 类型                      |\n");
    printf("|--------|---------------------------|\n");
    printf("| %%d    | int (有符号十进制)        |\n");
    printf("| %%u    | unsigned int              |\n");
    printf("| %%f    | float/double              |\n");
    printf("| %%lf   | double (scanf 输入用)     |\n");
    printf("| %%c    | char                      |\n");
    printf("| %%s    | 字符串 (char*)            |\n");
    printf("| %%p    | 指针地址                  |\n");
    printf("| %%x/%X | 十六进制                  |\n");
    printf("| %%o    | 八进制                    |\n");
    printf("| %%zu   | size_t                    |\n");
    printf("| %%%%   | 输出一个 %%               |\n");

    return 0;
}

/*
 * ============================================
 * 关键点总结：
 *
 * 1. printf 输出，scanf 输入，都使用格式字符串
 * 2. scanf 需要变量地址（&），但数组名和指针不用
 * 3. scanf 遇到空格/换行会停止读取字符串
 * 4. scanf 的 %s 不安全（不检查缓冲区边界），
 *    生产环境建议使用 fgets()
 * 5. 注意输入缓冲区的换行符残留问题
 * 6. 检查 scanf 返回值确保输入正确
 * ============================================
 */
